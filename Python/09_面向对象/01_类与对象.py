# 【本章小结】
# ==============================================================================
#
# 1. 类 = 把数据和操作数据的方法打包在一起的模具；对象是按模具造出来的实例
# 2. class 类名: 定义类，类名用大驼峰；类体里可以写 pass 占位
# 3. __init__ 是构造方法，创建对象时自动调用，负责给属性赋初值，返回值必须是 None
# 4. self 是「当前这个对象」的引用，Python 调用方法时自动传入，必须写在第一个参数
# 5. 实例属性用 self.xxx 定义，每个对象各有一份，存在各自的 __dict__ 里
# 6. 实例方法第一个参数是 self，因此能读写自己的属性
# 7. 创建对象 = 调用类名加括号：s = Student(...)
# 8. 四大坑：方法忘写 self、创建对象忘写括号、少写一个下划线、访问未定义属性
# 9. 类本身也是对象，type(Student) 是 <class 'type'>


