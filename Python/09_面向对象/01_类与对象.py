# ==============================================================================
# 知识点 1：为什么需要「类」—— 从字典的痛处说起
# ==============================================================================
#
# 假设要管理学生信息。不用类，最自然的写法是用字典：
#
#     student = {"name": "张三", "age": 18, "score": 92}
#
# 但字典有三个天生的短板：
#   1. 键名全靠手打字符串，写成 "nmae" 不会立刻报错，只在运行时 KeyError
#   2. 数据和操作是分开的：「是否及格」得写一个游离在外的函数 is_pass(student)
#   3. 描述不了「学生这个整体」：字典里塞什么字段，全凭自觉
#
# 【重点】类 = 把「数据」和「操作这些数据的方法」打包在一起的模具。
#         模具（类）只有一份，用模具压出来的月饼（对象）可以有很多个。

student1 = {"name": "张三", "score": 92}


def is_pass_dict(student):
    """游离在外的函数：算字典形式的学生是否及格。"""
    return student["score"] >= 60


print("--- 用字典管理学生 ---")
print(f"张三的总分：{student1['score']}，及格：{is_pass_dict(student1)}")

# 输出：
# --- 用字典管理学生 ---
# 张三的总分：92，及格：True
#
# 【注意】字典能存数据，但「及格」这个能力不在字典里，得靠外部的函数。
#         数据传到别处后，你很难知道它当初是「学生」还是「随便一个字典」。


class Student:
    """学生类：有姓名、年龄、分数，并且会自我介绍、会算是否及格。"""

    def __init__(self, name, age, score):
        self.name = name        # 实例属性：姓名
        self.age = age          # 实例属性：年龄
        self.score = score      # 实例属性：分数

    def introduce(self):
        """实例方法：把自己介绍一遍。"""
        print(f"我叫{self.name}，今年{self.age}岁，考了{self.score}分")

    def is_pass(self):
        """实例方法：返回是否及格。"""
        return self.score >= 60


s1 = Student("张三", 18, 92)    # 造出第一个学生对象
s2 = Student("李四", 19, 55)    # 造出第二个学生对象

print("\n--- 用类管理学生 ---")
s1.introduce()
s2.introduce()
print(f"张三及格吗：{s1.is_pass()}")
print(f"李四及格吗：{s2.is_pass()}")

# 输出：
# --- 用类管理学生 ---
# 我叫张三，今年18岁，考了92分
# 我叫李四，今年19岁，考了55分
# 张三及格吗：True
# 李四及格吗：False
#
# 【重点】数据和能力打包在一起后，s1 自己就知道怎么「自我介绍」，
#         不需要外面再传一个函数进去。这就是面向对象的第一层好处：封装。


# ==============================================================================
# 知识点 2：class 定义类 —— 最小的类
# ==============================================================================
#
# 语法：class 类名:  下面跟缩进的类体
#
# 【注意】类名用「大驼峰」：Student、BankAccount、HttpClient。
#         首字母小写的 student 是变量名，不是类名，别人一看就知道你不熟 Python。

class Empty:
    """一个空类。什么内容都没有，但语法完全合法。"""
    pass                # pass 是占位符：这里暂时不写东西，但缩进块不能空着


print("\n--- 类和 type() ---")
print(f"Empty 这个类本身：{Empty}")
print(f"Empty 的类型是：{type(Empty)}")

# 输出：
# --- 类和 type() ---
# Empty 这个类本身：<class '__main__.Empty'>
# Empty 的类型是：<class 'type'>
#
# 【为什么】type(Empty) 是 <class 'type'>，说明「类本身也是对象」——
#         连类都是被别人（元类 type）创建出来的。记住这句话，第 10 章会用到。


# ==============================================================================
# 知识点 3：__init__ 和 self —— 最难懂但也最重要的一节
# ==============================================================================
#
# 【讲解】把类想象成「房产证模板」，对象是「按模板盖出来的一栋栋房子」。
#
#   __init__ 是「盖房时的装修队」：房子一盖好就自动进场，把水电家具装好。
#            你不需要手动喊它，只要你调用 Student(...)，它就会自动执行。
#
#   self     是「装修队手里的房号」：告诉装修队「我现在装的是 3 号楼」。
#            每次操作对象，Python 都会自动把「这个对象」作为第一个参数传进来。
#
# 也就是说：s1.introduce() 实际上等价于 Student.introduce(s1)
#                                       ↑ Python 偷偷把 s1 塞给了 self
#
# 【重点】self 不是关键字，只是约定俗成的名字。写 def introduce(abc) 也能跑，
#         但全世界的 Python 程序员都用 self。所以：永远写 self。


class Dog:
    """狗。演示 __init__ 到底在什么时候被调用。"""

    def __init__(self, name):
        print(f"  [__init__ 被自动调用了] 正在给新狗起名：{name}")
        self.name = name        # 把参数 name 存成自己的属性

    def bark(self):
        print(f"  {self.name}：汪汪！")


print("\n--- 创建对象时发生了什么 ---")
print("准备创建第一只狗：")
d1 = Dog("旺财")
print("准备创建第二只狗：")
d2 = Dog("来福")
print("让它们叫：")
d1.bark()
d2.bark()

# 输出：
# --- 创建对象时发生了什么 ---
# 准备创建第一只狗：
#   [__init__ 被自动调用了] 正在给新狗起名：旺财
# 准备创建第二只狗：
#   [__init__ 被自动调用了] 正在给新狗起名：来福
# 让它们叫：
#   旺财：汪汪！
#   来福：汪汪！
#
# 【注意】__init__ 前后各是「两个下划线」，不是一前一后一个。
#         读作 "dunder init"（double underscore）。手写很容易少写一个，
#         少写的话不报错，但永远不会被调用，属性全都不会存在。


# ==============================================================================
# 知识点 4：实例属性 —— 每个对象各有一份
# ==============================================================================
#
# 【讲解】在 __init__ 里用 self.xxx = ... 创建的，就是「实例属性」。
#
#   实例属性 = 每个对象自己的私有抽屉。
#   张三改了年龄，李四的年龄纹丝不动——因为它们根本不共享抽屉。

p1 = Student("张三", 18, 92)
p2 = Student("李四", 19, 55)

print("\n--- 实例属性互不干扰 ---")
print(f"修改前：p1.age = {p1.age}，p2.age = {p2.age}")
p1.age = 20                                 # 只改 p1 的年龄
print(f"p1.age = {p1.age} 之后，p2.age 还是 {p2.age}")
print(f"p1 的属性字典：{p1.__dict__}")

# 输出：
# --- 实例属性互不干扰 ---
# 修改前：p1.age = 18，p2.age = 19
# p1.age = 20 之后，p2.age 还是 19
# p1 的属性字典：{'name': '张三', 'age': 20, 'score': 92}
#
# 【重点】每个对象内部有一个 __dict__ 字典，存的正是它自己的实例属性。
#         所以 obj.name 读的其实就是 obj.__dict__["name"]。


# ==============================================================================
# 知识点 5：实例方法 —— 能读能改自己属性的函数
# ==============================================================================
#
# 【讲解】定义在类里、第一个参数是 self 的函数，就叫「实例方法」。
#   它和普通函数唯一的区别：能通过 self 摸到自己的属性，如下面 add_score。
#
#   普通函数：  def add(a, b): return a + b
#   实例方法：  def add_score(self, n): self.score += n   ← 靠 self 改自己的分数


class Counter:
    """计数器：演示方法如何修改自己的状态。"""

    def __init__(self):
        self.count = 0          # 初始值 0

    def add(self, n=1):
        """增加 n，默认加 1。"""
        self.count += n
        return self.count       # 返回新值，方便打印

    def reset(self):
        """归零。"""
        self.count = 0

    def show(self):
        print(f"当前计数：{self.count}")


print("\n--- 实例方法修改自身状态 ---")
c = Counter()
c.show()
print(f"add() 返回：{c.add()}")
print(f"add(5) 返回：{c.add(5)}")
c.show()
c.reset()
c.show()

# 输出：
# --- 实例方法修改自身状态 ---
# 当前计数：0
# add() 返回：1
# add(5) 返回：6
# 当前计数：6
# 当前计数：0


# ==============================================================================
# 知识点 6：创建对象（实例化）与「类 vs 对象」
# ==============================================================================
#
# s = Student("张三", 18, 92) 这一行，Python 内部做了三件事：
#
#   第 1 步：创建一个「空对象」（此时还没有 name / age / score）
#   第 2 步：自动调用 __init__(新对象, "张三", 18, 92)，把属性填进去
#   第 3 步：把这个对象赋值给变量 s
#
# 【重点】__init__ 的返回值必须是 None，不能 return 别的东西。
#         它只负责「初始化已有对象」，不负责「创建对象」。

print("\n--- 创建对象的三步 ---")
s3 = Student("王五", 20, 78)
print(f"对象类型：{type(s3)}")
print(f"是 Student 的实例吗：{isinstance(s3, Student)}")
print(f"能读到名字吗：{s3.name}")
print(f"Student 的一个对象：{s1}")
print(f"4 个学生对象共用 1 个类：{type(s1) is type(s2)}")

# 输出：
# --- 创建对象的三步 ---
# 对象类型：<class '__main__.Student'>
# 是 Student 的实例吗：True
# 能读到名字吗：王五
# Student 的一个对象：<__main__.Student object at 0x...>
# 4 个学生对象共用 1 个类：True
#
# 【注意】`<__main__.Student object at 0x...>` 里的地址每次运行都不一样，
#         属于正常的「不确定输出」，不要拿它做比较。想让打印好看，
#         要用第 04 个文件里的 __str__ 魔术方法。


# ==============================================================================
# 知识点 7：新手最容易犯的 4 个错
# ==============================================================================

print("\n--- 常见错误 1：定义方法时忘了写 self ---")


class Bad1:
    def __init__(self, name):
        self.name = name

    def hello():            # 忘了写 self！括号里空空的
        print("hello")


try:
    b = Bad1("小明")
    b.hello()               # 调用时 Python 会传 1 个参数，但函数收 0 个
except TypeError as e:
    print(f"报错：TypeError: {e}")

# 输出：
# --- 常见错误 1：定义方法时忘了写 self ---
# 报错：TypeError: Bad1.hello() takes 0 positional arguments but 1 was given
#
# 【为什么】b.hello() 会被翻译成 Bad1.hello(b)，多塞了一个 b 进去，
#         可你的 hello() 一个参数都不收，于是 Python 抱怨「要 0 个却给了 1 个」。

print("\n--- 常见错误 2：创建对象时忘了写括号 ---")


class Bad2:
    def __init__(self):
        print("我被初始化了")


obj = Bad2               # 少了括号！这里只是把「类」起了个别名 obj
print(f"obj 的类型：{type(obj)}")
print(f"obj 是类本身，不是对象：{obj is Bad2}")

# 输出：
# --- 常见错误 2：创建对象时忘了写括号 ---
# obj 的类型：<class 'type'>
# obj 是类本身，不是对象：True
#
# 【注意】不写括号不会报错！这是最阴险的一点：代码看着能跑，
#         但 obj 指向的是类，不是对象，后面 obj.xxx() 全都会出问题。
#         正确写法是 Bad2()，加了括号才会真正创建对象。

print("\n--- 常见错误 3：__init__ 少写一个下划线 ---")


class Bad3:
    def _init_(self, name):     # 只有一个下划线
        self.name = name


b3 = Bad3()                 # 不带参数可以创建，因为没写 __init__
try:
    print(b3.name)          # 但属性根本没被赋值过
except AttributeError as e:
    print(f"报错：AttributeError: {e}")
try:
    Bad3("张三")            # 带上参数就露馅了
except TypeError as e:
    print(f"带参数创建时：TypeError: {e}")

# 输出：
# --- 常见错误 3：__init__ 少写一个下划线 ---
# 报错：AttributeError: 'Bad3' object has no attribute 'name'
# 带参数创建时：TypeError: Bad3() takes no arguments
#
# 【为什么】_init_ 只是个普通方法，根本不是构造方法，永远不会被自动调用，
#         所以对象建出来时属性压根没赋值。而错误信息里也不会出现
#         「你把 __init__ 拼错了」这句话，全靠自己盯出来。
#
# 【同理】访问任何没定义过的属性（如 Bad4 的 b），报的都是 AttributeError。
#         属性是「用到才创建」的，__init__ 里没写 self.b，b 就不存在。


