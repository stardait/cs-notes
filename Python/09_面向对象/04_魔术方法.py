# 知识点 6：__call__ —— 让对象像函数一样被调用
# ==============================================================================
#
# 【讲解】函数后面加括号是「调用」。对象默认不能这么干，会报
#   TypeError: 'Xxx' object is not callable。定义了 __call__ 之后，
#   对象后面加括号就合法了。
#
# 【为什么有用】这让对象可以「带着状态当函数用」：普通函数每次调用都是
#   重新开始，而可调用对象能记住上次的数据。装饰器、缓存、计数器都靠它。

class Multiplier:
    """带状态的乘法器：记住自己被调用了多少次。"""

    def __init__(self, factor):
        self.factor = factor
        self.call_count = 0         # 每次被调用就 +1

    def __call__(self, x):
        self.call_count += 1
        return x * self.factor


print("\n--- __call__ 让对象像函数 ---")
triple = Multiplier(3)              # 先造一个「乘以 3」的对象
print(f"triple(5) = {triple(5)}        ← 对象后面加括号，合法了")
print(f"triple(10) = {triple(10)}")
print(f"它被调用了 {triple.call_count} 次   ← 状态被记下来了")
print(f"callable(triple) = {callable(triple)}")

# 输出：
# --- __call__ 让对象像函数 ---
# triple(5) = 15        ← 对象后面加括号，合法了
# triple(10) = 30
# 它被调用了 2 次   ← 状态被记下来了
# callable(triple) = True
#
# 【重点】普通函数做不到「记住自己被调用了多少次」，因为函数没有实例状态。
#         可调用对象既能像函数一样用，又能保存状态，这是它的独特价值。

print("\n--- 没定义 __call__ 的对象不能加括号 ---")


class Plain:
    pass


try:
    Plain()()
except TypeError as e:
    print(f"报错：TypeError: {e}")

# 输出：
# --- 没定义 __call__ 的对象不能加括号 ---
# 报错：TypeError: 'Plain' object is not callable


# ==============================================================================
# 知识点 7：常见错误 —— __repr__ 返回了非字符串
# ==============================================================================
#
# 【讲解】__str__ 和 __repr__ 必须返回「字符串」。返回数字、列表都不行，
#   Python 会直接抛 TypeError。这是很多人第一次写魔术方法时踩的坑。

print("\n--- __repr__ 必须返回 str ---")


class BadRepr:
    def __repr__(self):
        return 123                  # 错误示范：返回了整数


try:
    print(BadRepr())
except TypeError as e:
    print(f"报错：TypeError: {e}")

# 输出：
# --- __repr__ 必须返回 str ---
# 报错：TypeError: BadRepr.__str__() must return a str, not int
#
# 【为什么】print() 会先把对象转成字符串。它没有 __str__ 可用，
#         于是退而用 __repr__，可你返回的是整数 123，没法当字符串输出。
#         改成 return "123" 就好了。注意这里报的方法名是 __str__。

