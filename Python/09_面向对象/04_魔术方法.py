# ==============================================================================
# 知识点 1：魔术方法是什么 —— 被「运算符」自动触发的方法
# ==============================================================================
#
# 【讲解】魔术方法就是名字前后各带两个下划线的方法，比如 __str__、__len__。
#   你几乎不会直接调用它们，而是「做某个动作时，Python 自动帮你调」。
#   print(x) 内部其实在调 str(x)，而 str(x) 又会去找 x.__str__()。
#   你定义了它，打印就按你的来。
#
# 【重点】魔术方法 = 给「内置操作」留的钩子。想让对象支持某个操作，
#         就去实现对应的魔术方法。
#
#   常用对照表：
#     操作              Python 实际调用        你该实现
#     ----------------  ---------------------  ----------------
#     print(obj)        str(obj)               __str__
#     直接看 obj        repr(obj)              __repr__
#     obj1 == obj2      obj1.__eq__(obj2)      __eq__
#     obj1 < obj2       obj1.__lt__(obj2)      __lt__
#     len(obj)          obj.__len__()          __len__
#     obj[0]            obj.__getitem__(0)     __getitem__
#     obj(1, 2)         obj.__call__(1, 2)     __call__
#
# 【注意】魔术方法不要自己手动调用！写 str(obj) 而不是 obj.__str__()。

print("--- 连 int 都有一堆魔术方法 ---")
print(f"3 + 5 实际调用的是：{(3).__add__(5)}")
print(f"len('hello') 实际调用的是：{'hello'.__len__()}")
print(f"'a' * 3 实际调用的是：{'a'.__mul__(3)}")

# 输出：
# --- 连 int 都有一堆魔术方法 ---
# 3 + 5 实际调用的是：8
# len('hello') 实际调用的是：5
# 'a' * 3 实际调用的是：aaa
#
# 【重点】+ 号是 __add__，len() 是 __len__，* 是 __mul__。这些类型都是
#         「普通对象」，只是实现了对应的魔术方法而已 —— 你写的类也能做到。


# ==============================================================================
# 知识点 2：__str__ 和 __repr__ —— 打印得好看
# ==============================================================================
#
# 【讲解】不定义这两个方法时，打印对象只会看到一串内存地址
#   <__main__.Money object at 0x0000023A...>，对调试毫无帮助。
#   两个方法的分工是：
#
#   __str__ ：给「人」看的，面向最终用户。print(obj) 和 f"{obj}" 用它。
#   __repr__ ：给「程序员」看的，面向调试。在列表里、交互式环境里用它。
#
# 【重点】__repr__ 的官方建议：最好能「看起来像创建它的代码」，
#         比如 Money(50)，调试时一眼就知道是什么、怎么造出来的。
#
# 【兜底规则】只写了 __repr__ 没写 __str__ 时，print 会退而用 __repr__；
#             反过来不成立（只写 __str__ 时，列表里仍然显示地址）。

class Money:
    def __init__(self, amount):
        self.amount = amount

    def __str__(self):
        """给用户看：50 元。"""
        return f"{self.amount} 元"

    def __repr__(self):
        """给程序员看：像构造代码。"""
        return f"Money({self.amount})"


m = Money(50)
print("\n--- __str__ 与 __repr__ ---")
print(m)                        # print 用 __str__
print(f"{m}")                   # f-string 也用 __str__
print(repr(m))                  # repr() 用 __repr__
print([m, Money(20)])           # 列表里显示用 __repr__

# 输出：
# --- __str__ 与 __repr__ ---
# 50 元
# 50 元
# Money(50)
# [Money(50), Money(20)]
#
# 【重点】注意最后一行：列表里显示的是 Money(50) 而不是 50 元。
#         因为容器内部用的是 __repr__。这就是两者分工会被感知到的地方。
#
# 【常见错误】只写了 __str__，然后发现打印列表还是地址。补上 __repr__ 就好。


# ==============================================================================
# 知识点 3：__eq__ —— 让对象能「等于」
# ==============================================================================
#
# 【讲解】默认的 == 比较的是「是不是同一个对象」（等同于 is）。
#   两个内容相同的 Money(50) 用 == 比默认是 False，因为它们在内存的不同位置。
#   定义了 __eq__ 后，== 就按你写的规则来比。
#
# 【注意】__eq__ 返回 NotImplemented（不是 raise NotImplementedError！）
#   表示「我不会比这个类型」，Python 会再尝试对方的 __eq__，
#   最后兜底用 is 比较，结果就是 False。

class Point:
    def __init__(self, x, y):
        self.x = x
        self.y = y

    def __eq__(self, other):
        """只有当对方也是 Point 时才比较坐标。"""
        if not isinstance(other, Point):
            return NotImplemented     # 交给 Python 兜底，别硬比
        return self.x == other.x and self.y == other.y

    def __repr__(self):
        return f"Point({self.x}, {self.y})"


print("\n--- __eq__ 让内容相同的对象相等 ---")
p1 = Point(1, 2)
p2 = Point(1, 2)
p3 = Point(3, 4)
print(f"p1 == p2：{p1 == p2}     ← 坐标一样，判等成功")
print(f"p1 == p3：{p1 == p3}")
print(f"p1 == (1, 2)：{p1 == (1, 2)}   ← 类型不同，兜底为 False")
print(f"p1 is p2：{p1 is p2}     ← is 比的是「同一个对象」")
print(f"p1 != p3：{p1 != p3}     ← 没写 __ne__，Python 自动取反")

# 输出：
# --- __eq__ 让内容相同的对象相等 ---
# p1 == p2：True     ← 坐标一样，判等成功
# p1 == p3：False
# p1 == (1, 2)：False   ← 类型不同，兜底为 False
# p1 is p2：False     ← is 比的是「同一个对象」
# p1 != p3：True     ← 没写 __ne__，Python 自动取反
#
# 【重点】== 比「内容」，is 比「身份」，这是新手最常混淆的一对。
# 【坑】定义了 __eq__ 后对象会变成「不可哈希」，不能放进 set 或当字典键。
#      需要的话同时定义 __hash__（通常写 return hash((self.x, self.y))）。


# ==============================================================================
# 知识点 4：__lt__ —— 让对象能比较大小、能排序
# ==============================================================================
#
# 【讲解】sorted()、max()、min() 在比较两个元素时，会调用 < 运算符，
#   也就是左边的 __lt__。所以你只要实现 __lt__，对象就能排序。
#
# 【重点】只需要实现 __lt__，sorted 就能工作。想支持 > 也可以顺手写 __gt__，
#         但如果只是想「排序」，__lt__ 一个就够了。

class Student:
    def __init__(self, name, score):
        self.name = name
        self.score = score

    def __lt__(self, other):
        """按分数从小到大排。"""
        return self.score < other.score

    def __repr__(self):
        return f"{self.name}({self.score})"


print("\n--- __lt__ 让对象能排序 ---")
students = [Student("张三", 92), Student("李四", 55), Student("王五", 78)]
print(f"原始顺序：{students}")
print(f"按分数排：{sorted(students)}")
print(f"最高分：{max(students)}")

# 输出：
# --- __lt__ 让对象能排序 ---
# 原始顺序：[张三(92), 李四(55), 王五(78)]
# 按分数排：[李四(55), 王五(78), 张三(92)]
# 最高分：张三(92)
#
# 【重点】sorted 内部不断做「a < b」的判断，每次都调你写的 __lt__。
#         所以排序规则完全由你决定：想按名字排就比 self.name。

print("\n--- 同一批数据，换个排序规则 ---")
print(f"按姓名排：{sorted(students, key=lambda s: s.name)}")

# 输出：
# --- 同一批数据，换个排序规则 ---
# 按姓名排：[张三(92), 李四(55), 王五(78)]
#
# 【注意】「按姓名排」的结果和原始顺序一样，是巧合：张三 < 李四 < 王五 恰好
#         就是拼音顺序。
# 【重点】如果排序规则经常变，用 key 参数比改 __lt__ 更灵活——
#         不用动类，传给 sorted 就行。而且 key 也能用来做多级排序。


# ==============================================================================
# 知识点 5：__len__ 和 __getitem__ —— 让对象像列表
# ==============================================================================
#
# 【讲解】
#   __len__      ：让 len(obj) 能用，返回值必须是非负整数。
#   __getitem__  ：让 obj[下标] 能用，参数是下标（可以是 int，也可以是切片）。
#
# 【重点】实现了 __getitem__ 之后会附赠一个大礼包：for 循环、in 判断、
#         list() 转换都会自动可用！因为 Python 的迭代协议会退而使用
#         __getitem__(0)、__getitem__(1)... 直到 IndexError 为止。
#
# 【注意】__getitem__ 必须在越界时抛 IndexError，否则 for 循环会无限转下去。

class Playlist:
    def __init__(self, songs):
        self.songs = songs

    def __len__(self):
        """len(playlist) 返回歌曲数量。"""
        return len(self.songs)

    def __getitem__(self, index):
        """playlist[0]、playlist[1:3] 都交给列表去处理。"""
        return self.songs[index]        # 越界时列表自己会抛 IndexError

    def __repr__(self):
        return f"Playlist({self.songs})"


print("\n--- __len__ 与 __getitem__ ---")
pl = Playlist(["晴天", "七里香", "稻香"])
print(f"len(pl) = {len(pl)}")
print(f"pl[0] = {pl[0]}")
print(f"pl[-1] = {pl[-1]}")
print(f"pl[0:2] = {pl[0:2]}   ← 切片也能用，因为切片被原样传给了列表")

# 输出：
# --- __len__ 与 __getitem__ ---
# len(pl) = 3
# pl[0] = 晴天
# pl[-1] = 稻香
# pl[0:2] = ['晴天', '七里香']   ← 切片也能用，因为切片被原样传给了列表

print("\n--- 实现了 __getitem__ 的附赠能力 ---")
print(f"for 循环：{[song for song in pl]}")
print(f"in 判断：{'晴天' in pl}，转 list：{list(pl)}")

# 输出：
# --- 实现了 __getitem__ 的附赠能力 ---
# for 循环：['晴天', '七里香', '稻香']
# in 判断：True，转 list：['晴天', '七里香', '稻香']
#
# 【重点】你只写了 __getitem__，却白得了 for、in、list() 三个能力。
#         这就是 Python 魔术方法的「协议」思想：实现一个钩子，
#         所有依赖这个协议的内置功能都自动可用。
#
# 【注意】有了 __len__ 之后，bool(obj) 也会跟着变：
#         长度为 0 时 bool(pl) 是 False！所以空对象会被当成「假」。

print(f"\n空播放列表的布尔值：{bool(Playlist([]))}，有歌的：{bool(pl)}")

# 输出：
# 空播放列表的布尔值：False，有歌的：True


