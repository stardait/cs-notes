# 1. lambda 参数: 表达式，用来创建一次性的匿名函数
# 2. lambda 的冒号后只能写表达式，不能写赋值、return、if 语句
# 3. 条件判断要用条件表达式：值1 if 条件 else 值2
# 4. lambda 没有名字和文档字符串，报错时显示 <lambda>
# 5. 短小的 key / 回调适合 lambda；复杂或复用的逻辑用 def
# 6. sorted(key=lambda ...)、map、filter、max 是 lambda 的主战场
# 7. 循环里创建 lambda 会捕获同一个变量，用默认参数固定当前值
# 8. lambda 不代表高级，能读懂、好维护才是目标


