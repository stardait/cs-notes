# ==============================================================================
# 知识点 1：lambda 的基本语法
# ==============================================================================
#
# lambda 是 Python 里创建「匿名函数」的关键字。
# 语法只有一句话：
#
#     lambda 参数列表: 表达式
#
# 它等价于一个只有 return 语句的 def：
#
#     lambda x: x * x
#     等价于
#     def 某个名字(x):
#         return x * x
#
# 【类比】def 像「正式给孩子上户口」：有名字、有出生证明（文档字符串）；
#   lambda 像「临时叫一声」：用完就走，不占名字。
#
# 【重点】lambda 的冒号后面只能写「一个表达式」，不能写语句。
#   表达式一定有一个值，这个值就是 lambda 的返回值（不需要写 return）。

# 把 lambda 赋值给变量，就能像普通函数一样调用
square = lambda x: x * x

print("5 的平方：", square(5))
print("类型：", type(square))
print("名字：", square.__name__)

# 输出：
# 5 的平方： 25
# 类型： <class 'function'>
# 名字： <lambda>
#
# 【注意】lambda 创建出来的仍然是普通的 function 对象。
#         只是它的 __name__ 统一叫 <lambda>，因为没有名字。

# 多个参数
add = lambda a, b: a + b
print("3 + 4 =", add(3, 4))

# 默认参数也可以使用
power = lambda base, exp=2: base ** exp
print("5 的默认平方：", power(5))
print("2 的 10 次方：", power(2, 10))

# 输出：
# 3 + 4 = 7
# 5 的默认平方： 25
# 2 的 10 次方： 1024
#
# 【重点】参数规则和 def 完全一样：位置参数、默认参数都可以。

# lambda 可以直接被调用，外面要加一层括号，否则会被理解成别的东西
print("立即调用：", (lambda x: x + 1)(10))

# 输出：
# 立即调用： 11
#
# 【注意】(lambda x: x + 1)(10) 里，第一对括号把 lambda 包成一个整体，
#         第二对括号才是「调用」。这种写法可读性一般，了解即可。


# ==============================================================================
# 知识点 2：lambda 里能写什么？
# ==============================================================================
#
# 只能写「表达式」：计算出一个值的东西。
# 不能写「语句」：赋值、if 语句、for 循环、return 等。
#
# 想要条件判断怎么办？用「条件表达式」：
#     值1 if 条件 else 值2
# 它本身就是一个表达式，所以可以放在 lambda 里。

absolute = lambda x: x if x >= 0 else -x
print("|-7| =", absolute(-7))
print("|3|  =", absolute(3))

# 输出：
# |-7| = 7
# |3|  = 3

# 【常见错误】在 lambda 里写赋值语句
# 下面这段代码不会被真正执行，只是尝试编译，确认它确实是语法错误：
try:
    compile("lambda x: x = x + 1", "<测试>", "exec")
except SyntaxError:
    print("lambda 里不能写赋值语句：SyntaxError")

# 输出：
# lambda 里不能写赋值语句：SyntaxError
#
# 【为什么】x = x + 1 是语句，不是表达式，没有「值」。
#         如果你需要多步计算，请老老实实写 def。
#
# 【常见错误】把 print 当成「执行动作」塞进 lambda，结果 lambda 返回 None
loud = lambda x: print(f"处理 {x}")
result = loud("数据")
print("lambda 的返回值：", result)

# 输出：
# 处理 数据
# lambda 的返回值： None
#
# 【为什么】print(...) 是一个表达式，它的值是 None。
#         lambda 会把「最后一个表达式的值」返回，于是返回 None。
#         这说明 lambda 不适合写「有副作用」的动作，它更适合「算出一个值」。


# ==============================================================================
# 知识点 3：lambda vs def —— 到底该用哪个？
# ==============================================================================
#
# 先看两个功能完全相同的写法：

def add_one_def(x):
    return x + 1


add_one_lambda = lambda x: x + 1

print("def 版本：", add_one_def(10))
print("lambda 版本：", add_one_lambda(10))

# 输出：
# def 版本： 11
# lambda 版本： 11

# 它们并不完全一样，差别主要在「可读性」和「可维护性」：

def with_doc(x):
    """返回 x 的两倍。"""
    return x * 2


double = lambda x: x * 2

print("def 的名字：", with_doc.__name__)
print("def 的文档：", with_doc.__doc__)
print("lambda 的名字：", double.__name__)
print("lambda 的文档：", double.__doc__)

# 输出：
# def 的名字： with_doc
# def 的文档： 返回 x 的两倍。
# lambda 的名字： <lambda>
# lambda 的文档： None
#
# 【重点】lambda 没有名字、没有文档字符串，报错时栈里只显示 <lambda>。
#         代码一旦变复杂，这些信息对排查问题非常重要。
#
# 一张简单的选择表：
#
#   场景                                 推荐
#   -----------------------------------  --------
#   逻辑超过一个表达式                    def
#   需要复用、需要名字                    def
#   需要文档字符串 / 类型标注             def
#   需要写多步过程、循环、异常处理        def
#   只在一个地方用一次的小回调            lambda
#   sorted / max 的 key 参数              lambda（或 itemgetter）
#   函数体一眼就能看懂                    lambda
#
# 【结论】lambda 不是「更高级的函数」，只是「更短的临时函数」。
#   当 lambda 让你多想了三秒，就应该换成 def。


# ==============================================================================
# 知识点 4：lambda 最常用的场景 —— 给内置函数当「小配件」
# ==============================================================================
#
# 很多内置函数需要一个「函数参数」，而我们往往只需要一个极短的动作。
# 这时候 lambda 就很合适。

# 场景 1：sorted 的 key —— 告诉排序「按什么排」
students = [("小明", 85), ("小红", 92), ("小刚", 78)]

by_score = sorted(students, key=lambda s: s[1])
print("按分数从低到高：", by_score)

by_score_desc = sorted(students, key=lambda s: s[1], reverse=True)
print("按分数从高到低：", by_score_desc)

best = max(students, key=lambda s: s[1])
print("最高分：", best)

# 输出：
# 按分数从低到高： [('小刚', 78), ('小明', 85), ('小红', 92)]
# 按分数从高到低： [('小红', 92), ('小明', 85), ('小刚', 78)]
# 最高分： ('小红', 92)
#
# 【为什么】key=lambda s: s[1] 的意思是：
#         「对每个学生 s，取出它的第 1 号元素（分数）作为排序依据」。
#         sorted 会拿这些「依据」去比较，而不是直接比较整个元组。

# 场景 2：map / filter —— 对每个元素做变换或筛选
numbers = [1, 2, 3, 4, 5, 6]

doubled = list(map(lambda n: n * 2, numbers))
print("每个数乘 2：", doubled)

evens = list(filter(lambda n: n % 2 == 0, numbers))
print("只保留偶数：", evens)

# 输出：
# 每个数乘 2： [2, 4, 6, 8, 10, 12]
# 只保留偶数： [2, 4, 6]
#
# 【注意】map / filter 返回的是「迭代器」，不是列表。
#         想看内容要用 list() 转一下，文件 03 会详细讲。

# 场景 3：一次性回调 —— 不需要为三行代码专门起个名字
def apply(func, value):
    return func(value)


print("用 lambda 平方：", apply(lambda x: x ** 2, 6))
print("用 lambda 加 100：", apply(lambda x: x + 100, 6))

# 输出：
# 用 lambda 平方： 36
# 用 lambda 加 100： 106
#
# 【适用条件】这个 lambda 只在这里用一次，而且一眼能看懂。

# 场景 4：用字典把「符号」映射到「算法」
calculator = {
    "+": lambda a, b: a + b,
    "-": lambda a, b: a - b,
    "*": lambda a, b: a * b,
}

for symbol in ("+", "-", "*"):
    print(f"8 {symbol} 2 = {calculator[symbol](8, 2)}")

# 输出：
# 8 + 2 = 10
# 8 - 2 = 6
# 8 * 2 = 16
#
# 【重点】这里 lambda 的用途是「把一小段计算装进字典」，
#         主流程只需要按符号查表，不需要写一长串 if / elif。


# ==============================================================================
# 知识点 5：什么时候不该用 lambda
# ==============================================================================
#
# 【原则】lambda 适合「短到没必要起名字」的逻辑；
#   如果逻辑需要解释，名字本身就是最好的注释。

# 不推荐：把两层条件判断塞进一行 lambda
level_lambda = lambda score: "优秀" if score >= 90 else ("及格" if score >= 60 else "不及格")
print("lambda 判断：", level_lambda(95), level_lambda(70), level_lambda(40))

# 推荐：同样的逻辑用 def 写清楚
def level_def(score):
    if score >= 90:
        return "优秀"
    if score >= 60:
        return "及格"
    return "不及格"


print("def 判断：   ", level_def(95), level_def(70), level_def(40))

# 输出：
# lambda 判断： 优秀 及格 不及格
# def 判断：    优秀 及格 不及格
#
# 【重点】两段结果一样，但下面这段任何人都能一眼看懂。
#         嵌套条件表达式超过一层，就应该改用 def。

# 不推荐：需要复用的函数写成 lambda
#   square = lambda x: x * x
#   ...
#   square = lambda x: x ** 2     # 改了一处，却很难搜到所有使用点
#
# 推荐：只要一个函数会被调用多次、会被别人 import、需要测试，
#       就给它一个正式的名字，用 def。


# ==============================================================================
# 知识点 6：常见误用 —— 循环里的 lambda 会「记住最后一个值」
# ==============================================================================
#
# 这是 lambda 最著名的坑，也是闭包的经典陷阱。
# 先看现象：

funcs = [lambda: i for i in range(3)]
print("直接捕获：", [f() for f in funcs])

# 输出：
# 直接捕获： [2, 2, 2]
#
# 【为什么】lambda 里没有立刻把 i 的值存下来，它只是「引用变量 i」。
#   等三个 lambda 真正被调用时，循环早就结束了，i 已经是 2。
#   所以三个函数都返回 2。
#
# 【怎么修】用默认参数在「创建 lambda 的那一刻」把当前值存进去：
#   默认参数只会在函数定义时求值一次。

fixed_funcs = [lambda i=i: i for i in range(3)]
print("默认参数修复：", [f() for f in fixed_funcs])

# 输出：
# 默认参数修复： [0, 1, 2]
#
# 【重点】看到「循环里创建函数，之后统一调用」就要警惕这个坑。
#         文件 05 讲闭包时还会再遇到它。


# ==============================================================================
# 知识点 7：把几个小工具串起来
# ==============================================================================
#
# 需求：从单词列表里筛出长度 >= 3 的词，再按长度从短到长排序。
# 这里同时用到了 filter（筛选）、sorted（排序）和两个 lambda。

words = ["Python", "is", "fun", "to", "learn"]

long_words = sorted(
    filter(lambda w: len(w) >= 3, words),   # 先筛掉太短的
    key=lambda w: len(w),                    # 再按长度排序
)

print("筛选并排序：", long_words)

# 输出：
# 筛选并排序： ['fun', 'learn', 'Python']
#
# 【解读】
#   1. filter 保留长度 >= 3 的词：Python, fun, learn
#   2. sorted 按长度排序：fun(3) → learn(5) → Python(6)
#
# 【注意】这段代码可以读，但已经有点「链式调用」的味道。
#   如果再加两个步骤，建议拆成中间变量，或者写成普通循环 + def，
#   可读性会比一长串 lambda 更好。


