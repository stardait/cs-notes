# ==============================================================================
# 知识点 1：从一个「想记住东西」的需求说起
# ==============================================================================
#
# 需求：写一个函数，每调用一次就报一个数：1、2、3……
#
# 最容易想到的是用全局变量 count + global 语句。
# 这样能跑，但有两个问题：
#   - 任何代码都能改 count，容易被别处误伤
#   - 想同时有两个计数器，就得多写一个全局变量
#
# 我们真正想要的是：一个函数自带一个小口袋，口袋里装着 count，
# 每调用一次就从口袋里拿出来加一。这个「自带小口袋的函数」就是闭包。
#
# 【类比】闭包像一台自带计数器的售票机：
#   你不需要在墙上挂一块公共记数板（全局变量），
#   每台机器内部有自己的计数，互不干扰。



# ==============================================================================
# 知识点 2：闭包的定义 —— 三个条件
# ==============================================================================
#
# 【定义】满足下面三个条件，就构成闭包：
#   1. 有嵌套函数（函数里定义函数）
#   2. 内层函数引用了外层函数的变量
#   3. 外层函数把内层函数返回出去
#
# 【重点】闭包让外层函数的局部变量「活过了」外层函数的执行。
#   正常情况下，函数一结束，局部变量就销毁；
#   但如果内层函数还引用着它，Python 会把它放进一个「单元格」（cell）里保留。

def make_greeting(greeting):
    def say(name):
        return f"{greeting}，{name}！"
    return say


hello = make_greeting("你好")
morning = make_greeting("早上好")

print(hello("小明"))
print(morning("小红"))

# 输出：
# 你好，小明！
# 早上好，小红！
#
# 【为什么】make_greeting 早就执行完了，但它返回的 say 还记得当时的 greeting。
#   hello 记住的是「你好」，morning 记住的是「早上好」，互不影响。

print("自由变量名：", hello.__code__.co_freevars)
print("单元格内容：", hello.__closure__[0].cell_contents) # type: ignore

# 输出：
# 自由变量名： ('greeting',)
# 单元格内容： 你好
#
# 【说明】
#   __code__.co_freevars：这个函数引用了哪些外层变量
#   __closure__：保存这些变量的单元格（cell）元组
#   cell_contents：单元格里当前的值
#   这些属性平时不用，但能帮你看清「闭包到底存了什么」。


# ==============================================================================
# 知识点 3：计数器 —— 闭包最经典的例子
# ==============================================================================
#
# 关键在 nonlocal：
#   内层函数里写了 count = count + 1，这是一次「赋值」。
#   Python 看到函数里有对 count 赋值，就认为 count 是内层的局部变量；
#   可右边又要读 count，此时它还没赋值，于是报 UnboundLocalError。
#
#   nonlocal count 的意思是：
#   「count 不是我的局部变量，去上一层函数里找」。

def make_counter():
    count = 0

    def counter():
        nonlocal count      # 声明：我要改的是外层函数的 count
        count += 1
        return count

    return counter


counter_a = make_counter()
counter_b = make_counter()

print("计数器 A：", counter_a())
print("计数器 A：", counter_a())
print("计数器 A：", counter_a())
print("计数器 B：", counter_b())

# 输出：
# 计数器 A： 1
# 计数器 A： 2
# 计数器 A： 3
# 计数器 B： 1
#
# 【重点】counter_a 和 counter_b 来自两次 make_counter()，
#   每次调用都会创建一个新的 count 单元格，所以它们互不干扰。

print("A 当前的 count：", counter_a.__closure__[0].cell_contents) # type: ignore

# 输出：
# A 当前的 count： 3
#
# 【注意】同一个函数对象被调用多次，共用同一个单元格；
#   不同次 make_counter() 创建的单元格彼此独立。


# ==============================================================================
# 知识点 4：为什么必须写 nonlocal？
# ==============================================================================
#
# 先看一个故意写错的版本，观察报错：

def make_broken_counter():
    count = 0

    def counter():
        count += 1        # type: ignore # 这里没有 nonlocal
        return count

    return counter


broken = make_broken_counter()

try:
    broken()
except UnboundLocalError as e:
    print("报错类型：", type(e).__name__)
    print("报错信息：", e)

# 输出：
# 报错类型： UnboundLocalError
# 报错信息： cannot access local variable 'count' where it is not associated with a value
#
# 【为什么】Python 在编译内层函数时，看到 count += 1，
#   就判定 count 是内层的局部变量。
#   执行到 += 时，先读 count，但局部 count 还没赋值，于是报错。
#
# 【重点】只要内层函数「重新绑定」外层变量（赋值、+=、-= 等），
#   就必须写 nonlocal。
#
# 如果只是「读取」外层变量，不需要 nonlocal：

def make_reader():
    value = 42

    def read():
        return value      # 只读，不赋值，不需要 nonlocal

    return read


print("只读闭包：", make_reader()())

# 输出：
# 只读闭包： 42
#
# 【补充】如果只是修改可变对象的内容（比如 records.append(item)），
#   也不需要 nonlocal——因为没有重新绑定变量，只是改了对象内部。
#   只有 records = [...] 这种重新赋值才需要 nonlocal。

# 【对比】global 是改「模块级全局变量」，nonlocal 是改「外层函数变量」。
#   闭包优先用 nonlocal，不要为了省事把状态放到全局。


# ==============================================================================
# 知识点 5：闭包记住的是「变量」，不是「当时的值」
# ==============================================================================
#
# 这一点非常容易误解。看下面的例子：

def make_printer():
    value = 1

    def show():
        return value

    value = 2          # 返回之前又改了一次
    return show


printer = make_printer()
print("打印结果：", printer())

# 输出：
# 打印结果： 2
#
# 【为什么】show 捕获的是变量 value 本身，不是「定义 show 那一刻的 1」。
#   value 后来变成 2，show 看到的就是 2。
#
# 【重点】闭包是「按引用捕获变量」，不是「按值快照」。
#   如果想让它在创建时就固定住某个值，用默认参数：

def make_printer_fixed():
    value = 1

    def show(v=value):     # 默认参数在定义时求值，把 1 存了下来
        return v

    value = 2
    return show


print("默认参数固定：", make_printer_fixed()())

# 输出：
# 默认参数固定： 1
#
# 【联想】文件 02 里循环创建 lambda 的坑，本质就是这个：
#   所有 lambda 共享同一个循环变量 i，等调用时 i 已经是最后一个值。
#   用 lambda i=i: i 正是用默认参数在定义时「拍快照」。


# ==============================================================================
# 知识点 6：闭包的应用场景
# ==============================================================================
#
# 场景 1：带配置的函数工厂
#   同一套逻辑，不同的参数，生成不同的专用函数。

def make_discount(rate):
    def apply(price):
        return round(price * (1 - rate), 2)
    return apply


vip_discount = make_discount(0.2)
print("VIP 打 8 折：", vip_discount(100))
print("VIP 买 88 元：", vip_discount(88))

# 输出：
# VIP 打 8 折： 80.0
# VIP 买 88 元： 70.4
#
# 【重点】rate 被闭包记住，但调用者完全不需要知道它的存在。
#   这比每次调用都传 rate 更不容易传错。

# 场景 2：多个函数共享同一份状态
#   下面做一个迷你银行账户：存款和取款两个函数，共享同一个 balance。

def make_account(initial=0):
    balance = initial

    def deposit(amount):
        nonlocal balance
        balance += amount
        return balance

    def withdraw(amount):
        nonlocal balance
        if amount > balance:
            return f"余额不足（当前 {balance} 元）"
        balance -= amount
        return balance

    return deposit, withdraw


deposit, withdraw = make_account(100)

print("存 50：", deposit(50))
print("取 200：", withdraw(200))
print("取 30：", withdraw(30))
print("再存 80：", deposit(80))

# 输出：
# 存 50： 150
# 取 200： 余额不足（当前 150 元）
# 取 30： 120
# 再存 80： 200
#
# 【重点】deposit 和 withdraw 是两个不同的函数，
#   但它们引用的是同一个 balance 单元格。
#   改一个，另一个立刻能看到，这正是「共享状态」的闭包写法。

# 场景 3：装饰器的前置知识
#   装饰器本质上就是「闭包 + 函数作为参数」。
#   这里先看一眼最小结构，下一个文件详细展开。

def trace(func):
    def wrapper():
        print(f"准备调用 {func.__name__}")
        return func()
    return wrapper


@trace
def say_hi():
    return "嗨！"


print(say_hi())

# 输出：
# 准备调用 say_hi
# 嗨！
#
# 【预告】@trace 会把 say_hi 替换成 wrapper，而 wrapper 记住了原来的 say_hi。
#   这就是闭包在装饰器里的核心作用。


# ==============================================================================
# 知识点 7：常见错误
# ==============================================================================
#
# 【常见错误 1】忘了 nonlocal，运行到 += 才报 UnboundLocalError
#   前面已经演示。记住：内层要「重新赋值」外层变量，就写 nonlocal。
#
# 【常见错误 2】以为闭包保存的是值，结果被后来的修改影响
#   前面 make_printer 的例子已经演示。需要快照就用默认参数。
#
# 【常见错误 3】把多个计数器写成了同一个闭包
#   如果只调用一次工厂、把同一个函数赋给两个变量，它们共享状态：

shared_a = make_counter()
shared_b = shared_a          # 只是起了个别名，不是新计数器

print("shared_a：", shared_a())
print("shared_b：", shared_b())

# 输出：
# shared_a： 1
# shared_b： 2
#
# 【为什么】shared_a 和 shared_b 指向同一个函数对象，
#   当然共享同一个 count 单元格。
#   要独立计数，必须调用两次 make_counter()。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 闭包 = 嵌套函数 + 引用外层变量 + 外层返回内层函数
# 2. 闭包让外层函数的局部变量在内层函数中继续存活
# 3. __closure__ 和 __code__.co_freevars 可以查看闭包保存的变量
# 4. 内层要重新赋值外层变量时必须写 nonlocal
# 5. 只读外层变量、或只修改可变对象内容，不需要 nonlocal
# 6. 闭包按引用捕获变量，不是按值快照；要快照用默认参数
# 7. 每次调用工厂函数都会创建独立的状态；别名会共享状态
# 8. 闭包常用于计数器、函数工厂、配置固定的工具、装饰器


