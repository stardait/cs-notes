# 【本章小结】
# ==============================================================================
#
# 1. if 的三要素：if + 条件 + 冒号，代码块靠「缩进 4 空格」划分，不用大括号
# 2. 条件为 False 时跳过整个缩进块；嵌套时 else 与哪个 if 对齐就属于哪个 if
# 3. if-else 是二选一；elif 是「从上往下、命中即停」，所以条件顺序决定结果
# 4. 条件要从严格往宽松排：>= 90 必须排在 >= 60 前面
# 5. 嵌套 if 用于「前一个成立，后一个才有意义」；超过 3 层就用 and 拍平
# 6. 条件表达式：变量 = A if 条件 else B，先写结果再写条件，else 不能省
# 7. 假值只有：False / None / 0 / 0.0 / '' / [] / {} / ()，其余都是真（'0' 也是真！）
# 8. 判空写 if x:，判 None 写 if x is None:，不要写 if x == True:
# 9. == 是比较、= 是赋值；浮点数不能用 ==，用 math.isclose 或 round
# 10. and / or 返回操作数本身；多值相等用 in，区间判断用 18 <= age < 60


