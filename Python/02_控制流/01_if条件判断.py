# ==============================================================================
# 知识点 1：if —— 程序的第一条「岔路口」
# ==============================================================================
#
# 【讲解】
#   前面一章的代码是一条直线：从上到下，一句不落地全部执行。从 if 开始，程序学会
#   「看情况办事」—— 像走到路口看红绿灯：绿灯就走，红灯就停。
#
#   if 语句只有三样东西，缺一不可：关键字 if、能算出 True / False 的条件、
#   以及冒号 : 加「缩进 4 个空格」的代码块。
#
# 【重点】Python 用缩进划分代码块，不用大括号。
#   C / Java：if (age >= 18) { 语句1; 语句2; }
#   Python  ：if age >= 18: 换行 + 缩进 4 空格
#   缩进不是排版好看，它就是语法本身。统一用 4 个空格，别用 Tab。

age = 20                                    # 用一个变量代表「用户年龄」

if age >= 18:                               # 条件为 True，才进入下面的缩进块
    print("你已经成年了")                    # 4 个空格缩进 = 属于 if 的代码块
    print("可以独立办理银行卡")              # 同样的缩进 = 同一个代码块

print("这行没有缩进，无论如何都会执行")      # 不在 if 里，是「主干道」

# 输出：
# 你已经成年了
# 可以独立办理银行卡
# 这行没有缩进，无论如何都会执行
#
# 【重点】条件为 False 时，整个缩进块一起被跳过，不是只跳一行。


# ==============================================================================
# 知识点 2：if-else —— 二选一，必须走一条
# ==============================================================================
#
# 【讲解】
#   只有 if 的时候，条件不成立就什么都不做。
#   但生活里更多是二选一：及格 / 不及格、成年 / 未成年。
#   生活类比：检票口 —— 有票就进站（if），没票就回家（else），
#   不存在「既没进站、也没回家」这种状态。

score = 58

if score >= 60:                             # 条件成立，走这一支
    print(f"{score} 分：及格")
else:                                       # 否则走这一支
    print(f"{score} 分：不及格")

# 输出：
# 58 分：不及格
#
# 【注意】else 后面不能再写条件！
#       else score < 60:      ← SyntaxError
#   else 的意思就是「上面所有条件都不成立」，它不需要、也不允许条件。
#
# 【小技巧】代码块暂时不想写，可以用 pass 占位（它什么都不做）。


# ==============================================================================
# 知识点 3：if-elif-else —— 多选一，命中即停
# ==============================================================================
#
# 【讲解】
#   现实里的分类往往不止两类：成绩有五级、天气有晴阴雨雪。
#   elif（else if 的缩写）把多个条件串成一条链，从上往下逐个检查。
#
# 【重点】检查顺序是「从上往下」，一旦命中就停止，后面的条件根本不会被计算。
#         所以条件的先后顺序会直接影响结果 —— 这是新手最容易忽略的点。

score = 85

if score >= 90:
    level = "优秀"
elif score >= 80:                           # 上一条件不成立，才轮到这一条
    level = "良好"
elif score >= 70:
    level = "中等"
elif score >= 60:
    level = "及格"
else:                                       # 上面全不成立
    level = "不及格"

print(f"{score} 分 → {level}")

# 输出：
# 85 分 → 良好

# 【重点】顺序陷阱：把宽条件放在前面，细条件就永远轮不到。
score = 95

if score >= 60:                             # 95 >= 60 成立，直接命中
    print(f"{score} 分：及格")
elif score >= 90:                           # 这行永远执行不到
    print(f"{score} 分：优秀")

# 输出：
# 95 分：及格
#
# 【为什么】Python 不是「挑一个最合适的」，而是「执行第一个成立的」。
#   所以条件要从严格往宽松排：>= 90 必须排在 >= 60 前面。
#
# 【结构规则】if 可以单独出现；elif 必须跟在 if 后面；else 最多一个且在最后。


# ==============================================================================
# 知识点 4：嵌套 if —— 先粗筛，再细筛
# ==============================================================================
#
# 【讲解】
#   代码块里当然还能再写 if，这就是嵌套，像过机场安检：
#   先查护照（第一层），护照没问题再查行李（第二层）。
#
#   什么时候该嵌套？当后一个判断「只有前一个成立才有意义」时 ——
#   比如「会员消费满 200 打 8 折」：不是会员，根本不用算消费额。

is_member = True                            # 是不是会员
amount = 300                                # 消费金额

if is_member:                               # 第一层：是不是会员
    if amount >= 200:                       # 第二层：消费够 200 吗
        discount = 0.8
    else:
        discount = 0.9
else:                                       # 不是会员，不打折
    discount = 1.0

print(f"消费 {amount} 元，折扣 {discount}，实付 {amount * discount:.0f} 元")

# 输出：
# 消费 300 元，折扣 0.8，实付 240 元
#
# 【重点】嵌套超过 3 层就该警觉：读代码的人要在脑子里叠好几层缩进。
#   上面这段其实可以拍平，结果完全一样，但好读得多：
#
#       if is_member and amount >= 200:
#           discount = 0.8
#       elif is_member:
#           discount = 0.9
#       else:
#           discount = 1.0
#
# 【规则】能用 and 合并的条件，就别嵌套。


# ==============================================================================
# 知识点 5：条件表达式（三元运算）—— 一行写完 if-else
# ==============================================================================
#
# 【讲解】
#   有些 if-else 只是为了「二选一取个值」，写 4 行太啰嗦。可以压成一行：
#
#       变量 = 条件成立时的值 if 条件 else 条件不成立时的值
#
# 【注意】顺序和 if 语句是反的：先写结果，再写条件。
#   读法是「取 A，如果条件成立；否则取 B」。

age = 17
label = "成年" if age >= 18 else "未成年"   # 条件不成立，取 else 后面的值
print(f"age = {age} → {label}")

# 输出：
# age = 17 → 未成年

number = 8
parity = "偶数" if number % 2 == 0 else "奇数"
print(f"{number} 是{parity}")

# 输出：
# 8 是偶数
#
# 【常见错误】三元里忘了 else：
#     label = "成年" if age >= 18        ← SyntaxError，三元必须有 else
#
# 【常见错误】把三元一层层嵌套：
#     grade = "优秀" if s >= 90 else "及格" if s >= 60 else "不及格"
#   这行能跑，但没人愿意读第二遍。分支超过两个，请老实用 if / elif / else。


# ==============================================================================
# 知识点 6：真值测试 —— 不是只有 True 才算「真」
# ==============================================================================
#
# 【讲解】
#   if 后面不一定要写比较运算。Python 会先把任何值「转成布尔」再判断，
#   这叫真值测试（truthiness）。规则只有一条：
#
#       空的就是假，非空的就是真；零就是假，非零就是真。
#
#   假值（falsy）一共就这么几个，建议背下来：
#       False、None、0、0.0、''（空字符串）、[]（空列表）、{}（空字典）、()（空元组）
#   除了它们，其他一切值在 if 里都算真 —— 包括字符串 '0' 和 'False'！

print("\n--- 真值测试一览 ---")
print(f"bool(0)        = {bool(0)}")        # False  零
print(f"bool(None)     = {bool(None)}")     # False  空无
print(f"bool('')       = {bool('')}")       # False  空字符串
print(f"bool([])       = {bool([])}")       # False  空列表
print(f"bool(1)        = {bool(1)}")        # True   非零
print(f"bool(-1)       = {bool(-1)}")       # True   负数也是非零
print(f"bool('0')      = {bool('0')}")      # True   注意！'0' 是非空字符串

# 输出：
# --- 真值测试一览 ---
# bool(0)        = False
# bool(None)     = False
# bool('')       = False
# bool([])       = False
# bool(1)        = True
# bool(-1)       = True
# bool('0')      = True
#
# 【常见错误】bool('0') 是 True！判断「用户输入的是不是 0」不能写 if user_input:，
#   因为 '0' 也是真。必须先转数字：if int(user_input) == 0:

# 【重点】有了真值测试，判空可以写得非常干净：
username = ""                               # 模拟用户没有输入名字

if username:                                # 推荐：直接判断「里面有没有东西」
    print(f"欢迎回来，{username}")
else:
    print("用户名不能为空")

# 输出：
# 用户名不能为空

# 三种写法对比：if username: ✅ > if len(username) > 0: ⚠️ > if username != "": ⚠️
# 第一种最 Pythonic，后两种啰嗦且只适用于字符串。
#
# 【常见错误】用 == True 判断真假：
value = 1                                   # 整数 1，不是布尔值

print(f"value == True  → {value == True}")  # True：True 在数值上等于 1
print(f"value is True  → {value is True}")  # False：1 和 True 不是同一个对象

# 输出：
# value == True  → True
# value is True  → False
#
# 【为什么】True 就是整数 1，False 就是整数 0（print(True + 1) 得到 2）。
#   所以 if x == True: 会把 1 也当成真。判真假写 if x:，判 None 写 if x is None:。


# ==============================================================================
# 知识点 7：新手最常踩的 5 个坑
# ==============================================================================
#
# 【常见错误 1】把 == 写成 =
#     if score = 60:          ← SyntaxError
#   单个 = 是赋值，双个 == 才是比较。Python 直接报语法错误，这算「幸运的错误」；
#   C 语言里这行能编译通过，会悄悄算错。

print("\n--- 坑 2：用 == 比较浮点数 ---")
print(f"0.1 + 0.2 == 0.3 → {0.1 + 0.2 == 0.3}")       # 第 1 章讲过，浮点是近似值

import math                                 # 用 isclose 做「近似相等」比较

print(f"math.isclose(0.1 + 0.2, 0.3) → {math.isclose(0.1 + 0.2, 0.3)}")

# 输出：
# --- 坑 2：用 == 比较浮点数 ---
# 0.1 + 0.2 == 0.3 → False
# math.isclose(0.1 + 0.2, 0.3) → True
#
# 【为什么】0.1 + 0.2 实际是 0.30000000000000004，不是 0.3。
#   金额、成绩这类要判断相等的浮点数，用 math.isclose 或先 round 再比。

print("\n--- 坑 3：and / or 返回的是操作数本身 ---")
print(f"'' or '默认值'     → {'' or '默认值'}")       # 左边为假，返回右边
print(f"'小明' or '默认值'  → {'小明' or '默认值'}")  # 左边为真，直接返回左边
print(f"0 and 5           → {0 and 5}")             # 左边为假，短路，返回 0
print(f"3 and 5           → {3 and 5}")             # 左边为真，返回右边

# 输出：
# --- 坑 3：and / or 返回的是操作数本身 ---
# '' or '默认值'     → 默认值
# '小明' or '默认值'  → 小明
# 0 and 5           → 0
# 3 and 5           → 5
#
# 【重点】and / or 返回的不是 True / False，而是「决定了结果的那个操作数」。
#   正确用法：name = user_input or "匿名"       ← 给默认值
#   错误用法：if user_input or "匿名":          ← 恒为真，判断永远成立！

print("\n--- 坑 4：缩进决定 else 归谁 ---")
score = 75

if score >= 60:                             # 外层 if
    print("第一层：及格")
    if score >= 90:                         # 内层 if
        print("第二层：优秀")
    else:                                   # 与内层 if 对齐 → 属于内层
        print("第二层：及格但不算优秀")

# 输出：
# --- 坑 4：缩进决定 else 归谁 ---
# 第一层：及格
# 第二层：及格但不算优秀
#
# 【注意】else 与哪个 if 对齐就属于哪个 if；往左挪 4 格，逻辑完全变了。

print("\n--- 坑 5：重复判断可以更简洁 ---")
answer = "y"

if answer == "y" or answer == "Y" or answer == "yes":    # 啰嗦：条件重复三遍
    print("确认")
if answer in ("y", "Y", "yes"):             # 简洁：装进元组，in 一次判完
    print("确认（用 in 更清爽）")

# 输出：
# --- 坑 5：重复判断可以更简洁 ---
# 确认
# 确认（用 in 更清爽）
#
# 【额外】链式比较：18 <= age < 60 等价于 18 <= age and age < 60。


# ==============================================================================
# 知识点 8：综合案例 —— 判断闰年
# ==============================================================================
#
# 【讲解】
#   公历闰年规则：
#       1. 能被 4 整除，且不能被 100 整除  → 闰年（如 2024）
#       2. 能被 400 整除                  → 闰年（如 2000）
#   翻译成 if / elif 时要「特殊条件在前，一般条件在后」：
#   先判 % 400，再判 % 100，最后判 % 4。顺序颠倒就会误判 1900 年。

year = 2024

if year % 400 == 0:                         # 世纪闰年：2000、2400
    print(f"{year} 年是闰年（能被 400 整除）")
elif year % 100 == 0:                       # 整百年但不能被 400 整除：1900
    print(f"{year} 年不是闰年（整百年，但不能被 400 整除）")
elif year % 4 == 0:                         # 普通闰年：2024、2028
    print(f"{year} 年是闰年（能被 4 整除，且不是整百年）")
else:                                       # 其余都不是
    print(f"{year} 年不是闰年")

# 输出：
# 2024 年是闰年（能被 4 整除，且不是整百年）
#
# 【补充】一行版：is_leap = year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


