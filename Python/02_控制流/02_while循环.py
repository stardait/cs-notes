# 【本章小结】
# ==============================================================================
#
# 1. while 是「条件成立就反复执行」，每轮开始前重新检查一次条件
# 2. 三要素：初始化、条件、更新，缺一不可；忘了更新就是死循环（Ctrl+C 停）
# 3. while 先判断后执行，条件一开始为假时，循环体一次都不执行
# 4. 计数器模式：count = 0 在外，count += 1 在里，更新不能被 if 挡住
# 5. 累加器模式：累加初始化 0，累乘初始化 1，初始化必须写在循环外
# 6. while-else：循环「正常跑完」执行 else；被 break 打断则不执行
# 7. 差一错误：想清楚最后一次循环时变量应该是几，边界用 < 还是 <=
# 8. 别用浮点数当循环变量，累加误差会让次数对不上
# 9. while 适合「不知道循环多少次，只知道什么时候停」：除到 0、取到空


