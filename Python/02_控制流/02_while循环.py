# ==============================================================================
# 知识点 1：while —— 条件成立就一直转
# ==============================================================================
#
# 【讲解】
#   if 是「条件成立就执行一次」，while 是「条件成立就反复执行」。
#   生活类比：洗衣机。只要「没到设定时间」这个条件成立，滚筒就一直转；
#   时间一到，条件变 False，循环结束 —— 不是转一次就停。
#
#   语法和 if 几乎一样：关键字 while + 条件 + 冒号 + 缩进代码块。
#   区别只在于：while 的代码块执行完，会「回到开头再检查一次条件」。

count = 1                                   # ① 初始化：循环变量从 1 开始

while count <= 5:                           # ② 条件：每轮开始前检查一次
    print(f"第 {count} 次循环")
    count += 1                              # ③ 更新：让条件早晚会变 False

print(f"循环结束后 count = {count}")         # 循环外的代码，只执行一次

# 输出：
# 第 1 次循环
# 第 2 次循环
# 第 3 次循环
# 第 4 次循环
# 第 5 次循环
# 循环结束后 count = 6
#
# 【重点】循环结束时 count 是 6，不是 5。
#   因为条件 `count <= 5` 是在 count 变成 6 时才为 False，
#   也就是说：多走了一次「检查」，但没有多执行一次循环体。


# ==============================================================================
# 知识点 2：while 三要素 —— 少一个就是死循环
# ==============================================================================
#
# 【讲解】
#   写 while 之前，先把这三件事想清楚，缺一不可：
#
#       ① 初始化：循环变量从几开始？        count = 1
#       ② 条件  ：什么时候继续转？          count <= 5
#       ③ 更新  ：怎么让它早晚停下来？      count += 1
#
# 【为什么】第 ③ 步最容易忘。忘了它，条件永远为真，程序会一直转下去，
#   这就是「死循环」—— 你的终端会疯狂刷屏，只能按 Ctrl+C 强制中断。

# 【常见错误】忘记更新循环变量：
#     count = 1
#     while count <= 5:
#         print(count)          ← 没有 count += 1，永远打印 1
#
#   上面这段千万别运行。真遇到了，在终端按 Ctrl+C 停止。
#
# 【注意】while 是「先判断，后执行」。如果一开始条件就是 False，
#   循环体一次都不会执行 —— 这一点和 C / Java 的 do-while 不同。
number = 10

while number < 5:                           # 10 < 5 是 False，直接跳过
    print("这行永远不会执行")

print("条件一开始就不成立，循环体一次都没进")

# 输出：
# 条件一开始就不成立，循环体一次都没进


# ==============================================================================
# 知识点 3：计数器模式 —— 「数了多少次」
# ==============================================================================
#
# 【讲解】
#   计数器 = 一个从 0 开始的变量，每发生一件事就 +1。
#   像超市门口的计数门：进来一个人，数字加一。
#
#   套路固定，背下来就能套：
#       count = 0              ① 从 0 开始
#       while 还没数完:         ② 数完了就停
#           count += 1         ③ 数一个加一
#
# 例：火箭发射倒计时（这是「倒数计数器」，每轮 -1）
count = 5

while count > 0:
    print(f"{count}...")
    count -= 1                              # 递减，直到 count 变成 0

print("发射！")

# 输出：
# 5...
# 4...
# 3...
# 2...
# 1...
# 发射！

# 例：统计 1 到 20 里有几个偶数
number = 1                                  # 被检查的数字
even_count = 0                              # 计数器：数到几个偶数了

while number <= 20:
    if number % 2 == 0:                     # 是偶数才计数
        even_count += 1
    number += 1                             # 【重点】这行在 if 外面，每轮都执行

print(f"1 到 20 中共有 {even_count} 个偶数")

# 输出：
# 1 到 20 中共有 10 个偶数
#
# 【常见错误】把 number += 1 写进 if 里面：
#   那样只有偶数才推进，奇数时会永远卡在同一个数上 → 死循环。
#   规则：循环变量的更新，必须每轮都执行，不要被 if 挡住。


# ==============================================================================
# 知识点 4：累加器模式 —— 「加起来一共多少」
# ==============================================================================
#
# 【讲解】
#   累加器 = 一个不断长大的变量。像往存钱罐里投硬币：
#   每投一枚，罐子里的总数就变大。
#
#   套路也很固定：
#       total = 0              ① 从 0 开始（加法的「单位元」）
#       while 还有数没加:       ②
#           total += 当前数     ③ 累加
#           推进到下一个数      ④ 更新
#
# 【重点】累加初始化为 0，累乘初始化为 1 —— 搞反了结果全错。

i = 1
total = 0

while i <= 100:
    total += i                              # 把 i 加进总和
    i += 1                                  # 别忘了推进

print(f"1 + 2 + ... + 100 = {total}")
print(f"用公式验证：100 * 101 // 2 = {100 * 101 // 2}")

# 输出：
# 1 + 2 + ... + 100 = 5050
# 用公式验证：100 * 101 // 2 = 5050

# 累乘：算 5 的阶乘 5! = 5 × 4 × 3 × 2 × 1
n = 5
result = 1                                  # 【重点】累乘从 1 开始，不能是 0

i = 1
while i <= n:
    result *= i                             # result = result * i
    i += 1

print(f"{n}! = {result}")

# 输出：
# 5! = 120

# 带条件的累加：只加奇数
i = 1
odd_sum = 0

while i <= 100:
    if i % 2 == 1:                          # 只处理奇数
        odd_sum += i
    i += 1                                  # 更新放在 if 外面

print(f"1 到 100 的奇数和 = {odd_sum}")

# 输出：
# 1 到 100 的奇数和 = 2500
#
# 【常见错误】把 total = 0 写在循环体内部：
#   那样每轮开头都会清零，最后只剩最后一个数 —— 结果永远不对。
#   初始化在循环外，累加在循环内，记住这个位置关系。


# ==============================================================================
# 知识点 5：while-else —— 循环「正常结束」时做点收尾
# ==============================================================================
#
# 【讲解】
#   while 后面可以跟一个 else，语法长这样：
#
#       while 条件:
#           循环体
#       else:
#           收尾代码
#
#   执行规则只有一句话：
#       循环因为「条件变 False」而结束时 → 执行 else
#       循环被 break 强行打断时        → 不执行 else（break 下个文件讲）
#
#   所以 while-else 的 else，意思是「没被打断，正常跑完了」。

n = 1

while n <= 3:
    print(f"第 {n} 轮")
    n += 1                                  # 条件最终会变 False
else:
    print("循环正常结束，else 执行了")

# 输出：
# 第 1 轮
# 第 2 轮
# 第 3 轮
# 循环正常结束，else 执行了

# 就算循环体一次都没执行，else 也照样执行
n = 10

while n < 5:
    n += 1                                  # 根本进不来
else:
    print("循环体一次没执行，else 也会执行")

# 输出：
# 循环体一次没执行，else 也会执行
#
# 【注意】while-else 平时用得不多，很多人根本没写过。
#   但你读别人代码时会遇到，而且它和 for-else 是同一套机制，
#   后面判断素数、查找元素时用得上。不想用的话，把收尾代码直接写在循环后面，
#   效果一样 —— 区别只在于 break 时会不会跳过。


# ==============================================================================
# 知识点 6：常见错误 —— 差一错误与浮点计数
# ==============================================================================
#
# 【常见错误 1】差一错误（off-by-one）：多一次或少一次
#
#   想打印 1 到 5，写成 while i < 5 只会到 4；写成 <= 5 才是 1 到 5。
#   这个「差一」是编程史上最经典的 bug，检查边界时先问自己：
#   「最后一次循环时，变量应该是几？」

i = 1
while i < 5:                                # 少了等号，只到 4
    print(i, end=" ")
    i += 1
print()

# 输出：
# 1 2 3 4

i = 1
while i <= 5:                               # 加上等号，才是 1 到 5
    print(i, end=" ")
    i += 1
print()

# 输出：
# 1 2 3 4 5

# 【常见错误 2】用浮点数做循环变量 —— 累加误差会让次数对不上
x = 0.0
steps = 0

while x < 1.0:                              # 想加 10 次 0.1 就到 1.0
    x += 0.1
    steps += 1

print(f"加了 {steps} 次，x = {x}")

# 输出：
# 加了 11 次，x = 1.0999999999999999
#
# 【为什么】0.1 在二进制里是无限循环小数，加 10 次得到的是 0.9999999999999999，
#   仍小于 1.0，于是又加了第 11 次，直接冲到 1.0999...
# 【怎么办】循环次数用整数控制，需要精度就用 round() 或 Decimal。
#
# 【常见错误 3】想在 while 条件里做赋值：
#     while (line = 读取一行):     ← Python 里这是 SyntaxError
#   要用海象运算符 := （Python 3.8+），或者写 while True 配合 break（下个文件）。


# ==============================================================================
# 知识点 7：实战 —— 辗转相除、数字反转、数位统计
# ==============================================================================
#
# 【讲解】while 最适合「不知道要循环多少次，只知道什么时候停」的场景。
#   下面三个例子都是这种：数字有几位、什么时候除到 0，事先都不知道。

# 例 1：辗转相除法求最大公约数（欧几里得算法，两千多年前的老古董）
a, b = 48, 18
x, y = a, b                                 # 复制一份，保留原始数据用于打印

while y != 0:                               # 余数不为 0 就继续
    x, y = y, x % y                         # 元组解包，同时更新，不需要临时变量

print(f"gcd({a}, {b}) = {x}")

# 输出：
# gcd(48, 18) = 6
#
# 【手动验算】48 % 18 = 12 → (18, 12) → 18 % 12 = 6 → (12, 6) → 12 % 6 = 0 → 答案是 6

# 例 2：数字反转 —— 12345 变成 54321
number = 12345
original = number                           # 留一份原值
reversed_number = 0

while number > 0:
    digit = number % 10                     # 取出最后一位
    reversed_number = reversed_number * 10 + digit   # 接在新数字的末尾
    number //= 10                           # 砍掉最后一位

print(f"{original} 反转后是 {reversed_number}")

# 输出：
# 12345 反转后是 54321

# 例 3：数位统计 —— 98765 有几位？各数字之和是多少？
number = 98765
original = number
digits = 0                                  # 位数
digit_sum = 0                               # 数位和

while number > 0:
    digit = number % 10                     # 每次取出最后一位
    digit_sum += digit
    digits += 1
    number //= 10                           # 砍掉最后一位

print(f"{original} 共有 {digits} 位，各位数字之和是 {digit_sum}")

# 输出：
# 98765 共有 5 位，各位数字之和是 35


