# 2. 不需要下标时优先用 for，比 while 少维护一个变量，也就少一处出错
# 3. range 三种形态：range(stop) / range(start, stop) / range(start, stop, step)
# 4. range 含头不含尾，range(a, b) 一共 b - a 个数；参数必须是整数
# 5. range 是惰性对象，print 看到的是 range(0, 5)，要看内容用 list()
# 6. enumerate(seq) 同时拿下标和值，start=1 可以从 1 开始编号
# 7. zip(a, b) 把两个序列并排配对，长度不一致时以短的为准（会悄悄丢数据）
# 8. for-else：循环正常取完才执行 else，被 break 打断就跳过 —— 适合查找
# 9. for 每轮都会重新给循环变量赋值，改它不影响下一轮
# 10. 别在遍历列表时增删元素，要遍历副本 numbers[:]


