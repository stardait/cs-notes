# ==============================================================================
# 知识点 1：命名空间 —— 名字和对象的「对照表」
# ==============================================================================
#
# 【讲解】命名空间（namespace）可以理解成一张字典：
#   键是名字（变量名、函数名），值是它指向的对象。
#   `a = 100` 做的事，就是往这张表里写一条：'a' → 100。
#
# 【类比】公司通讯录：名字 → 分机号。打电话时报名字，总机去表里查号码。
#   Python 找一个变量，也是去对应的「表」里查。
#
# 【重点】Python 自带两个函数能直接看到这张表：
#   locals()  → 当前的「局部」命名空间（函数内部用）
#   globals() → 当前的「全局」命名空间（整个文件）

GLOBAL_NAME = "我是全局变量"


def show_namespace():
    """看看函数内部的命名空间里有什么。"""
    local_var = "我是局部变量"
    print(f"  函数内 locals() 的键：{sorted(locals().keys())}")


print("\n--- 命名空间就是一张表 ---")
show_namespace()

print(f"  全局里有 GLOBAL_NAME 吗：{'GLOBAL_NAME' in globals()}")
print(f"  全局里有 local_var 吗：{'local_var' in globals()}")

# 输出：
# --- 命名空间就是一张表 ---
#   函数内 locals() 的键：['local_var']
#   全局里有 GLOBAL_NAME 吗：True
#   全局里有 local_var 吗：False
#
# 【重点】local_var 写在函数里，只出现在函数那张表里，全局表里根本没有它
#         —— 这就是「作用域」的由来。参数和局部变量都在同一张表里。


# ==============================================================================
# 知识点 2：局部作用域 —— 函数内部的变量出不来
# ==============================================================================
#
# 【讲解】函数一被调用，Python 就给它新建一张「局部表」。
#   函数里的赋值，默认都写进这张表；函数执行完，这张表就被扔掉。
#
# 【重点】所以函数内的变量，出了函数就「不存在」，
#   这不是「值被清空了」，而是「名字根本查不到」。

number = 100          # 全局的 number


def local_demo():
    number = 1        # 这是另一个变量，只是恰好同名
    print(f"  函数内的 number = {number}")


print("\n--- 局部变量出了函数就没了 ---")
local_demo()
print(f"  函数外的 number = {number}")

try:
    print(local_var)
except NameError as e:
    print(f"  在函数外访问局部变量：{e}")

# 输出：
# --- 局部变量出了函数就没了 ---
#   函数内的 number = 1
#   函数外的 number = 100
#   在函数外访问局部变量：name 'local_var' is not defined
#
# 【注意】`number = 1` 没有改全局的 100，它只是「新建了一个同名的局部变量」。
#         这在业内叫「遮蔽」（shadowing）：
#         局部变量把全局变量挡住了，函数里看不见外面那个。


# ==============================================================================
# 知识点 3：全局作用域 —— 整个文件都能看见
# ==============================================================================
#
# 【讲解】写在函数外面的变量属于「全局命名空间」，整个文件都能读。
#   函数里「只读」一个全局变量，完全不需要任何声明。
# 【注意】局部变量只在「函数被调用期间」存在，全局变量活到模块结束。
#   想改全局变量必须用 global，而「偷偷改」只会新建一个局部变量（知识点 6）。

greeting = "你好"          # 全局


def say_hello(name):
    print(f"  {greeting}，{name}！")     # 直接读全局，合法


print("\n--- 全局变量：整个文件都能读 ---")
say_hello("小明")
say_hello("小红")

# 输出：
# --- 全局变量：整个文件都能读 ---
#   你好，小明！
#   你好，小红！


# ==============================================================================
# 知识点 4：内置作用域 —— Python 自带的那些名字
# ==============================================================================
#
# 【讲解】print、len、sum、max、range 这些名字，既不是你定义的，
#   也不在全局表里，它们住在一张最外层的表：内置命名空间。
#
# 【重点】查找顺序永远是：局部 → 外层函数 → 全局 → 内置。
#   所以你可以用全局变量「盖住」内置名字，也可以用局部变量盖住全局名字。

import builtins            # 内置命名空间就是一个模块


def use_builtin():
    """函数里没定义 len，就一层层往外找，最后在内置里找到了。"""
    print(f"  函数里直接用 len：{len('hello')}")


def shadow_len():
    """用局部变量盖住内置的 len。"""
    len = 100                       # 局部变量，遮蔽了内置函数
    print(f"  函数内的 len = {len}")


print("\n--- 内置作用域与遮蔽 ---")
use_builtin()
print(f"  'len' 在内置命名空间里吗：{'len' in dir(builtins)}")
shadow_len()
print(f"  函数外的 len 没受影响：{len('hello')}")

# 输出：
# --- 内置作用域与遮蔽 ---
#   函数里直接用 len：5
#   'len' 在内置命名空间里吗：True
#   函数内的 len = 100
#   函数外的 len 没受影响：5
#
# 【常见错误】如果你在文件开头写 `list = [1, 2, 3]`，
#         那后面所有 list(...) 的用法都会报 'list' object is not callable。
#         内置名字千万别拿来当变量名。


# ==============================================================================
# 知识点 5：LEGB 规则 —— 一个名字到底从哪儿来
# ==============================================================================
#
# 【讲解】LEGB 是四个单词的首字母，就是查找顺序：
#   L  Local（当前函数）→ E  Enclosing（外层函数）→ G  Global → B  Builtins
# 【重点】逐层往外找，找到第一个就停，找不到就 NameError。
#   所以「就近优先」：内层定义了，就永远看不到外层的同名变量；
#   内层没定义，就会去外层借。

level = "全局 G"


def outer():
    level = "外层 E"                        # E 层

    def inner_shadow():
        level = "内层 L"                    # L 层，离自己最近
        print(f"  自己定义了：{level}")

    def inner_borrow():
        print(f"  自己没定义：{level}")     # → 去 E 层借

    inner_shadow()
    inner_borrow()
    print(f"  outer 看到：{level}")


print("\n--- LEGB：就近优先，没有就往外借 ---")
outer()
print(f"  全局看到：{level}")

# 输出：
# --- LEGB：就近优先，没有就往外借 ---
#   自己定义了：内层 L
#   自己没定义：外层 E
#   outer 看到：外层 E
#   全局看到：全局 G
#
# 【重点】inner_shadow 有自己的 level，就只看自己的；inner_borrow 没有，
#         才去 E 层借。outer 和全局也都只认自己那层，互不干扰。


# ==============================================================================
# 知识点 6：global —— 声明「我要改的是全局那个」
# ==============================================================================
#
# 【讲解】在函数里给变量赋值，Python 默认认为你要创建局部变量；真想改全局的，
#   就在函数开头写 `global 变量名`。
# 【关键区别】只读全局变量不需要 global；想改全局变量必须写 global。

counter = 0


def increase():
    """修改全局变量，必须声明 global。"""
    global counter          # 告诉 Python：下面的 counter 是全局那个
    counter += 1


def read_counter():
    """只是读取，不需要 global。"""
    print(f"  读到的 counter = {counter}")


print("\n--- global：改全局要声明 ---")
increase()
increase()
read_counter()
print(f"  最终 counter = {counter}")

# 输出：
# --- global：改全局要声明 ---
#   读到的 counter = 2
#   最终 counter = 2


# ---------- 不写 global 会怎样？ ----------
total = 0


def broken_add():
    """想改全局 total，但忘了写 global。"""
    try:
        total = total + 1       # 被判定为局部变量，但赋值前就读了它
    except UnboundLocalError as e:
        print(f"  报错：{e}")


print("\n--- 忘了写 global ---")
broken_add()

# 输出：
# --- 忘了写 global ---
#   报错：cannot access local variable 'total' where it is not associated with a value
#
# 【为什么】函数体里只要出现 `total = ...`，Python 就在整个函数范围内把 total
#   判定为局部变量，哪怕赋值语句在后面 —— 所以 `total + 1` 读的是「还没赋值的
#   局部变量」，直接报错。
# 【常见错误】解决办法：加 global，或者用参数+返回值（推荐）。


def add_total(value, amount=1):
    """推荐写法：不碰全局，靠参数进、靠返回值出。"""
    return value + amount


total = add_total(total)

print(f"  用参数+返回值改：total = {total}")

# 输出：
#   用参数+返回值改：total = 1


# ==============================================================================
# 知识点 7：nonlocal —— 改「外层函数」的变量
# ==============================================================================
#
# 【讲解】嵌套函数里想改「外层函数的变量」，global 帮不上忙（那是全局的），
#   要用 nonlocal —— 它专门指向 E 层（Enclosing）。
# 【类比】global 是「改公司总部的文件」，nonlocal 是「改本部门的文件」。
# 【重点】nonlocal 只能用在嵌套函数里，而且外层必须真的有这个变量，
#   否则报 SyntaxError: no binding for nonlocal 'x' found。

def make_counter():
    """返回一个计数器函数，每次调用加 1。"""
    count = 0                   # 外层函数的局部变量

    def increment():
        nonlocal count          # 声明：改的是外层那个 count
        count += 1
        return count

    return increment


print("\n--- nonlocal：改外层函数的变量 ---")
c1 = make_counter()
print(f"  c1 连续调用：{c1()}, {c1()}, {c1()}")

c2 = make_counter()
print(f"  c2 连续调用：{c2()}, {c2()}")
print(f"  c1 再调一次：{c1()}")

# 输出：
# --- nonlocal：改外层函数的变量 ---
#   c1 连续调用：1, 2, 3
#   c2 连续调用：1, 2
#   c1 再调一次：4
#
# 【重点】c1 和 c2 各自记着自己的 count，互不干扰：每次调用 make_counter()
#         都会新建一个独立的 count。若不写 nonlocal，`count += 1` 会直接报
#         UnboundLocalError，原因和 broken_add 一样。


# ==============================================================================
# 知识点 8：闭包的雏形 —— 函数会「记住」外面的变量
# ==============================================================================
#
# 【讲解】make_counter 里的 increment 用到了外层的 count。
#   正常来说，make_counter 执行完，它的局部变量应该消失了，
#   但 increment 还能用 —— 因为 Python 把 count「打包」存在了函数对象里，
#   这个包叫**闭包**（closure）。
#
# 【类比】出门前把家里的钥匙揣兜里：家（外层函数）已经关门了，
#   但钥匙（闭包）还在你手上，随时能开门取东西。
#
# 【重点】闭包 = 内层函数 + 它引用的外层变量。这是装饰器、工厂函数的基础。

def make_multiplier(n):
    """返回一个「乘以 n」的函数。"""

    def multiply(x):
        return x * n            # n 来自外层，被闭包保存下来

    return multiply


print("\n--- 闭包：函数记住了外面的变量 ---")
double = make_multiplier(2)
triple = make_multiplier(3)

print(f"  double(10) = {double(10)}")
print(f"  triple(10) = {triple(10)}")
print(f"  double 记住的 n = {double.__closure__[0].cell_contents}")

# 输出：
# --- 闭包：函数记住了外面的变量 ---
#   double(10) = 20
#   triple(10) = 30
#   double 记住的 n = 2
#
# 【重点】double 和 triple 是同一个函数代码，但各自绑定了不同的 n，
#         所以结果不同。__closure__ 就是那个「钥匙串」，
#         里面装的是外层变量的值（cell_contents）。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 命名空间是一张「名字 → 对象」的表；locals() 看局部，globals() 看全局
# 2. 函数内的赋值默认写进局部表，函数一结束这张表就没了
# 3. 函数里读全局变量不用声明；要改全局变量必须写 global
# 4. 只写 `x = x + 1` 而没写 global，会得到 UnboundLocalError（x 被判成局部变量）
# 5. 内置名字（len、list、sum）住在内置命名空间，别拿来当变量名把它盖住
# 6. 查找顺序 LEGB：Local → Enclosing → Global → Builtins，就近优先
# 7. nonlocal 改外层函数的变量；global 改全局变量，两者不能混用
# 8. 闭包 = 内层函数 + 它引用的外层变量；make_counter/make_multiplier 都是典型例子
# 9. 想改状态时，优先「参数进、返回值出」；global 用得越少，代码越好测


