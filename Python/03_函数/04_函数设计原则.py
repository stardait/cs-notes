# ==============================================================================
# 知识点 1：单一职责 —— 一个函数只做一件事
# ==============================================================================
#
# 【讲解】判断函数是不是「只做一件事」，标准很简单：能不能用一句话说清，
#   而且句子里没有「并且」「然后」。「算平均分并且判等级然后打印报告」就是四件事。
# 【为什么不好】想复用「算平均分」时会把打印一起带过来；想改打印格式得读懂整个函数；
#   还没法单独测试：一调用就打印一堆东西。
# 【重点】函数越短越好，通常超过 20 行就该想想能不能拆。

def process_student_bad(name, scores):
    """一个函数干了四件事：算平均、判等级、打印、返回。"""
    avg = sum(scores) / len(scores)                                   # 1. 算平均
    level = "优秀" if avg >= 90 else "及格" if avg >= 60 else "不及格"   # 2. 判等级
    print(f"  【报告】{name}：平均 {avg:.1f}，等级 {level}")              # 3. 打印
    return level                                                      # 4. 返回


print("\n--- 反例：一个函数干太多事 ---")
print(f"  返回值：{process_student_bad('小明', [90, 85, 92])}")

# 输出：
# --- 反例：一个函数干太多事 ---
#   【报告】小明：平均 89.0，等级 及格
#   返回值：及格


# ---------- 正例：拆成三个各司其职的小函数 ----------
def average(scores):
    """只算平均分。"""
    return sum(scores) / len(scores)


def get_level(avg):
    """只判等级。"""
    if avg >= 90:
        return "优秀"
    if avg >= 60:
        return "及格"
    return "不及格"


def print_report(name, scores):
    """只负责打印，计算都交给上面两个函数。"""
    avg = average(scores)
    print(f"  【报告】{name}：平均 {avg:.1f}，等级 {get_level(avg)}")


print("\n--- 正例：拆成三个小函数 ---")
print_report("小明", [90, 85, 92])
print(f"  平均分能单独测：{average([90, 85, 92])}")
print(f"  等级能单独测：{get_level(59)}, {get_level(75)}, {get_level(95)}")

# 输出：
# --- 正例：拆成三个小函数 ---
#   【报告】小明：平均 89.0，等级 及格
#   平均分能单独测：89.0
#   等级能单独测：不及格, 及格, 优秀
#
# 【重点】拆开后每个函数都能单独测，改打印格式也只动 print_report 一处。


# ==============================================================================
# 知识点 2：纯函数与副作用
# ==============================================================================
#
# 【讲解】纯函数要满足两条：同样的输入永远返回同样的输出；
#   不碰任何外部状态（不打印、不写文件、不改全局、不改传入的可变对象）。
#   副作用就是「函数除了返回值之外，对外界造成的影响」。
# 【类比】纯函数像数学题 f(x) = 2x：x 给 3，答案永远是 6，算一百遍也不会弄脏纸。
#   副作用函数像「往账本上记账」：每调用一次，账本就变一次。

def add_tax(price, rate=0.06):
    """纯函数：结果只由参数决定。"""
    return round(price * (1 + rate), 2)


print("\n--- 纯函数：输入定输出 ---")
print(f"  add_tax(100) = {add_tax(100)}")
print(f"  add_tax(100) = {add_tax(100)}")
print(f"  add_tax(100) = {add_tax(100)}")

# 输出：
# --- 纯函数：输入定输出 ---
#   add_tax(100) = 106.0
#   add_tax(100) = 106.0
#   add_tax(100) = 106.0
#
# 【重点】同样的输入调三次，结果完全一样 —— 这才叫「可预测」。


discount_percent = 10


def apply_discount_bad(price):
    """副作用：每调用一次，就偷偷把全局折扣改大一点。"""
    global discount_percent
    discount_percent += 1
    return round(price * (100 - discount_percent) / 100, 2)


print("\n--- 副作用：偷偷改了全局 ---")
print(f"  第一次：{apply_discount_bad(100)}")
print(f"  第二次：{apply_discount_bad(100)}")
print(f"  第三次：{apply_discount_bad(100)}")
print(f"  折扣率已经被改成：{discount_percent}%")

# 输出：
# --- 副作用：偷偷改了全局 ---
#   第一次：89.0
#   第二次：88.0
#   第三次：87.0
#   折扣率已经被改成：13%
#
# 【为什么】输入都是 100，输出却次次不同 —— 它依赖并修改了外部状态，
#         测试结果取决于「之前被调用过几次」。
# 【重点】正确做法是把折扣率变成参数，让函数保持干净：


def apply_discount(price, percent=10):
    """纯函数：折扣率由参数决定，不改任何外部状态。"""
    return round(price * (100 - percent) / 100, 2)


print(f"  纯函数版：{apply_discount(100)}, {apply_discount(100)}, {apply_discount(100)}")

# 输出：
#   纯函数版：90.0, 90.0, 90.0


def add_bonus_bad(scores):
    """副作用：直接改了调用者的列表。"""
    for i in range(len(scores)):
        scores[i] += 5
    return scores


scores = [80, 90]
print("\n--- 副作用：改了传入的列表 ---")
print(f"  调用前：{scores}")
add_bonus_bad(scores)
print(f"  调用后：{scores}   ← 原列表被改了")

# 输出：
# --- 副作用：改了传入的列表 ---
#   调用前：[80, 90]
#   调用后：[85, 95]   ← 原列表被改了


def add_bonus_good(scores):
    """纯函数：造一个新列表，不动原数据。"""
    return [s + 5 for s in scores]


scores = [80, 90]
new_scores = add_bonus_good(scores)
print(f"  原列表还是：{scores}")
print(f"  新列表是：{new_scores}")

# 输出：
#   原列表还是：[80, 90]
#   新列表是：[85, 95]
#
# 【重点】「不改传入的可变对象」是极重要的一条纪律：别人把列表交给你，
#         默认是「借你看」，不是「送你随便改」。


# ==============================================================================
# 知识点 3：参数设计 —— 少、清楚、别让人猜
# ==============================================================================
#
# 【讲解】参数是函数的「操作面板」：按钮越多、标签越糊，用的人越容易按错。
#   1. 参数别太多：超过 4 个，就该考虑封装成字典或对象
#   2. 别用布尔旗标：create_report(data, True, False, True) 完全看不出意思
#   3. 单位写进名字：timeout_ms 比 t 清楚一万倍

# ---------- 布尔旗标：调用处变成「猜谜」 ----------
# 反面写法长这样（这里只注释，不运行）：
#     def create_report(data, is_admin, is_pdf, is_verbose): ...
#     create_report(rows, True, False, True)     ← 这三个 True/False 什么意思？
#
# 正解：把「模式」变成有名字的参数，并且强制用关键字传（加 *）。

def create_report(data, *, kind="user", output="html"):
    """kind / output 必须点名传，调用处一眼看懂。"""
    return f"{kind} 报表（{output}），共 {len(data)} 行"


print("\n--- 布尔旗标 → 有名字的参数 ---")
rows = ["订单1", "订单2", "订单3"]
print(f"  管理员 PDF：{create_report(rows, kind='admin', output='pdf')}")
print(f"  普通网页：{create_report(rows)}")

# 输出：
# --- 布尔旗标 → 有名字的参数 ---
#   管理员 PDF：admin 报表（pdf），共 3 行
#   普通网页：user 报表（html），共 3 行
#
# 【重点】布尔参数一旦超过一个，调用处就会变成 `f(x, True, False, True)` 的天书。
#         要么拆成几个函数，要么换成有含义的字符串参数。


# ---------- 参数名里带单位 ----------
# 反面写法 `def wait(t)`：t 是秒还是毫秒？只能去翻实现。正解是把单位写进名字：
#     def wait(timeout_ms)  → 调用处一眼看懂
# 【注意】工程代码里因为单位搞错导致的 bug 非常多，能写进名字就别省这几个字母。


# ==============================================================================
# 知识点 4：返回早（early return）—— 把嵌套拍平
# ==============================================================================
#
# 【讲解】「返回早」就是在函数开头先用 if 把异常情况挡掉并 return，
#   让主流程保持「一路平铺」，不用一层层往里缩进。
# 【类比】进地铁先安检：不合格的拦在门口（早 return），合格的顺着通道往前走。
# 【重点】能早返回就早返回，嵌套层数最好不超过两层。

def get_level_nested(score):
    """嵌套版：能跑，但要一层层读进去才知道主流程。"""
    if 0 <= score <= 100:
        if score >= 90:
            return "优秀"
        else:
            if score >= 60:
                return "及格"
            else:
                return "不及格"
    else:
        return "分数非法"


def get_level_early(score):
    """卫语句版：先把异常情况挡掉，主流程一路平铺。"""
    if not 0 <= score <= 100:
        return "分数非法"          # 哨兵条件，直接挡在门口
    if score >= 90:
        return "优秀"
    if score >= 60:
        return "及格"
    return "不及格"                # 剩下的自然就是不及格


print("\n--- 返回早：先挡异常，再走主流程 ---")
for s in (-5, 59, 75, 95):
    print(f"  {s:>3} 分：{get_level_early(s)}")

# 输出：
# --- 返回早：先挡异常，再走主流程 ---
#    -5 分：分数非法
#    59 分：不及格
#    75 分：及格
#    95 分：优秀
#
# 【重点】两个版本结果一样，但 get_level_early 的缩进是平的，
#         眼睛扫一遍就知道有几种情况，不用在脑子里记「我现在在哪一层」。


# ==============================================================================
# 知识点 5：文档字符串 —— 把「怎么用」写清楚
# ==============================================================================
#
# 【讲解】一份合格的 docstring 至少要说清四件事：
#   1. 这个函数干什么（一句话）
#   2. 每个参数是什么、什么类型、有什么约束
#   3. 返回什么、什么类型
#   4. 什么情况下会抛异常
# 【重点】docstring 是写给「调用者」看的：他不关心你内部怎么实现，只关心
#   怎么传参、会拿到什么。格式不必死板，但同一项目里要统一。

def calculate_bmi(weight_kg, height_m):
    """计算 BMI 指数。

    参数:
        weight_kg (float): 体重，单位千克，必须大于 0
        height_m (float): 身高，单位米，必须大于 0

    返回:
        float: BMI 值，保留一位小数

    异常:
        ValueError: 体重或身高不是正数时抛出

    示例:
        >>> calculate_bmi(70, 1.75)
        22.9
    """
    if weight_kg <= 0 or height_m <= 0:
        raise ValueError("体重和身高都必须是正数")
    return round(weight_kg / height_m ** 2, 1)


print("\n--- 文档字符串：参数、返回、异常 ---")
print(f"  70kg / 1.75m 的 BMI = {calculate_bmi(70, 1.75)}")

try:
    calculate_bmi(70, 0)
except ValueError as e:
    print(f"  非法输入：{e}")

print(f"  docstring 第一行：{calculate_bmi.__doc__.splitlines()[0]}")

# 输出：
# --- 文档字符串：参数、返回、异常 ---
#   70kg / 1.75m 的 BMI = 22.9
#   非法输入：体重和身高都必须是正数
#   docstring 第一行：计算 BMI 指数。
#
# 【注意】写清「异常」尤其重要：调用者才知道要 try 什么。


# ==============================================================================
# 知识点 6：命名 —— 好名字省掉一半注释
# ==============================================================================
#
# 【讲解】函数名的三条习惯：动词开头（get_ / calc_ / is_ / has_）、
#   见名知意（calc_total_price 比 calc 好）、返回布尔时用 is_ / has_ / can_。
# 【重点】函数名是「最小的文档」。名字起对了，很多注释都可以省掉。

def is_valid_email(address):
    """is_ 开头 → 一看就知道返回布尔值。"""
    return "@" in address and "." in address.split("@")[-1]


def calc_total_price(quantity, unit_price):
    """calc_ 开头 → 一看就知道是算出一个数。"""
    return quantity * unit_price


print("\n--- 命名：动词开头，见名知意 ---")
print(f"  is_valid_email('a@b.com') = {is_valid_email('a@b.com')}")
print(f"  is_valid_email('abc') = {is_valid_email('abc')}")
print(f"  calc_total_price(3, 19.9) = {calc_total_price(3, 19.9)}")

# 输出：
# --- 命名：动词开头，见名知意 ---
#   is_valid_email('a@b.com') = True
#   is_valid_email('abc') = False
#   calc_total_price(3, 19.9) = 59.699999999999996
#
# 【注意】最后一行出现浮点误差（19.9 * 3 不是精确的 59.7），这是第 1 章讲过的
#         老问题，跟函数设计无关；真要处理钱，请用 decimal 模块。


