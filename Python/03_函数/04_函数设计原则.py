# 【本章小结】
# ==============================================================================
#
# 1. 单一职责：一个函数只做一件事，能用一句话说清且没有「并且」
# 2. 纯函数：同样输入永远同样输出，不碰外部状态；副作用 = 打印、改全局、改参数
# 3. 别改传入的可变对象：别人是「借你看」，不是「送你改」
# 4. 参数要少、要有名字、单位写进变量名；布尔旗标是坏味道
# 5. 返回早（卫语句）：先用 if 挡掉异常，再让主流程平铺
# 6. docstring 要写清：干什么、参数、返回、会抛什么异常
# 7. 命名：动词开头、见名知意、布尔用 is_/has_/can_
# 8. 经验值：函数超过 20 行、参数超过 4 个、嵌套超过 2 层，就该重构了


