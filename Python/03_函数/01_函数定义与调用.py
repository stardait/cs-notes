# 练习 3：写一个函数 `statistics(numbers)`，一次返回（最小值, 最大值, 平均值）。
def statistics(numbers):
    """返回（最小值, 最大值, 平均值）

    参数:
        numbers

    返回:
        （最小值, 最大值, 平均值）
    """
    avg = sum(numbers) / len(numbers)
    return min(numbers),max(numbers),avg
