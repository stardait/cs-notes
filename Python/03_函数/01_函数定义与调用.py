# ==============================================================================
# 知识点 1：为什么需要函数？
# ==============================================================================
#
# 【讲解】函数就像一台「咖啡机」：按一下按钮（调用）出来一杯咖啡，按「大杯」
#   出来大杯 —— 这叫传参数。程序里也是：把反复使用的逻辑打包、起个名字。
#
# 【重点】函数的价值不只是「少打字」，更在于：改一处就处处生效、
#   有名字让代码自解释、能单独测试。这三点比省几行字重要得多。

# ---------- 反面教材：同样的逻辑抄三遍 ----------
print("\n--- 不用函数：复制粘贴 ---")
print(f"订单 A 总价：{2 * 20 * 0.8}")     # 同一个算式，抄了三遍
print(f"订单 B 总价：{5 * 20 * 0.8}")
print(f"订单 C 总价：{3 * 20 * 0.8}")

# 输出：
# --- 不用函数：复制粘贴 ---
# 订单 A 总价：32.0
# 订单 B 总价：80.0
# 订单 C 总价：48.0


# ---------- 用函数：写一次，到处调用 ----------
def order_total(quantity):
    """根据数量算出订单总价（单价 20 元，打八折）。"""
    unit_price = 20          # 单价
    discount = 0.8           # 八折
    return quantity * unit_price * discount


print("\n--- 用函数：写一次，到处叫 ---")
print(f"订单 A 总价：{order_total(2)}")
print(f"订单 B 总价：{order_total(5)}")
print(f"订单 C 总价：{order_total(3)}")

# 输出：
# --- 用函数：写一次，到处叫 ---
# 订单 A 总价：32.0
# 订单 B 总价：80.0
# 订单 C 总价：48.0
#
# 【重点】哪天折扣要从 0.8 改成 0.75，只改 discount 一行；复制粘贴得改三处。


# ==============================================================================
# 知识点 2：def —— 定义函数
# ==============================================================================
#
# 语法：
#     def 函数名(参数列表):
#         函数体（必须缩进 4 个空格）
#         return 返回值          # 这一行可以没有
#
# 【注意】定义函数 ≠ 执行函数。def 只是「把做法记下来」，真正跑起来是在
#   你写 `函数名()` 的那一刻 —— 括号才是「调用」。
# 【类比】def 是写菜谱，函数名加括号才是照着菜谱做菜。

print("\n--- 定义 vs 调用 ---")


def greet():
    """最简单的函数：不接收参数，也没有返回值。"""
    print("  你好，我是函数体内的代码")


print("1. 函数已经定义好了，但上面没有任何输出")
greet()                    # 加括号 → 调用，函数体才真正执行
print("2. 刚才那一行才是「调用」")

# 输出：
# --- 定义 vs 调用 ---
# 1. 函数已经定义好了，但上面没有任何输出
#   你好，我是函数体内的代码
# 2. 刚才那一行才是「调用」
#
# 【重点】定义时函数体一行都不执行；每调用一次就从头执行一次，局部变量也重建。


# ==============================================================================
# 知识点 3：参数 —— 让函数处理不同的数据
# ==============================================================================
#
# 【讲解】参数就是「投料口」：咖啡机投咖啡豆，函数投数据。
#   定义时括号里的名字叫「形参」（占位符），调用时真正传的值叫「实参」。
# 【重点】形参只在函数体内存在，出了函数就消失了（文件 03 细讲作用域）。


def introduce(name, age):
    """自我介绍：接收两个参数，用 f-string 拼一句话打印出来。"""
    print(f"  我叫{name}，今年{age}岁，明年{age + 1}岁。")


print("\n--- 带参数的函数 ---")
introduce("小明", 18)          # 按顺序传：name="小明"，age=18
introduce("小红", 20)          # 同一个函数，不同数据，不同输出

# 输出：
# --- 带参数的函数 ---
#   我叫小明，今年18岁，明年19岁。
#   我叫小红，今年20岁，明年21岁。
#
# 【注意】参数个数必须对上。少传、多传都会报 TypeError，文件 02 详细讲。


# ==============================================================================
# 知识点 4：返回值 —— return 和 print 根本不是一回事
# ==============================================================================
#
# 【常见错误】新手最常犯的错：以为函数里 print 了，外面就能拿到这个值。
#   print 是「说话」：念完就散了；return 是「交货」：能存进变量继续运算。
# 【重点】没有 return（或只写一个光秃秃的 return）的函数返回 None。
#         None 不是「不存在」，它是一个真实的值，类型是 NoneType。


def add_print(a, b):
    """只打印，不返回。"""
    print(f"  计算 {a} + {b} = {a + b}")


def add_return(a, b):
    """把结果返回出去，不打印。"""
    return a + b


print("\n--- 打印 vs 返回 ---")

result1 = add_print(2, 3)
print(f"add_print 的返回值：{result1}")

result2 = add_return(2, 3)
print(f"add_return 的返回值：{result2}")

print(f"返回的值还能继续算：{add_return(2, 3) + 100}")     # 5 + 100

# 输出：
# --- 打印 vs 返回 ---
#   计算 2 + 3 = 5
# add_print 的返回值：None
# add_return 的返回值：5
# 返回的值还能继续算：105
#
# 【重点】add_print 屏幕上明明看到了 5，但 result1 里是 None —— 两码事。


# ---------- return 会立刻结束整个函数 ----------
def find_first_negative(numbers):
    """返回列表里第一个负数；一个负数都没有就返回 None。"""
    for n in numbers:
        if n < 0:
            return n          # 立刻结束整个函数，后面的元素不再检查
    return None               # 循环跑完了还没返回过，才走到这里


print("\n--- return 会立刻结束函数 ---")
print(f"第一个负数：{find_first_negative([3, 7, -2, -5, 8])}")
print(f"没有负数时：{find_first_negative([1, 2, 3])}")

# 输出：
# --- return 会立刻结束函数 ---
# 第一个负数：-2
# 没有负数时：None
#
# 【注意】return 后面的代码永远不会执行，写了也是死代码。「先判断、早返回」
#         能让函数少一层缩进（文件 04 细讲）。


# ---------- 一次返回多个值 ----------
def min_max(numbers):
    """一次返回最小值和最大值（其实是打包成一个元组返回）。"""
    return min(numbers), max(numbers)


print("\n--- 一次返回多个值 ---")
low, high = min_max([4, 1, 9, 3])          # 元组解包
print(f"最小值={low}，最大值={high}")

# 输出：
# --- 一次返回多个值 ---
# 最小值=1，最大值=9
#
# 【重点】`return a, b` 不是「返回两个值」，而是返回一个元组 (1, 9)。
#         用 `x, y = 函数()` 接收时，Python 自动帮你拆开。


# ==============================================================================
# 知识点 5：docstring —— 给函数配一份说明书
# ==============================================================================
#
# 【讲解】把说明写在函数体的第一行，用三个引号包起来，就是 docstring。
#   它和普通注释 `#` 不同：注释只给人看、Python 直接忽略；
#   docstring 会被存进函数的 __doc__ 属性，程序也能读出来。
# 【重点】IDE 的悬停提示、help()、自动生成文档的工具，读的都是 docstring。
#   在 PyCharm / VS Code 里把光标放进括号敲 `"""` 再回车，会自动生成模板。


def area_of_circle(radius):
    """计算圆的面积。

    参数:
        radius (float): 圆的半径，应当大于 0

    返回:
        float: 圆的面积
    """
    return 3.14159 * radius ** 2


import inspect             # 标准库，这里只用它的 getdoc() 把说明打印得干净些

print("\n--- 读取 docstring ---")
print(inspect.getdoc(area_of_circle))      # getdoc 会去掉多余缩进，适合打印
print(f"\n圆的面积：{area_of_circle(2)}")

# 输出：
# --- 读取 docstring ---
# 计算圆的面积。
#
# 参数:
#     radius (float): 圆的半径，应当大于 0
#
# 返回:
#     float: 圆的面积
#
# 圆的面积：12.56636
#
# 【提示】没写 docstring 的函数，__doc__ 是 None。
#         在交互式环境里敲 help(area_of_circle) 能看到排版好的完整说明。


# ==============================================================================
# 知识点 6：函数也是对象
# ==============================================================================
#
# 【讲解】def 其实做了两件事：创建一个「函数对象」，再给它贴上名字。
#   就像 1、"abc"、[1, 2] 都是对象，函数同样是对象。
# 【为什么重要】既然函数是对象，它就能：赋值给别的变量（起别名）、
#   放进列表 / 字典、作为参数传给另一个函数 ← 装饰器、回调函数的基础
# 【重点】`add` 和 `add()` 是两回事：前者是函数对象本身（一台机器），
#         后者是调用它得到的结果（机器产出的咖啡）。


def add(a, b):
    return a + b


def multiply(a, b):
    return a * b


print("\n--- 函数是对象 ---")
print(f"type(add) = {type(add)}")
print(f"它是不是对象：{isinstance(add, object)}")

alias = add                    # 不加括号：把函数对象赋给 alias
print(f"alias(3, 4) = {alias(3, 4)}")

for func in [add, multiply]:   # 函数可以放进列表，循环里挨个调用
    print(f"  {func.__name__}(3, 4) = {func(3, 4)}")


def apply(func, x, y):
    """把 func 当成参数传进来，再调用它。"""
    return func(x, y)


print(f"apply(add, 10, 5) = {apply(add, 10, 5)}")
print(f"apply(multiply, 10, 5) = {apply(multiply, 10, 5)}")
print(f"apply(max, 10, 5) = {apply(max, 10, 5)}")      # 内置函数也是对象

# 输出：
# --- 函数是对象 ---
# type(add) = <class 'function'>
# 它是不是对象：True
# alias(3, 4) = 7
#   add(3, 4) = 7
#   multiply(3, 4) = 12
# apply(add, 10, 5) = 15
# apply(multiply, 10, 5) = 50
# apply(max, 10, 5) = 10
#
# 【重点】apply 这种「把函数当参数」的写法，就是 map / filter / sorted(key=...) 的原理。
#         现在能看懂 apply(max, 10, 5)，以后就能看懂 sorted(words, key=len)。


# ==============================================================================
# 知识点 7：【常见错误】新手必踩的 3 个坑
# ==============================================================================

print("\n--- 常见错误 1：忘写括号 ---")

value = add            # 少写了 ()
print(f"少写括号拿到的是：{type(value).__name__} 对象")
print(f"补上括号才是结果：{add(1, 2)}")

# 输出：
# --- 常见错误 1：忘写括号 ---
# 少写括号拿到的是：function 对象
# 补上括号才是结果：3
#
# 【常见错误】`value = add` 本身不报错，所以这个 bug 很隐蔽。


print("\n--- 常见错误 2：先调用，后定义 ---")

try:
    too_early()        # 此时 too_early 这个名字还不存在
except NameError as e:
    print(f"报错：{e}")


def too_early():
    return "现在才定义好"


# 输出：
# --- 常见错误 2：先调用，后定义 ---
# 报错：name 'too_early' is not defined
#
# 【注意】Python 从上往下执行，调用必须写在定义之后。但「函数体里引用后面
#         才定义的函数」是合法的：函数体的代码等调用时才执行，那时名字早就有了。


print("\n--- 常见错误 3：函数名和变量名撞车 ---")


def get_name():
    return "小明"


print(f"正常调用：{get_name()}")

get_name = "我把它覆盖了"      # 用变量名覆盖掉了函数对象
try:
    get_name()
except TypeError as e:
    print(f"覆盖之后再调用：{e}")

# 输出：
# --- 常见错误 3：函数名和变量名撞车 ---
# 正常调用：小明
# 覆盖之后再调用：'str' object is not callable
#
# 【常见错误】函数名也是普通变量名，重新赋值就把函数顶掉了。
#         所以别用 len、max、sum、list、str 这些内置名字当变量名。


