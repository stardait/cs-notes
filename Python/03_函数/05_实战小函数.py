# 知识点 3：字符串反转 —— 一行代码 vs 手写循环
# ==============================================================================
#
# 【需求】把字符串倒过来："hello" → "olleh"。
#
# 【讲解】Python 的切片语法 `s[start:stop:step]`，step 写 -1 就是「从后往前取」，
#   这是最 Pythonic 的写法。手写循环版能帮你理解它到底做了什么。
#
# 【重点】切片会生成一个新字符串，原来的不变 ——
#   字符串是不可变对象，所有「修改」其实都是「造一个新的」。

def reverse_string(text):
    """用切片反转字符串。"""
    return text[::-1]


def reverse_string_loop(text):
    """手写循环：从后往前一个个拼。"""
    result = ""
    for i in range(len(text) - 1, -1, -1):
        result += text[i]
    return result


text = "hello"
print("\n--- 字符串反转 ---")
print(f"  切片版：{reverse_string(text)}")
print(f"  循环版：{reverse_string_loop(text)}")
print(f"  中文也能转：{reverse_string('上海自来水来自海上')}")
print(f"  转完之后原变量还是：{text}")

# 输出：
# --- 字符串反转 ---
#   切片版：olleh
#   循环版：olleh
#   中文也能转：上海自来水来自海上
#   转完之后原变量还是：hello
#
# 【重点】`text[::-1]` 是 O(n) 的一次复制，比循环里 `result += ...` 快得多：
#   字符串拼接每次都要新建对象，循环越长越慢。


def is_palindrome(text):
    """判断回文：忽略大小写和空格后，正着读反着读一样。"""
    cleaned = text.lower().replace(" ", "")
    return cleaned == cleaned[::-1]


print("\n--- 顺便做个回文判断 ---")
print(f"  '上海自来水来自海上'：{is_palindrome('上海自来水来自海上')}")
print(f"  'A man a plan'：{is_palindrome('A man a plan')}")
print(f"  'hello'：{is_palindrome('hello')}")

# 输出：
# --- 顺便做个回文判断 ---
#   '上海自来水来自海上'：True
#   'A man a plan'：False
#   'hello'：False
#
# 【注意】'A man a plan' 反转后是 'nalp a nam A'，去空格小写也不相等，所以是 False；
#   真正回文的是 "A man a plan a canal Panama"。


