# 知识点 4：列表去重 —— set 快，但它会打乱顺序
# ==============================================================================
#
# 【需求】去掉列表里重复的元素。
#
# 【讲解】最直接的办法是 `set(items)`，但它有两个问题：
#   1. 顺序丢了（集合是无序的）
#   2. 元素必须可哈希（列表里套列表就不行）
#
#   想「去重但保持原顺序」，用 `dict.fromkeys(items)`：
#   字典的键不能重复，而且 Python 3.7+ 的字典保留插入顺序。

data = [3, 1, 3, 2, 1, 5]


def unique_by_set(items):
    """用集合去重：最快，但不保证顺序。"""
    return list(set(items))


def unique(items):
    """用字典的键去重：保持第一次出现的顺序。"""
    return list(dict.fromkeys(items))


print("\n--- 列表去重 ---")
print(f"  原始数据：{data}")
print(f"  set 去重：{unique_by_set(data)}")
print(f"  保序去重：{unique(data)}")
print(f"  如果需要有序，再排一下：{sorted(set(data))}")

# 输出：
# --- 列表去重 ---
#   原始数据：[3, 1, 3, 2, 1, 5]
#   set 去重：[1, 2, 3, 5]
#   保序去重：[3, 1, 2, 5]
#   如果需要有序，再排一下：[1, 2, 3, 5]
#
# 【重点】`unique` 保留了 3 第一次出现的位置，`set` 版本没有。
#   做「最近浏览记录」「标签列表」这类功能时，顺序很重要，别图省事用 set。
#
# 【注意】上面 set 版本这次恰好输出了升序，这是小整数的哈希特性带来的巧合，
#   不是保证！换成字符串或大数字，顺序就会变。别依赖它。


# ==============================================================================
# 知识点 5：计算平均分 —— 空列表怎么办？
# ==============================================================================
#
# 【需求】给一串分数，算平均分。
#
# 【边界】空列表不能做除法（会 ZeroDivisionError），必须单独处理。
#
# 【重点】「空输入」是最常见的边界情况。处理方式有两种：
#   1. 返回一个约定的值（这里返回 0.0）
#   2. 抛异常，强制调用者处理
#   选哪种取决于业务：统计报表返回 0 更友好，扣款金额就该直接报错。

def average(scores):
    """计算平均分；空列表返回 0.0。

    参数:
        scores (list): 分数列表

    返回:
        float: 平均分；列表为空时返回 0.0
    """
    if not scores:                # 空列表直接返回，避免除以 0
        return 0.0
    return sum(scores) / len(scores)


print("\n--- 计算平均分 ---")
print(f"  [90, 85, 92] 的平均分：{average([90, 85, 92])}")
print(f"  保留两位小数：{average([90, 85, 92]):.2f}")
print(f"  空列表：{average([])}")
print(f"  总分：{sum([90, 85, 92])}")

# 输出：
# --- 计算平均分 ---
#   [90, 85, 92] 的平均分：89.0
#   保留两位小数：89.00
#   空列表：0.0
#   总分：267
#
# 【注意】`average([])` 如果不写那三行判断，会直接抛
#   ZeroDivisionError: division by zero。


# ==============================================================================
# 知识点 6：把五个函数组装起来 —— 一个小报表
# ==============================================================================
#
# 【讲解】单个函数再漂亮，也要能组合起来解决真问题。
#   这里把 average 和 get_level 拼在一起，输出一张小报表。
#
# 【重点】组装时注意「每个函数只做一件事」：
#   get_level 只管判等级，report 只管排版，谁也别抢谁的活。

def get_level(score):
    """按平均分判等级。"""
    if score >= 90:
        return "优秀"
    if score >= 60:
        return "及格"
    return "不及格"


students = {
    "小明": [88, 92, 79],
    "小红": [95, 98, 91],
    "小刚": [56, 62, 48],
}


def print_report(students):
    """打印所有学生的成绩报表。"""
    print("  姓名    平均分   等级")
    for name, scores in students.items():
        avg = average(scores)
        print(f"  {name}    {avg:>5.1f}   {get_level(avg)}")


print("\n--- 小报表：把函数组装起来 ---")
print_report(students)

# 输出：
# --- 小报表：把函数组装起来 ---
#   姓名    平均分   等级
#   小明     86.3   及格
#   小红     94.7   优秀
#   小刚     55.3   不及格
#
# 【重点】注意 `{avg:>5.1f}`：`>` 右对齐、`5` 占 5 格、`.1f` 保留一位小数。
#   中文姓名宽度不齐，对齐会有点歪，实际项目里可以用更精细的格式化，
#   但这里已经能看出「函数拆好后，组装是一行行读得懂的代码」。


