# ==============================================================================
# 知识点 1：重复子问题 —— 递归变慢的元凶
# ==============================================================================
#
# 回顾第 03 个文件：fib(4) 的调用树有 9 个节点，但不同的 n 只有 0~4 五个，
# 一半以上的调用都在重复计算。fib(20) 更夸张：只有 21 个不同的 n，
# 却调用了 21891 次 —— 每多一层，重复量就翻倍，这就是「指数爆炸」。
#
# 【重点】这种「同一个子问题被反复求解」的现象，叫「重叠子问题」。
#   有重叠子问题，才有优化的空间；没有重叠（比如归并排序），缓存了也没用。
#
# 【类比】你算 1+1=2，算一次就够了，下次直接用答案。
#   可朴素的递归函数没有「草稿纸」，每次都要从头再算一遍。
#   「记忆化」就是给递归配一张草稿纸。

calls = 0                               # 统计函数被调用了多少次

def fib_naive(n):
    """朴素递归：没有任何缓存"""
    global calls
    calls += 1                          # 每进一次函数就记一笔
    if n < 2:
        return n
    return fib_naive(n - 1) + fib_naive(n - 2)

calls = 0
value = fib_naive(20)
print("--- 朴素递归有多浪费 ---")
print(f"fib(20) = {value}，调用 {calls} 次")
print(f"但不同的 n 只有 0~20 共 21 个")

# 输出：
# --- 朴素递归有多浪费 ---
# fib(20) = 6765，调用 21891 次
# 但不同的 n 只有 0~20 共 21 个
#
# 【重点】21891 次调用里，真正有用的只有 21 次，其余 21870 次全是重复劳动。
#   把这些答案记下来，第二次直接查表，就能省掉 99.9% 的时间。


# ==============================================================================
# 知识点 2：手动记忆化 —— 用字典当草稿纸
# ==============================================================================
#
# 【思路】用一个字典 memo 存「参数 → 结果」：
#   进入函数先查表：表里有，直接返回；
#   表里没有，老老实实算，算完把结果写进表里，再返回。
#
# 【重点】记忆化的三步，和查字典一模一样：
#   ① 先查：if n in memo: return memo[n]
#   ② 再算：没查到才真正计算
#   ③ 后存：memo[n] = result
#
# 【注意】第③步不能忘。只查不存，等于白查，每次还是重新算。

memo = {}                               # 草稿纸：{参数: 结果}
memo_calls = 0                          # 函数被调用的总次数
memo_hits = 0                           # 命中缓存的次数
memo_misses = 0                         # 真正计算的次数

def fib_memo(n):
    global memo_calls, memo_hits, memo_misses
    memo_calls += 1
    if n in memo:                       # ① 先查表
        memo_hits += 1
        return memo[n]
    memo_misses += 1
    if n < 2:                           # ② 表里没有，才真正计算
        result = n
    else:
        result = fib_memo(n - 1) + fib_memo(n - 2)
    memo[n] = result                    # ③ 算完存回表里
    return result

memo.clear()                            # 清空，保证从零开始统计
memo_calls = memo_hits = memo_misses = 0
value = fib_memo(20)

print("\n--- 手动记忆化 ---")
print(f"fib(20) = {value}")
print(f"函数调用 {memo_calls} 次：真正计算 {memo_misses} 次，命中缓存 {memo_hits} 次")
print(f"memo 里存了 {len(memo)} 个结果")

# 输出：
#
# --- 手动记忆化 ---
# fib(20) = 6765
# 函数调用 39 次：真正计算 21 次，命中缓存 18 次
# memo 里存了 21 个结果
#
# 【重点】调用次数从 21891 降到 39，计算量从指数级降到线性级。
#   21 次真实计算正好对应 0~20 这 21 个不同的 n，一次都没浪费。
#
# 【注意】为什么是 39 次调用，而不是 21 次？因为每个 n 第一次算出来之后，
#   还会被父节点再查一次。39 = 1（最初调用）+ 2 × 19（n=2..20 各发起两次子调用）。
#   第二次进来只是查表，不再重算，代价极小。

# 记忆化之后，fib(100) 也能瞬间算出来
print(f"\n记忆化版 fib(100) = {fib_memo(100)}")
print(f"memo 现在有 {len(memo)} 个结果")

# 输出：
#
# 记忆化版 fib(100) = 354224848179261915075
# memo 现在有 101 个结果
#
# 【注意】只算了一个 fib(100)，memo 却存了 101 个结果 —— 因为递归路上
#   把 0~99 全算了一遍。这就是「自顶向下」：从大问题出发，需要哪个小问题就算哪个。


# ==============================================================================
# 知识点 3：functools.lru_cache —— 一行装饰器搞定
# ==============================================================================
#
# 手动写 memo 要改函数体，代码变长还容易写错。
# Python 标准库 functools 提供了现成的装饰器：lru_cache。
#
# 【名字里的 LRU】Least Recently Used，最近最少使用。
#   缓存满了的时候，优先扔掉「最久没被用过」的那条。
#
# 【重点】用法只有两步：
#   1. 顶部写 from functools import lru_cache
#   2. 在函数上写 @lru_cache(maxsize=None)
#   函数体一个字都不用改，缓存自动生效。

from functools import lru_cache

@lru_cache(maxsize=None)                # maxsize=None 表示缓存不设上限
def fib_cache(n):
    if n < 2:
        return n
    return fib_cache(n - 1) + fib_cache(n - 2)

fib_cache.cache_clear()                 # 清掉之前的缓存，保证统计准确
print("\n--- lru_cache 版 ---")
print(f"fib(20) = {fib_cache(20)}")
print(f"缓存信息：{fib_cache.cache_info()}")

# 输出：
#
# --- lru_cache 版 ---
# fib(20) = 6765
# 缓存信息：CacheInfo(hits=18, misses=21, maxsize=None, currsize=21)
#
# 【重点】CacheInfo 的四个字段：
#   hits=18     命中次数：直接查表拿到的次数
#   misses=21   未命中次数：真正执行函数体的次数（正好 21 个不同的 n）
#   maxsize=None 缓存上限，None 表示不限制
#   currsize=21 当前缓存了多少条
#
# 【注意】hits + misses = 39，和手动记忆化的调用次数完全一致。
#   说明 lru_cache 做的就是「自动帮你查表、存表」，逻辑和我们手写的一模一样。

# cache_clear() 可以随时清空缓存，cache_info() 可以随时查看状态
fib_cache.cache_clear()
print(f"清空后：{fib_cache.cache_info()}")
print(f"重新算 fib(10) = {fib_cache(10)}，缓存变为 {fib_cache.cache_info()}")

# 输出：
#
# 清空后：CacheInfo(hits=0, misses=0, maxsize=None, currsize=0)
# 重新算 fib(10) = 55，缓存变为 CacheInfo(hits=8, misses=11, maxsize=None, currsize=11)
#
# 【注意】`functools.cache` 是 Python 3.9 之后提供的简写，
#   等价于 `lru_cache(maxsize=None)`，名字更短。看到了别不认识。


# ==============================================================================
# 知识点 4：四种写法对比 —— 从 21891 次到 20 次
# ==============================================================================
#
# 同一个斐波那契，我们有四种写法：
#   ① 朴素递归：代码最短，速度最慢
#   ② 手动字典记忆化：自顶向下，边算边记
#   ③ lru_cache：自顶向下，缓存自动化
#   ④ 迭代 DP：自底向上，从 0 开始往后推
#
# 【重点】④ 和 ①②③ 的方向正好相反：记忆化是「从 fib(100) 往下问，
#   问到 fib(0) 再往上答」；迭代 DP 是「从 fib(0) 开始，一步步推到 fib(100)」。
#   两者本质相同，都是「每个子问题只算一次」。

def fib_dp(n):
    """自底向上的迭代写法：只用两个变量滚动"""
    a, b = 0, 1                         # a=fib(i), b=fib(i+1)
    for _ in range(n):
        a, b = b, a + b                 # 同时更新，等价于 (a,b)=(b,a+b)
    return a

print("\n--- 四种写法对比 ---")
print(f"朴素递归 fib(20)   = {fib_naive(20)}，约 21891 次调用")
print(f"手动记忆化 fib(20) = {fib_memo(20)}，39 次调用 / 21 次计算")
print(f"lru_cache fib(20)  = {fib_cache(20)}，21 次计算 + 18 次命中")
print(f"迭代 DP fib(20)    = {fib_dp(20)}，循环 20 轮，20 次加法")

# 输出：
#
# --- 四种写法对比 ---
# 朴素递归 fib(20)   = 6765，约 21891 次调用
# 手动记忆化 fib(20) = 6765，39 次调用 / 21 次计算
# lru_cache fib(20)  = 6765，21 次计算 + 18 次命中
# 迭代 DP fib(20)    = 6765，循环 20 轮，20 次加法
#
# 【注意】这里 fib_cache(20) 命中 18 次，是因为前面 fib(10) 已缓存过 0~10。
#   缓存状态会影响 hits 的数字，但答案永远不变。
# 【重点】四个结果必须完全一致 —— 「不同的实现，相同的语义」。
#   优化性能的前提永远是不改变答案。

# 大数也不在话下：DP 版能轻松算到 fib(100)、fib(200)
print(f"\nDP 版 fib(100) = {fib_dp(100)}")
print(f"DP 版 fib(200) = {fib_dp(200)}")

# 输出：
#
# DP 版 fib(100) = 354224848179261915075
# DP 版 fib(200) = 280571172992510140037611932413038677189525
#
# 【注意】fib(200) 有 42 位数字。Python 整数没有上限，所以能精确算；
#   换成 C 的 long long，早就溢出了。
#
# 【注意】别用「跑一遍计时」来比较这几种写法：朴素递归以秒计，DP 版以微秒计，
#   差距大到不需要精确测量。而朴素递归算 fib(100) 约需 1.1 × 10^21 次调用，
#   按每秒 1 亿次算也要 35 万年 —— 这就是「算法复杂度」的威力。


# ==============================================================================
# 知识点 5：lru_cache 的容量上限与 LRU 淘汰
# ==============================================================================
#
# maxsize=None 表示缓存无限增长。如果函数的参数有很多种取值，
# 缓存会越吃越多内存 —— 这时候就该给它设个上限。
#
# 【重点】maxsize=3 的意思是「最多记 3 条」。第 4 条进来时，
#   把「最久没有被使用过」的那条扔掉，给新来的腾位置。

@lru_cache(maxsize=2)                   # 只记 2 条
def square(n):
    print(f"  真正计算 square({n})")     # 只有未命中时才会打印
    return n * n

print("\n--- maxsize=2 的 LRU 淘汰 ---")
for i in (1, 2, 3, 1):
    print(f"square({i}) = {square(i)}")
print(f"缓存信息：{square.cache_info()}")

# 输出：
#
# --- maxsize=2 的 LRU 淘汰 ---
#   真正计算 square(1)
# square(1) = 1
#   真正计算 square(2)
# square(2) = 4
#   真正计算 square(3)
# square(3) = 9
#   真正计算 square(1)
# square(1) = 1
# 缓存信息：CacheInfo(hits=0, misses=4, maxsize=2, currsize=2)
#
# 【重点】逐个看：算 1、算 2 → 缓存满（存 1、2）；
#   算 3 → 扔掉最久没用的 1，存 3（此时存 2、3）；
#   再算 1 → 1 已被扔，只能重新算，同时扔掉最久没用的 2。所以 4 次全未命中。
#
# 【注意】maxsize 设得太小，缓存频繁失效等于白缓存；设得太大又占内存。
#   不确定就用 None，但前提是参数种类有限（比如斐波那契的 n）。


# ==============================================================================
# 知识点 6：记忆化的边界 —— 不是所有函数都能缓存
# ==============================================================================
#
# 【限制 1】参数必须可哈希（hashable）
#   lru_cache 用参数当字典的 key，列表、字典、集合都不能当 key。
#   所以 merge_sort(arr) 这种「参数是列表」的函数，没法直接加缓存。

@lru_cache(maxsize=None)
def sum_list(nums):
    return sum(nums)

try:
    sum_list([1, 2, 3])
except TypeError as e:
    print("\n--- 限制 1：参数必须可哈希 ---")
    print(f"TypeError: {e}")

# 输出：
#
# --- 限制 1：参数必须可哈希 ---
# TypeError: unhashable type: 'list'
#
# 【注意】元组是可哈希的，所以 sum_list((1, 2, 3)) 可以正常工作。
#   真要对列表做缓存，得先把它转成元组：sum_list(tuple(nums))。

# 【限制 2】缓存不降低递归深度：记忆化只减少「重复计算」，不减少「调用层数」。
#   fib_memo(2000) 依然要往下递归 2000 层，照样爆栈。

memo.clear()
try:
    fib_memo(2000)
except RecursionError:
    print("\n--- 限制 2：缓存不解决深度问题 ---")
    print("fib_memo(2000) → RecursionError：缓存省了时间，但没省栈帧")
print(f"此时 1..2000 的结果一条都没缓存下来：memo 有 {len(memo)} 条")

# 输出：
#
# --- 限制 2：缓存不解决深度问题 ---
# fib_memo(2000) → RecursionError：缓存省了时间，但没省栈帧
# 此时 1..2000 的结果一条都没缓存下来：memo 有 0 条
#
# 【为什么】递归是「先钻到底，再往上返回」，爆栈发生在往下钻的路上。
#   还没钻到底就炸了，自然没有任何结果被存进 memo。
#   想算 fib(2000)，只能用迭代 DP（或者手动改写成显式栈）。
#
# 【重点】记忆化解决的是「时间」，不解决「深度」。
#   两个问题要分开治：时间用缓存，深度用循环。

# 【限制 3】返回值是可变对象时，缓存会被调用者改坏：缓存存的是引用，谁拿到都能改。

@lru_cache(maxsize=None)
def make_list(n):
    return [0] * n                      # 返回一个可变列表

first = make_list(3)
first.append(99)                        # 调用者手贱改了一下
print("\n--- 限制 3：缓存返回可变对象 ---")
print(f"第一次拿到后改成：{first}")
print(f"第二次调用 make_list(3)：{make_list(3)}")

# 输出：
#
# --- 限制 3：缓存返回可变对象 ---
# 第一次拿到后改成：[0, 0, 0, 99]
# 第二次调用 make_list(3)：[0, 0, 0, 99]
#
# 【重点】第二次调用拿到的不是干净的 [0, 0, 0]，而是被改过的 [0, 0, 0, 99]。
#   因为缓存里存的就是同一个列表对象。
#   解决办法：返回不可变对象（元组、字符串、数字），或在返回前做拷贝。
#
# 【限制 4】有副作用的函数不要缓存：打印、写文件、发请求、生成随机数，
#   这些「每次调用都该产生新效果」的函数一旦缓存，第二次就什么都不做了。


