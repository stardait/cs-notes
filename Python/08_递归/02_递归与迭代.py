# ==============================================================================
# 知识点 1：同一个问题，两种写法
# ==============================================================================
#
# 递归和迭代（循环）不是对立的两个世界，它们能解决同一批问题。
# 区别只在「你用哪种方式描述过程」：
#
#   迭代：告诉计算机「第一步做什么，第二步做什么……」—— 关注过程
#   递归：告诉计算机「大问题等于小问题加一点东西」—— 关注结构
#
# 下面三个例子，左边递归、右边循环，结果完全一样。

def sum_rec(n):
    """递归求和 1..n"""
    if n == 1:                          # 终止条件
        return 1
    return n + sum_rec(n - 1)           # 规模缩小

def sum_iter(n):
    """循环求和 1..n"""
    total = 0
    for i in range(1, n + 1):           # 一个一个加
        total += i
    return total

print("--- 求和：递归 vs 迭代 ---")
print(f"递归 sum_rec(100)  = {sum_rec(100)}")
print(f"迭代 sum_iter(100) = {sum_iter(100)}")

# 输出：
# --- 求和：递归 vs 迭代 ---
# 递归 sum_rec(100)  = 5050
# 迭代 sum_iter(100) = 5050


def reverse_rec(s):
    """递归反转字符串"""
    if len(s) <= 1:                     # 长度 0 或 1，本身就是反转结果
        return s
    return reverse_rec(s[1:]) + s[0]    # 先反转后面，再把第一个字符接上

def reverse_iter(s):
    """循环反转字符串：每次把新字符插到最前面"""
    result = ""
    for ch in s:
        result = ch + result
    return result

text = "Python"
print("\n--- 反转字符串：递归 vs 迭代 ---")
print(f"原字符串：{text}")
print(f"递归结果：{reverse_rec(text)}")
print(f"迭代结果：{reverse_iter(text)}")

# 输出：
#
# --- 反转字符串：递归 vs 迭代 ---
# 原字符串：Python
# 递归结果：nohtyP
# 迭代结果：nohtyP


def count_digits_rec(n):
    """递归数位数"""
    if n < 10:                          # 只剩一位，就是 1 位
        return 1
    return 1 + count_digits_rec(n // 10)  # 去掉个位，位数加 1

def count_digits_iter(n):
    """循环数位数"""
    count = 0
    while n > 0:
        count += 1
        n //= 10
    return count

print("\n--- 数位数：递归 vs 迭代 ---")
print(f"递归 count_digits_rec(2026)  = {count_digits_rec(2026)}")
print(f"迭代 count_digits_iter(2026) = {count_digits_iter(2026)}")

# 输出：
#
# --- 数位数：递归 vs 迭代 ---
# 递归 count_digits_rec(2026)  = 4
# 迭代 count_digits_iter(2026) = 4
#
# 【重点】三个例子的递归版都能用一句话说清：
#   「先处理小一号的问题，再补上自己这一层。」
#   循环版则要写清楚「从哪开始、到哪结束、每步怎么变」。
#   没有谁更高级，只有谁更贴合问题的结构。
#
# 【递归的隐藏成本】调用一次函数，Python 就在内存里建一个栈帧，保存参数、
#   局部变量和返回地址。递归最特殊的地方是「所有栈帧要同时存在」：
#   算 sum_rec(100) 时，sum_rec(1) 返回之前，外面 99 层全挂在那里等结果。
#   而循环只有一个 total 变量，反复用同一块内存。
#   所以递归的内存开销是 O(深度)，迭代是 O(1)；深度一大就会出事（见知识点 3）。
#   【注意】递归并不比循环「算得多」，它只是「算得绕」：同样的求和，
#   多了 100 次函数调用和栈帧创建销毁，只会更慢。


# ==============================================================================
# 知识点 2：递归树展开 —— 从一条链变成一棵树
# ==============================================================================
#
# 前面几个递归，每次只调用自己一次，画出来是一条链：
#
#   factorial(4) → factorial(3) → factorial(2) → factorial(1)
#
# 但斐波那契不一样：
#   fib(n) = fib(n-1) + fib(n-2)
# 一次调用会分叉成两个，再各自分叉……画出来是一棵**树**。
#
# 【重点】链式递归的开销是 O(n)，树形递归的开销可能是指数级 O(2^n)。

def fib_tree(n, depth=0):
    """打印斐波那契的调用树（只打印，不优化）"""
    print("  " * depth + f"fib({n})")   # 缩进表示层级
    if n < 2:                           # fib(0)=0, fib(1)=1
        return n
    return fib_tree(n - 1, depth + 1) + fib_tree(n - 2, depth + 1)

print("\n--- fib(4) 的调用树 ---")
result = fib_tree(4)
print(f"fib(4) = {result}")

# 输出：
#
# --- fib(4) 的调用树 ---
# fib(4)
#   fib(3)
#     fib(2)
#       fib(1)
#       fib(0)
#     fib(1)
#   fib(2)
#     fib(1)
#     fib(0)
# fib(4) = 3
#
# 【重点】数一数：一共 9 个节点，但不同的 n 只有 0、1、2、3、4 五个。
#   也就是说 fib(2) 被算了 2 次，fib(1) 被算了 3 次 —— 全是重复劳动！
#
# 【为什么】因为递归函数只知道自己这一层，不记得「刚才算过什么」。
#   这就是第 05 个文件「记忆化」要解决的问题。

# 用计数器量化一下「重复劳动」有多夸张
calls = 0

def fib_count(n):
    global calls
    calls += 1
    if n < 2:
        return n
    return fib_count(n - 1) + fib_count(n - 2)

print("\n--- 不同 n 的调用次数 ---")
for n in (5, 10, 15, 20, 25):
    calls = 0
    value = fib_count(n)
    print(f"fib({n:2d}) = {value:6d}，调用 {calls:6d} 次")

# 输出：
#
# --- 不同 n 的调用次数 ---
# fib( 5) =      5，调用     15 次
# fib(10) =     55，调用    177 次
# fib(15) =    610，调用   1973 次
# fib(20) =   6765，调用  21891 次
# fib(25) =  75025，调用 242785 次
#
# 【重点】n 每增加 5，调用次数大约变成 11 倍（斐波那契的黄金比例 1.618^5 ≈ 11）。
#   这就是「指数爆炸」：fib(40) 要调用约 3.3 亿次，fib(50) 约 400 亿次。
#   电脑不是算不出来，是算到天荒地老。
#
# 【注意】递归树不是画着好看的，它是你分析递归性能最直接的工具：
#   树有几个节点，函数就调用几次；树的深度，就是栈的最大深度。


# ==============================================================================
# 知识点 3：栈溢出 —— 递归的硬天花板
# ==============================================================================
#
# 栈帧要占内存，而调用栈的空间是有限的。
# 如果递归太深，栈被撑爆，程序就会崩溃 —— 这叫「栈溢出（stack overflow）」。
#
# Python 的做法很直接：默认只允许 1000 层，到了就抛 RecursionError。
# 【重点】这不是 bug，是保护机制。没有它，程序会直接段错误崩溃，连报错信息都没有。

def sum_to(n):
    if n == 1:
        return 1
    return n + sum_to(n - 1)

print("\n--- 栈溢出 ---")
print(f"sum_to(900) = {sum_to(900)}")    # 900 层，安全

try:
    print(f"sum_to(5000) = {sum_to(5000)}")   # 5000 层，超过默认上限
except RecursionError:
    print("sum_to(5000) → RecursionError：递归太深，栈溢出了")

print(f"迭代版 1..5000 = {sum(range(1, 5001))}")   # 迭代没有深度问题

# 输出：
#
# --- 栈溢出 ---
# sum_to(900) = 405450
# sum_to(5000) → RecursionError：递归太深，栈溢出了
# 迭代版 1..5000 = 12502500
#
# 【重点】同一件事，递归版挂了，迭代版毫无压力。
#   因为迭代只用了一个 total 变量，不存在「栈越叠越高」的问题。

# 把上限调高，可以让它跑完 —— 但这是治标不治本
import sys

sys.setrecursionlimit(10000)            # 上限提到 10000
print(f"\n调高上限后 sum_to(5000) = {sum_to(5000)}")
sys.setrecursionlimit(1000)             # 恢复默认，别影响后面的代码

# 输出：
#
# 调高上限后 sum_to(5000) = 12502500
#
# 【注意】调高上限有风险：
#   1. 在 Windows 上，层数太深可能直接让解释器崩溃，而不是抛 RecursionError
#   2. 它只解决「能不能跑完」，不解决「该不该用递归」
#   3. 5000 层栈帧的内存开销，比循环大得多

# 如果非要「用递归的思路 + 不受深度限制」，可以自己用列表当栈，把递归改成循环
# 这叫「显式栈」：递归用的是解释器的调用栈，我们改用堆内存里的 list

def sum_explicit_stack(n):
    """用显式栈模拟递归：把「待处理的任务」放进 list"""
    stack = [n]                         # 先放入最大的任务
    total = 0
    while stack:                        # 只要还有任务就继续
        x = stack.pop()                 # 取出一个任务
        if x == 0:
            continue
        total += x
        stack.append(x - 1)             # 把「小一号的任务」压回去
    return total

print(f"显式栈版 1..5000 = {sum_explicit_stack(5000)}")

# 输出：
#
# 显式栈版 1..5000 = 12502500
#
# 【注意】显式栈不受递归深度限制，但代码明显变难读了。
#   而且这个例子能成立，是因为加法满足交换律；
#   如果顺序重要（比如字符串拼接），显式栈要额外记录「返回后该做什么」，会更复杂。
#   所以：能用循环就用循环，别一上来就手写显式栈。
#
# 【补充】你可能会听说「尾递归」：把递归调用放在函数的最后一个动作，
#   返回值直接就是递归结果，不再做后续运算（例如 return f(n-1, acc+n)）。
#   支持尾递归优化的语言（如 Scheme）能把这种递归变成循环、不占栈。
#   但 CPython 明确不做这个优化，理由是它会破坏 traceback 信息。
#   【重点】所以别为了「尾递归」改写 Python 代码：收益为零，可读性反而下降。
#   在 Python 里要避免深递归，唯一可靠的办法就是改用循环。


# ==============================================================================
# 知识点 4：什么时候该用递归，什么时候该用循环
# ==============================================================================
#
# 【用递归】当问题的结构本身就是「嵌套」或「树」的时候：
#   1. 树形数据：文件目录、JSON、HTML DOM、嵌套列表、菜单
#   2. 分治算法：归并排序、快速排序、二分查找
#   3. 回溯搜索：全排列、组合、八皇后、数独
#   4. 数学定义天然递归：阶乘、斐波那契、汉诺塔
#
# 【用循环】当问题是「一条线」的时候：
#   1. 线性遍历：求和、找最大值、过滤、累加
#   2. 深度不可控：处理用户输入、遍历长链表、解析长字符串
#   3. 对性能敏感：循环没有函数调用开销
#
# 【一句话总结】结构是树 → 用递归；结构是线 → 用循环。

# 递归不可替代的典型场景：嵌套列表求和
# 你事先不知道它嵌套了多少层，循环根本不知道要写几重

def nested_sum(data):
    total = 0
    for x in data:
        if isinstance(x, list):         # 遇到列表，说明还能往里钻
            total += nested_sum(x)      # 交给递归处理这个子列表
        else:
            total += x                  # 普通数字，直接加
    return total

nested = [1, [2, 3, [4, 5]], 6, [[7]]]
print("\n--- 递归最擅长的场景：嵌套列表求和 ---")
print(f"数据：{nested}")
print(f"总和：{nested_sum(nested)}")

# 输出：
#
# --- 递归最擅长的场景：嵌套列表求和 ---
# 数据：[1, [2, 3, [4, 5]], 6, [[7]]]
# 总和：28
#
# 【重点】这个函数只有 6 行，却能处理任意深度的嵌套。
#   用循环写，你得手动维护一个「待处理列表」的栈，代码会立刻变得难懂。
#   【为什么】因为数据是树形的，而递归天生就是为树形结构准备的。
#
# 【注意】嵌套再深也有极限。如果嵌套层数可能超过 1000，
#   要么改用显式栈，要么在数据源头限制深度。

# 【常见错误】拿递归去处理线性的大数据
print("\n--- 反例：用递归处理大数据 ---")
try:
    sum_to(100000)                      # 10 万层，想都别想
except RecursionError:
    print("sum_to(100000) → RecursionError：10 万条数据请用循环")

print("循环版 1..100000 =", sum(range(1, 100001)))

# 输出：
#
# --- 反例：用递归处理大数据 ---
# sum_to(100000) → RecursionError：10 万条数据请用循环
# 循环版 1..100000 = 5000050000


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 递归和迭代能解决同一批问题：递归描述结构，迭代描述过程
# 2. 递归的内存开销是 O(深度)，因为所有栈帧要同时挂在内存里
# 3. 链式递归（阶乘）是 O(n)；树形递归（斐波那契）可能是指数级 O(2^n)
# 4. 展开递归树就能看出重复计算：fib(4) 只用到 5 个不同的 n，却调用了 9 次
# 5. Python 默认递归上限 1000 层，超过抛 RecursionError，这是保护机制
# 6. 显式栈可以绕过深度限制，但代码更复杂，只在必要时用
# 7. Python 不支持尾递归优化，写成尾递归也照样爆栈
# 8. 判断标准：结构是树用递归，结构是线用循环


