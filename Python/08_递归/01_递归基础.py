# ==============================================================================
# 知识点 1：递归是什么？—— 函数自己调用自己
# ==============================================================================
#
# 【概念】递归（recursion）：一个函数在执行过程中，直接或间接地调用自己。
#
# 【类比 1】俄罗斯套娃：打开一层，里面还有一个一模一样的娃娃，
#          一直打开到最小的那个，打不开了为止。
# 【类比 2】查词典：查「递归」这个词，解释里写着「参见：递归」。
#          如果你真照做，就会永远查下去 —— 所以递归必须有「停下来的地方」。
#
# 【重点】递归不是「循环的另一种写法」，而是「把大问题交给一个更小的同类问题」。
#   写递归时，你只要相信「小一号的问题已经解决了」，不要在脑子里展开每一层。

def countdown(n):
    """倒计时：打印 n, n-1, ..., 1，然后发射"""
    if n <= 0:                  # 终止条件：减到 0 就不再往下
        print("发射！")
        return                  # 关键：return 让这一层结束，不再递归
    print(n)                    # 先做自己的事：报数
    countdown(n - 1)            # 再把「报 n-1」的任务交给下一层

print("--- 倒计时 ---")
countdown(3)

# 输出：
# --- 倒计时 ---
# 3
# 2
# 1
# 发射！
#
# 【注意】countdown 没有返回值，它靠「每层做一件事」完成工作。
#         这种「动作型递归」和后面阶乘那种「返回值型递归」是两种不同的写法。


# ==============================================================================
# 知识点 2：递归三要素 —— 少一个就会出事
# ==============================================================================
#
# 写递归之前，先在心里回答三个问题：
#
#   ① 终止条件（base case）：什么时候停下来？停下来时返回什么？
#   ② 递归调用（recursive case）：大问题怎么用「小一号的问题」表示？
#   ③ 规模缩小：每次调用，问题必须比上一次更小、更靠近终止条件。
#
# 【重点】三要素缺一不可：
#   缺 ① → 函数永远停不下来 → RecursionError（栈溢出）
#   缺 ② → 那根本不是递归，只是个普通函数
#   缺 ③ → 即使写了终止条件，也永远走不到 → 还是 RecursionError
#
# 下面用「求列表长度」来示范：规模缩小 = 列表变短。

def length(items):
    """返回列表 items 的长度（用递归实现）"""
    if not items:               # ① 终止条件：空列表长度为 0
        return 0
    return 1 + length(items[1:])  # ② 递归调用 + ③ 规模缩小（列表少一个元素）

print("\n--- 递归三要素：求列表长度 ---")
print(f"length([])              = {length([])}")
print(f"length([1, 2, 3])       = {length([1, 2, 3])}")
print(f"length(['a','b','c','d']) = {length(['a', 'b', 'c', 'd'])}")

# 输出：
#
# --- 递归三要素：求列表长度 ---
# length([])              = 0
# length([1, 2, 3])       = 3
# length(['a','b','c','d']) = 4
#
# 【为什么】length(items[1:]) 的答案可以完全信任：假设它真能算出「去掉第一个
#   元素后的长度」，那 1 + 它 就是总长度。这种思考方式叫「递归信任」。
#
# 【注意】items[1:] 每次都会复制出一个新列表，代价是 O(n)，
#         所以这个写法只是为了演示，实际求长度请直接用 len()。


# ==============================================================================
# 知识点 3：阶乘 —— 递归的「Hello World」
# ==============================================================================
#
# 阶乘的数学定义本身就是递归的：
#     n! = n × (n-1)!      （当 n ≥ 1）
#     0! = 1               （终止条件，数学家规定的）
#
# 比如 5! = 5 × 4! = 5 × 4 × 3! = 5 × 4 × 3 × 2 × 1 = 120
#
# 【重点】数学公式里出现了「自己」，代码里就写「自己调用自己」。

def factorial(n):
    if n == 0:                      # 终止条件：0! 定义为 1
        return 1
    return n * factorial(n - 1)     # 递归调用：n! 依赖 (n-1)!

print("\n--- 阶乘 ---")
for n in range(0, 11):
    print(f"{n}! = {factorial(n)}")

print(f"20! = {factorial(20)}")

# 输出：
#
# --- 阶乘 ---
# 0! = 1
# 1! = 1
# 2! = 2
# 3! = 6
# 4! = 24
# 5! = 120
# 6! = 720
# 7! = 5040
# 8! = 40320
# 9! = 362880
# 10! = 3628800
# 20! = 2432902008176640000
#
# 【注意】Python 的整数没有大小上限，20! 也能精确算出来。
#         换成 C 或 Java 的 int，13! 就已经溢出了。

# 【重点】循环也能做同样的事（result = 1; for i in range(2, n+1): result *= i）。
#   递归和循环能解决同一批问题，区别在「思路」而不在「能力」：
#   递归更贴近数学定义，循环更省内存 —— 第 02 个文件专门比较。


# ==============================================================================
# 知识点 4：累加 —— 和阶乘长得一模一样的递归
# ==============================================================================
#
# 把阶乘的「乘」换成「加」，就是累加：
#     S(n) = n + S(n-1)      （当 n ≥ 2）
#     S(1) = 1               （终止条件）
#
# 【重点】递归函数的骨架是固定的：先写终止条件，再写「自己 = 小一号 + 自己的部分」。
#   阶乘是 n * f(n-1)，累加是 n + f(n-1)，只有运算符不同。

def sum_to(n):
    """返回 1 + 2 + ... + n"""
    if n == 1:                      # 终止条件
        return 1
    return n + sum_to(n - 1)        # 规模缩小：n → n-1

def sum_formula(n):
    """用等差数列公式直接算，O(1) 时间"""
    return n * (n + 1) // 2

print("\n--- 累加 ---")
for n in (10, 100, 500):
    print(f"1 + 2 + ... + {n} = {sum_to(n)}，公式验证：{sum_formula(n)}")

# 输出：
#
# --- 累加 ---
# 1 + 2 + ... + 10 = 55，公式验证：55
# 1 + 2 + ... + 100 = 5050，公式验证：5050
# 1 + 2 + ... + 500 = 125250，公式验证：125250
#
# 【注意】这里故意只加到 500，不敢加到 1000 —— 因为递归默认只能用约 1000 层，
#         加到 1000 就会超深。这个坑在下面的知识点 6 会详细讲。
#
# 【常见错误】把终止条件写成 if n == 0: return 0 也能跑，
#   但这样 S(0) = 0 是额外定义出来的。写递归前要想清楚：
#   「最小的问题是什么？它的答案是多少？」想不清楚，递归一定写错。


# ==============================================================================
# 知识点 5：递归的执行过程 —— 压栈、触底、弹栈
# ==============================================================================
#
# 函数每被调用一次，Python 都会在「调用栈（call stack）」上压入一个栈帧（frame），
# 里面保存：这次调用的参数、局部变量、以及「返回后该回到哪一行继续执行」。
#
# 可以想象成一个叠盘子的架子：
#   进入一层函数 → 放一个盘子（压栈）
#   函数返回     → 拿走一个盘子（弹栈）
#
# 递归的执行分三个阶段：
#   ① 下行：一层层调用，栈越叠越高，直到碰到终止条件
#   ② 触底：最小的问题直接给出答案
#   ③ 上行：一层层返回，每层用「下一层的答案」算出自己的答案
#
# 下面把缩进打印出来，你就能亲眼看到这三步：

def factorial_trace(n, depth=0):
    """带缩进追踪的阶乘，depth 只用来控制缩进，不参与计算"""
    indent = "  " * depth
    print(f"{indent}→ 进入 factorial({n})")
    if n == 1:                                      # 触底
        print(f"{indent}← 触底，返回 1")
        return 1
    sub = factorial_trace(n - 1, depth + 1)         # 下行：先算小一号的
    result = n * sub                                # 上行：用子结果算自己
    print(f"{indent}← 返回 {n} * {sub} = {result}")
    return result

print("\n--- factorial(4) 的执行过程 ---")
factorial_trace(4)

# 输出：
#
# --- factorial(4) 的执行过程 ---
# → 进入 factorial(4)
#   → 进入 factorial(3)
#     → 进入 factorial(2)
#       → 进入 factorial(1)
#       ← 触底，返回 1
#     ← 返回 2 * 1 = 2
#   ← 返回 3 * 2 = 6
# ← 返回 4 * 6 = 24
#
# 【重点】注意返回的顺序：最后进入的最先返回（后进先出），这就是「栈」。
#         4! 的答案不是一次算出来的，而是等 1! 出来后，2!、3!、4! 依次弹出来的。
#
# 【为什么】print 的顺序是「先全部进入，再依次返回」，因为
#   print(f"{indent}← ...") 写在递归调用之后，必须等下一层返回才能执行。


# ==============================================================================
# 知识点 6：递归深度限制 —— Python 不让你无限套娃
# ==============================================================================
#
# 每压一个栈帧都要占内存。如果递归没有尽头，内存迟早被吃光，
# 这种崩溃叫「栈溢出（stack overflow）」。Python 的做法是提前设一个上限：
#   默认 1000 层，超过就抛 RecursionError，让程序体面地报错而不是直接崩溃。
#
# 【重点】这个上限不是「能算多大的数」，而是「能套多少层」。
#   factorial(500) 只要 500 层，没问题；factorial(2000) 要 2000 层，直接报错。

import sys

print("\n--- 递归深度限制 ---")
print(f"当前递归深度上限：{sys.getrecursionlimit()}")

def dive(n):
    """往下钻 n 层，用来测试深度"""
    if n == 0:                      # 终止条件
        return "触底成功"
    return dive(n - 1)

print(f"dive(900)  = {dive(900)}")   # 900 层，安全

try:
    dive(5000)                      # 5000 层，超过上限
except RecursionError as e:
    print(f"dive(5000) 报错：{e}")

# 输出：
#
# --- 递归深度限制 ---
# 当前递归深度上限：1000
# dive(900)  = 触底成功
# dive(5000) 报错：maximum recursion depth exceeded
#
# 【注意】上限写的是 1000，但从模块顶层代码开始调用时，
#         顶层本身已经占了 1~2 层栈，所以实际能递归的层数约为 998 层。
#         不同 Python 版本可能差一两层，不要卡着边界写代码。

# 可以手动调高上限，但要知道自己在干什么
sys.setrecursionlimit(5000)         # 把上限提到 5000
print(f"\n调高后上限：{sys.getrecursionlimit()}")
print(f"dive(4000)  = {dive(4000)}")
sys.setrecursionlimit(1000)         # 立刻恢复，避免影响后面的代码
print(f"已恢复上限：{sys.getrecursionlimit()}")

# 输出：
#
# 调高后上限：5000
# dive(4000)  = 触底成功
# 已恢复上限：1000
#
# 【注意】不要养成「一报错就 setrecursionlimit」的习惯：
#   1. 调得太高，可能让解释器直接崩溃（连报错的机会都没有）
#   2. 真正的问题是「这个问题本来就不该用递归」，应该换循环或显式栈
#   3. 递归 4000 层带来的内存和速度开销，往往比你想的大得多

# ==============================================================================
# 知识点 7：新手最常犯的三个错误
# ==============================================================================
#
# 【常见错误 1】忘记写终止条件
#   函数会一直调用自己，直到撞上 1000 层上限，抛 RecursionError。

def forget_base(n):
    return forget_base(n + 1)       # 没有 if，永远停不下来

try:
    forget_base(0)
except RecursionError:
    print("\n【错误 1】忘记终止条件 → RecursionError")

# 输出：
#
# 【错误 1】忘记终止条件 → RecursionError
#
# 【常见错误 2】递归调用写了，但忘了 return
#   结果不是报错，而是悄悄返回 None —— 这种错误最难查。

def lose_return(n):
    if n == 1:
        return 1
    lose_return(n - 1)              # 递归调用了，但没 return，结果直接丢掉

print(f"【错误 2】lose_return(5) = {lose_return(5)}")

# 输出：
#
# 【错误 2】lose_return(5) = None
#
# 【为什么】函数没有 return 语句时，Python 默认返回 None。
#   这里子问题的结果虽然算出来了，但没有交回给上一层，调用者拿到的是 None。
#   整个过程不会报错，等到你拿它去做运算时才会炸 —— 所以这种 bug 最难查。
#
# 【注意】如果你写成 `return n * lose_return(n - 1)` 但漏掉了最外层的 return，
#   内层返回 None 后，None 还会参与乘法，直接抛 TypeError：
#   unsupported operand type(s) for *: 'int' and 'NoneType'

# 【常见错误 3】规模没有缩小
#   终止条件写了，但每次调用参数没变，等于永远到不了终点。

def no_shrink(n):
    if n == 0:                      # 写了终止条件
        return 0
    return n + no_shrink(n)         # 但传进去的还是 n，规模没变！

try:
    no_shrink(5)
except RecursionError:
    print("【错误 3】规模没有缩小 → RecursionError")

# 输出：
#
# 【错误 3】规模没有缩小 → RecursionError
#
# 【重点】检查递归函数时，按顺序问自己三句话：
#   1. 最小的那个问题是什么？我给它写答案了吗？
#   2. 我调用自己时，参数真的变小了吗？
#   3. 我把子问题的结果 return 出去了吗？


