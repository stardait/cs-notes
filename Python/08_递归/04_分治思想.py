# 知识点 3：归并排序 —— 先分到底，再合并上来
# ==============================================================================
#
# 【思路】
#   ① 分解：把列表从中间切成两半
#   ② 解决：递归地把左半边、右半边分别排好序
#   ③ 合并：把两个「已经有序」的列表合并成一个有序列表
#
# 【重点】归并排序的灵魂在「合并」这一步（merge）：
#   两个有序列表，各拿一个指针从头开始比，谁小就先放谁，指针往后走。
#   这个合并操作只要 O(n) 时间，因为每个元素只被看一次。
#
# 【类比】两摞已经按大小排好的扑克牌，你要合成一摞有序的：
#   每次比较两摞最上面的牌，把小的那张拿出来放好，重复到拿完。

def merge(left, right):
    """合并两个有序列表，返回一个新的有序列表"""
    result = []
    i = j = 0                           # 两个指针，分别指向 left 和 right
    while i < len(left) and j < len(right):
        if left[i] <= right[j]:         # 左边的更小（或相等）
            result.append(left[i])
            i += 1
        else:                           # 右边的更小
            result.append(right[j])
            j += 1
    result.extend(left[i:])             # 把剩下的直接接上
    result.extend(right[j:])
    return result

def merge_sort(arr):
    """归并排序：返回排好序的新列表"""
    if len(arr) <= 1:                   # ① 只有一个元素，天然有序
        return arr
    mid = len(arr) // 2
    left = merge_sort(arr[:mid])        # ② 递归排左半边
    right = merge_sort(arr[mid:])       # ③ 递归排右半边
    merged = merge(left, right)         # ④ 合并两个有序列表
    print(f"合并 {left} + {right} → {merged}")
    return merged

print("\n--- 归并排序 ---")
data = [38, 27, 43, 3, 9, 82, 10]
print(f"排序前：{data}")
print(f"排序后：{merge_sort(data)}")

# 输出：
#
# --- 归并排序 ---
# 排序前：[38, 27, 43, 3, 9, 82, 10]
# 合并 [27] + [43] → [27, 43]
# 合并 [38] + [27, 43] → [27, 38, 43]
# 合并 [3] + [9] → [3, 9]
# 合并 [82] + [10] → [10, 82]
# 合并 [3, 9] + [10, 82] → [3, 9, 10, 82]
# 合并 [27, 38, 43] + [3, 9, 10, 82] → [3, 9, 10, 27, 38, 43, 82]
# 排序后：[3, 9, 10, 27, 38, 43, 82]
#
# 【重点】输出的顺序很有意思：先出现的是「最小的合并」，最后才是「总合并」。
#   因为递归会先钻到最底层（单个元素），触底之后才开始一层层往上合并。
#   「先分到底，再合上来」，这八个字就是归并排序的全部。
#
# 【注意】merge 里用 `<=` 而不是 `<`，是为了保证「相等元素保持原来的先后顺序」。
#   这叫「稳定排序」。如果写成 `<`，相等元素可能被换位置，稳定性就破坏了。
#
# 【为什么】归并排序为什么是 O(n log n)？
#   拆分：每次对半切，切 log2(n) 层。
#   合并：每一层把所有元素过一遍，是 O(n)。
#   合起来 O(n log n)。比冒泡排序的 O(n²) 快得多。


