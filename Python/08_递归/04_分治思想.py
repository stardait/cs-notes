# 【本章小结】
# ==============================================================================
#
# 1. 分治三步：分解（切小）、解决（递归到足够小）、合并（拼答案）
# 2. 二分查找：每次扔掉一半，O(log n)，前提是数组必须有序
# 3. 归并排序：先递归排两半，再合并两个有序列表，O(n log n)，稳定
# 4. 快速排序：先按基准分区，再递归排两边，不需要合并，平均 O(n log n)
# 5. 快排最坏 O(n²)：已排序数组 + 每次选第一个当基准，会退化成一条链
# 6. log2(n) = 把 n 反复除以 2 到 1 的次数，是分治高效的根本原因
# 7. 二分查找用循环更好；归并和快排用递归更自然


