# 这一节要用的工具：Counter（计数器）和 defaultdict（带默认值的字典）
from collections import Counter, defaultdict
# ==============================================================================
# 应用 1：词频统计 —— 统计每样东西出现了几次
# ==============================================================================
#
# 需求：一句话里每个词出现了几次？
#
# 核心思路只有一句：用一个字典记「词 → 次数」，
# 遇到一个词，就把它的计数加 1；没见过的词从 0 开始。

print("--- 需求：统计每个词出现的次数 ---")

sentence = "苹果 香蕉 苹果 橘子 香蕉 苹果"
words = sentence.split()            # split() 按空格切成列表
print("切词：", words)

# 输出：
# --- 需求：统计每个词出现的次数 ---
# 切词： ['苹果', '香蕉', '苹果', '橘子', '香蕉', '苹果']

# ---------- 写法 1：先判断键在不在（最直白，新手最好懂） ----------
counts = {}
for w in words:
    if w in counts:                 # 见过 → 加 1
        counts[w] += 1
    else:                           # 没见过 → 从 1 开始
        counts[w] = 1
print("\n写法 1：", counts)

# 输出：
# 写法 1： {'苹果': 3, '香蕉': 2, '橘子': 1}

# ---------- 写法 2：用 get(键, 0) 省掉 if（最常用） ----------
#
# 【重点】counts.get(w, 0) 的意思是"有就取原数，没有就当 0"，
#         然后再 +1 存回去。一行顶三行，是 Python 里的经典套路。

counts_get = {}
for w in words:
    counts_get[w] = counts_get.get(w, 0) + 1
print("写法 2：", counts_get)

# 输出：
# 写法 2： {'苹果': 3, '香蕉': 2, '橘子': 1}
#
# 【注意】两个字典的内容一样，但键的顺序都是「第一次出现的顺序」：
#         苹果、香蕉、橘子 —— 因为字典记住插入顺序。

# ---------- 写法 3：Counter，一行搞定 ----------
#
# 【重点】collections.Counter 就是专门干这件事的：
#         它长得像字典，但是「查不存在的键返回 0」而不是报 KeyError。

counter = Counter(words)
print("\n写法 3：", counter)
print("最多的两个：", counter.most_common(2), "；查不存在的词：", counter["西瓜"])

# 输出：
# 写法 3： Counter({'苹果': 3, '香蕉': 2, '橘子': 1})
# 最多的两个： [('苹果', 3), ('香蕉', 2)] ；查不存在的词： 0
#
# 【重点】Counter 打印时按次数从多到少排，而普通字典按插入顺序。
# 【注意】counter["西瓜"] 返回 0，不报 KeyError —— 这是 Counter 特有的行为。

# ---------- 排序：把次数从多到少排出来 ----------
#
# 【重点】sorted(字典.items(), key=lambda kv: kv[1], reverse=True)
#         是「按值排序」的标准写法：kv[0] 是键，kv[1] 是值。

print("\n--- 排行榜 ---")
ranked = sorted(counts.items(), key=lambda kv: kv[1], reverse=True)
for word, n in ranked:
    print(f"{word}：{n} 次")

# 输出：
# --- 排行榜 ---
# 苹果：3 次
# 香蕉：2 次
# 橘子：1 次
#
# 【常见错误】sorted 默认按「键」排，不是按值排！要按值排必须写 key=lambda kv: kv[1]。
print("\n默认排序只是按键：", sorted(counts.items()))

# 输出：
# 默认排序只是按键： [('橘子', 1), ('苹果', 3), ('香蕉', 2)]


# ==============================================================================
# 应用 2：分组聚合 —— 把数据按某个字段归类，再统计
# ==============================================================================
#
# 需求：有一批员工记录，要按部门分组，并算出每个部门的平均工资。
#
# 这是「字典 + 列表」的经典组合：
#     分组：   {部门: [员工1, 员工2, ...]}
#     聚合：   {部门: {"total": 总工资, "count": 人数}}

records = [
    {"name": "张三", "dept": "技术部", "salary": 15000},
    {"name": "李四", "dept": "销售部", "salary": 12000},
    {"name": "王五", "dept": "技术部", "salary": 18000},
    {"name": "赵六", "dept": "销售部", "salary": 9000},
    {"name": "孙七", "dept": "财务部", "salary": 11000},
]

# ---------- 第一步：分组 ----------
#
# 【重点】by_dept.setdefault(dept, []).append(name) 是分组的神器：
#         键还没有就先建个空列表，然后立刻把名字塞进去。

by_dept = {}
for r in records:
    by_dept.setdefault(r["dept"], []).append(r["name"])
print("\n按部门分组：", by_dept)

# ---------- 同样的分组，用 defaultdict 更省事 ----------
#
# 【为什么】defaultdict(list) 表示"键不存在时自动建一个空列表"，
#         于是就不需要 setdefault 了，直接 append 就行。

groups = defaultdict(list)
for r in records:
    groups[r["dept"]].append(r["name"])

print("defaultdict：", dict(groups))

# 输出：
# 按部门分组： {'技术部': ['张三', '王五'], '销售部': ['李四', '赵六'], '财务部': ['孙七']}
# defaultdict： {'技术部': ['张三', '王五'], '销售部': ['李四', '赵六'], '财务部': ['孙七']}
#
# 【注意】后面要加 dict() 转换一下，否则打印出来是 defaultdict(...) 的样子。
# 【重点】setdefault 和 defaultdict 二选一：临时用一下 → setdefault；
#         整个模块都在做分组 → defaultdict 更清爽。

# ---------- 第二步：聚合（总值 + 人数） ----------
#
# 【重点】entry = stats.setdefault(dept, {...}) 返回的是「那个内层字典」，
#         所以后面 entry["total"] += ... 改的是原字典，不是副本。

print("\n--- 每个部门的平均工资 ---")

stats = {}
for r in records:
    dept = r["dept"]
    entry = stats.setdefault(dept, {"total": 0, "count": 0})
    entry["total"] += r["salary"]
    entry["count"] += 1

for dept, entry in stats.items():
    avg = entry["total"] / entry["count"]
    print(f"{dept}：{entry['count']} 人，平均 {avg:.0f} 元")

# 输出：
# --- 每个部门的平均工资 ---
# 技术部：2 人，平均 16500 元
# 销售部：2 人，平均 10500 元
# 财务部：1 人，平均 11000 元
#
# 【注意】`:.0f` 是 f-string 的格式说明，表示"保留 0 位小数"。
#         16500.0 用 :.0f 打出来就是 16500，不带小数点。

# 【常见错误】把内层字典在循环外定义，所有人共用一个
#     entry = {"total": 0, "count": 0}      ← 放在循环外就错了
#     for r in records:
#         stats.setdefault(r["dept"], entry)  ← 所有部门拿到的是同一个字典
#   这和 02 文件里 fromkeys 的共享大坑是同一个毛病：可变对象别共用。


