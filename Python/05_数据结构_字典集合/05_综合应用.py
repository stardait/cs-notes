# 综合练习：把前面四招合起来做一张成绩报表
# ==============================================================================
#
# 需求：给一批学生的多科成绩，输出「每人平均分、最高分、是否优秀」，
#       并按平均分从高到低排名。

print("\n--- 成绩报表 ---")

scores = {
    "张三": [90, 85, 78],
    "李四": [60, 72, 55],
    "王五": [95, 92, 98],
}

report = {}
for name, marks in scores.items():
    avg = sum(marks) / len(marks)
    report[name] = {
        "平均分": round(avg, 1),
        "最高分": max(marks),
        "是否优秀": avg >= 85,
    }

ranking = sorted(report.items(), key=lambda kv: kv[1]["平均分"], reverse=True)
for name, info in ranking:
    print(f"{name}：平均 {info['平均分']} 分，最高 {info['最高分']} 分，优秀：{info['是否优秀']}")

# 输出：
# --- 成绩报表 ---
# 王五：平均 95.0 分，最高 98 分，优秀：True
# 张三：平均 84.3 分，最高 90 分，优秀：False
# 李四：平均 62.3 分，最高 72 分，优秀：False
#
# 【重点】这里用到了本章几乎所有东西：
#     dict.items() 遍历、字典推导式思路、round() 保留小数、
#     sorted 配 key 排序、f-string 输出。
# 【注意】张三 84.3 分没评上优秀（阈值 85），差一点点 —— 这种边界值最容易写错，
#         写业务代码时先把「临界情况」想清楚。


