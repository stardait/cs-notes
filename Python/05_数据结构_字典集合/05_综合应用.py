# 应用 3：查找重复元素
# ==============================================================================
#
# 需求：一个列表里，哪些元素出现了不止一次？
#
# 思路：用一个集合记「见过的」，再遇到同一个就说明重复了。

print("\n--- 找出重复元素 ---")

items = ["apple", "banana", "apple", "orange", "banana", "apple"]
print("原始列表：", items)

seen = set()            # 已经见过的
dups = set()            # 重复出现的（用集合自动去重）

for x in items:
    if x in seen:       # 见过 → 这是第二次及以后
        dups.add(x)
    else:               # 没见过 → 记下来
        seen.add(x)

print("出现过的：", sorted(seen))
print("重复过的：", sorted(dups))

# 输出：
# --- 找出重复元素 ---
# 原始列表： ['apple', 'banana', 'apple', 'orange', 'banana', 'apple']
# 出现过的： ['apple', 'banana', 'orange']
# 重复过的： ['apple', 'banana']
#
# 【重点】这里必须用「两个集合」：seen 负责"判断见过没"，dups 负责"收集重复的"。
#         如果只用一个集合，就没法区分"第一次"和"第二次"了。

# ---------- 用 Counter 一次拿到「谁重复了、重复几次」 ----------
#
# 【为什么】Counter 的 items() 里就是「元素 → 次数」，筛一下 v > 1 就得到重复元素。

counter = Counter(items)
print("\n重复元素及次数：", {k: v for k, v in counter.items() if v > 1})
print("重复的种类数：", len(dups))

# 输出：
# 重复元素及次数： {'apple': 3, 'banana': 2}
# 重复的种类数： 2
#
# 【注意】字典推导式筛出来的是「元素 → 次数」，信息比集合更全。
# 【常见错误】用计数法得到 counts 后，忘了「只出现一次的元素也在字典里」，
#         误把全部键当重复元素。一定要筛 `if v > 1`。


# ==============================================================================
# 应用 4：两个列表找差异
# ==============================================================================
#
# 需求：上周和本周都有值班名单，找出「谁离开了」「谁新来的」「谁一直都在」。
#
# 这是集合差集的典型场景，但有两个坑：
#     坑 1：结果顺序 —— 集合无序，想按原顺序输出就得自己处理
#     坑 2：重复次数 —— 集合会去重，如果你关心"出现两次"，集合就不够用

print("\n--- 名单差异 ---")

last_week = ["张三", "李四", "王五", "赵六"]
this_week = ["李四", "王五", "赵六", "孙七"]

print("上周：", last_week)
print("本周：", this_week)

left = set(last_week) - set(this_week)      # 上周有、本周没有
joined = set(this_week) - set(last_week)    # 本周有、上周没有
both = set(last_week) & set(this_week)      # 两边都有

print("\n离开的：", sorted(left))
print("新来的：", sorted(joined))
print("一直都在：", sorted(both))

# 输出：
# --- 名单差异 ---
# 上周： ['张三', '李四', '王五', '赵六']
# 本周： ['李四', '王五', '赵六', '孙七']
#
# 离开的： ['张三']
# 新来的： ['孙七']
# 一直都在： ['李四', '王五', '赵六']
#
# 【重点】三个结果刚好互补：离开的 + 都在的 == 上周；新来的 + 都在的 == 本周。
# ---------- 想保持原列表顺序？别用集合做结果 ----------
#
# 【为什么】集合本身无序，sorted() 只是碰巧按编码排，和"原顺序"是两回事。
#         要保序，就用列表推导式 + 集合做「快速判断」：

def difference(keep_order, other):
    """返回 keep_order 里不在 other 中的元素，保持 keep_order 的顺序"""
    other_set = set(other)                  # 先转集合，让 in 变成 O(1)
    return [x for x in keep_order if x not in other_set]

print("\n保序的离开名单：", difference(last_week, this_week))

# 输出：
# 保序的离开名单： ['张三']
#
# 【重点】这个函数是最实用的套路：**用集合加速判断，用列表承载顺序**。
#         如果直接在列表上写 `x not in other`，就是 O(n²)，数据一大就卡。
# ---------- 如果还关心「出现几次」呢？用 Counter 相减 ----------
#
# 【重点】Counter 支持减法，负数结果会被自动去掉，
#         相当于「多重集差集」：a 比 b 多出来的部分。

print("\n--- 带次数的差异 ---")

old_stock = ["苹果", "苹果", "香蕉"]
new_stock = ["苹果", "橘子"]

diff = Counter(old_stock) - Counter(new_stock)
print("旧库存：", old_stock)
print("新库存：", new_stock)
print("多出来的：", diff)
print("具体是：", dict(diff))

# 输出：
# --- 带次数的差异 ---
# 旧库存： ['苹果', '苹果', '香蕉']
# 新库存： ['苹果', '橘子']
# 多出来的： Counter({'苹果': 1, '香蕉': 1})
# 具体是： {'苹果': 1, '香蕉': 1}
# 【说明】
#   旧库存是 苹果×2、香蕉×1；新库存是 苹果×1、橘子×1。
#   相减后：苹果剩 1 个、香蕉剩 1 个，橘子是"新库存多出来的"所以不算。
#
# 【注意】用集合会丢掉"苹果有 2 个"这个信息（集合只关心有没有），
#         关心次数就必须用 Counter。


