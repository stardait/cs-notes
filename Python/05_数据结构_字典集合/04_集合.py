# ==============================================================================
# 知识点 1：集合是什么 —— 一个「只装独特东西的袋子」
# ==============================================================================
#
# 想象一个袋子：扔东西进去，顺序不重要（无序）；同一样东西扔两次也只有一件
# （去重）；你没法说"给我第 3 个"（不支持下标）；但问"里面有苹果吗"一摸就知道
# （查询极快）。
#
# 【重点】集合和字典是亲戚：底层都用「哈希表」。字典是「键 → 值」，
#         集合可以理解为「只有键、没有值的字典」。

fruits = {"苹果", "香蕉", "橘子", "苹果"}      # 故意写两个苹果

print("写了两个苹果：", sorted(fruits), "；苹果出现", sorted(fruits).count("苹果"), "次")
print("set([1,2,2,3])：", set([1, 2, 2, 3]))
print("set('hello') 排序后：", sorted(set("hello")))

# 输出：
# 写了两个苹果： ['橘子', '苹果', '香蕉'] ；苹果出现 1 次
# set([1,2,2,3])： {1, 2, 3}
# set('hello') 排序后： ['e', 'h', 'l', 'o']
#
# 【重点】花括号里写重复元素，Python 直接帮你合并，**不报错、不警告**。
# 【注意】必须用 sorted() 才能让输出稳定：集合「无序」，直接 print(fruits)
#         每次运行的顺序都可能不同（哈希随机化）。sorted 按 Unicode 编码排，
#         所以是"橘子、苹果、香蕉"，不是拼音序。小整数集合直接打印"碰巧"
#         是升序，但那只是实现细节，别依赖。
# 【注意】set("hello") 是把字符串拆成单个字符，重复的 l 只留一个。

# 【常见错误】创建空集合写成 {}，拿到的是空字典
print("\n{} 的类型：", type({}), "；set() 的类型：", type(set()))

# 输出：
# {} 的类型： <class 'dict'> ；set() 的类型： <class 'set'>
#
# 【注意】拿到空字典之后调 s.add(1)，会报
#         AttributeError: 'dict' object has no attribute 'add'。
#         记牢：空字典 {}，空集合 set()。

# ==============================================================================
# 知识点 2：去重 —— 集合最常用的功能
# ==============================================================================
#
#     set(列表)         得到集合（无序）
#     list(set(列表))   再转回列表（顺序不保证！）
#
# 【重点】set() 去重是 O(n)，比"双重循环两两比较"快得多，
#         但代价是「顺序丢了」。

print("\n--- 列表去重 ---")

votes = ["张三", "李四", "张三", "王五", "李四", "张三"]
print("原始投票：", votes)
print("投票人数：", len(set(votes)))
print("去重后的名单：", sorted(set(votes)))

# 输出：
# --- 列表去重 ---
# 原始投票： ['张三', '李四', '张三', '王五', '李四', '张三']
# 投票人数： 3
# 去重后的名单： ['张三', '李四', '王五']

# 【重点】想「去重但保留原顺序」，用字典：list(dict.fromkeys(votes))
# 【为什么】dict.fromkeys 把每个元素当键，重复的键自动合并，
#         而字典记住插入顺序，所以顺序就留下来了。
print("\n保序去重：", list(dict.fromkeys(votes)))

# 输出：
# 保序去重： ['张三', '李四', '王五']
#
# 【注意】如果这里写 list(set(votes))，结果永远是这三个名字，
#         但顺序每次运行都可能不同 —— 那种写法不能用来保证顺序。
# 【重点】判断「有没有重复」最快的一行写法：
#         len(列表) != len(set(列表))，没重复时两者相等，有重复时集合更短。
print("有重复吗？", len(votes) != len(set(votes)))

# 输出：
# 有重复吗？ True


# ==============================================================================
# 知识点 3：四个基本运算 —— 交、并、差、对称差
# ==============================================================================
#
# 名称   符号   含义 / 生活化理解
# ------------------------------------------------------------
# 交集    &      两个都有 —— "咱俩都选了"
# 并集    |      两个合起来（去重）—— "所有人选过的课"
# 差集    -      在左边、不在右边 —— "只有我选了"
# 对称差  ^      只在一个里 —— "咱俩选的不一样"
#
# 【重点】差集有方向：a - b 和 b - a 完全不同。对称差没方向：a ^ b == b ^ a。

class_a = {"数学", "英语", "物理"}
class_b = {"数学", "化学", "生物"}

print("\nA 班：", sorted(class_a))
print("B 班：", sorted(class_b))

print("\n交集（都选的）：", sorted(class_a & class_b))
print("并集（一共几门）：", sorted(class_a | class_b), "共", len(class_a | class_b), "门")
print("差集（只有 A 选的）：", sorted(class_a - class_b))
print("反过来（只有 B 选的）：", sorted(class_b - class_a))
print("对称差（只有一边选的）：", sorted(class_a ^ class_b))

# 输出：
# A 班： ['数学', '物理', '英语']
# B 班： ['化学', '数学', '生物']
#
# 交集（都选的）： ['数学']
# 并集（一共几门）： ['化学', '数学', '物理', '生物', '英语'] 共 5 门
# 差集（只有 A 选的）： ['物理', '英语']
# 反过来（只有 B 选的）： ['化学', '生物']
# 对称差（只有一边选的）： ['化学', '物理', '生物', '英语']
#
# 【重点】同一个减号，换个顺序结果完全不同。记口诀：
#         「a - b 是 a 里有、b 里没有的」，以左边为准。
# 【注意】"数学"不在对称差里，因为两边都有 —— 被排除了。
#         对称差 ≈ (a | b) - (a & b)，即"并集减交集"。

# 【重点】方法版（intersection / union / difference / symmetric_difference）
#         和运算符等价，但参数更宽松：运算符要求两边都是集合，方法接受任何
#         可迭代对象，还能一次传多个集合。所以 `s & [3,4]` 报错，
#         而 `s.intersection([3,4])` 可以。
nums_a, nums_b = {1, 2, 3, 4}, {3, 4, 5, 6}

try:
    print("\ns & [3,4]：", nums_a & [3, 4])
except TypeError as e:
    print("\ns & [3,4] 报错：", e)

print("s.intersection([3,4])：", nums_a.intersection([3, 4]))
print("一次求三个的交集：", nums_a.intersection({2, 3, 4}, {3, 4, 9}))

# 原地版本：&= 和 |= 直接改左边的集合（返回 None）
modify = {1, 2, 3}
modify &= {2, 3, 4}             # 等价于 modify = modify & {...}
modify |= {9}
print("原地运算后：", sorted(modify))

# 输出：
# s & [3,4] 报错： unsupported operand type(s) for &: 'set' and 'list'
# s.intersection([3,4])： {3, 4}
# 一次求三个的交集： {3, 4}
# 原地运算后： [2, 3, 9]


# ==============================================================================
# 知识点 4：子集、超集、是否相交
# ==============================================================================
#
#     a.issubset(b)       a 是 b 的子集吗？   a 里每个元素都在 b 里
#     a.issuperset(b)     a 是 b 的超集吗？   b 里每个元素都在 a 里
#     a.isdisjoint(b)     a 和 b 完全不相交吗？（没有共同元素）
#
# 运算符版：a <= b 子集（含相等）、a < b 真子集、a >= b 超集、a > b 真超集。
# 【重点】`<=` 和 `<` 的区别就是「允不允许相等」，和数字比较完全一致。

admins = {"张三", "李四"}
users = {"张三", "李四", "王五", "赵六"}

print("\n--- 子集与超集 ---")
print("admins 是 users 的子集吗？", admins.issubset(users))
print("users 是 admins 的超集吗？", users.issuperset(admins))
print("admins <= users ?", admins <= users, "；users >= admins ?", users >= admins)

print("\n--- 真子集：更严格 ---")
print("admins < users ?", admins < users)       # 更小，是真子集
print("admins <= admins ?", admins <= admins)   # 相等：是子集，但不是真子集
print("admins < admins ?", admins < admins)

print("\n--- 是否相交 ---")
print("admins 和 users 有交集吗？", not admins.isdisjoint(users))
print("{1,2} 和 {3,4} 不相交吗？", {1, 2}.isdisjoint({3, 4}))

# 输出：
# --- 子集与超集 ---
# admins 是 users 的子集吗？ True
# users 是 admins 的超集吗？ True
# admins <= users ? True ；users >= admins ? True
#
# --- 真子集：更严格 ---
# admins < users ? True
# admins <= admins ? True
# admins < admins ? False
#
# --- 是否相交 ---
# admins 和 users 有交集吗？ True
# {1,2} 和 {3,4} 不相交吗？ True
#
# 【重点】集合和它自己：<= 是 True，< 是 False。
#         写"必须严格更小"的业务逻辑时，这个细节很关键。
# 【注意】isdisjoint 的语义是「不相交」，很容易看反。
#         想问"有交集吗"，请写 `not a.isdisjoint(b)`。
#         另外：空集是任何集合的子集，`set() <= admins` 是 True。


# ==============================================================================
# 知识点 5：增、删、查，以及 frozenset
# ==============================================================================
#
# 【重点】集合没有"改"：元素就是内容本身，改元素等于删一个再加一个。

print("\n--- add / remove / discard ---")

tools = {"锤子", "扳手"}

tools.add("螺丝刀")
tools.add("锤子")                   # 已存在，什么也不发生（不报错！）
print("加完：", sorted(tools))

tools.remove("扳手")
tools.discard("电钻")               # 不存在，但 discard 不报错
print("删完：", sorted(tools))

try:
    tools.remove("电钻")            # 不存在，remove 报 KeyError
except KeyError as e:
    print("remove 不存在的：", e)

# 输出：
# --- add / remove / discard ---
# 加完： ['扳手', '螺丝刀', '锤子']
# 删完： ['螺丝刀', '锤子']
# remove 不存在的： '电钻'
#
# 【重点】add 一个已经存在的元素，集合不变，也不报错 ——
#         这和"往列表里 append 同一项会多一个"形成鲜明对比。
# 【怎么选】不确定元素在不在 → 用 discard；
#           元素应该存在（不在就是 bug）→ 用 remove，让错误早点暴露。
# 【为什么】集合的 in 是 O(1)（一次哈希计算就定位），列表的 in 是 O(n)
#         （要一个个比过去）。所以「大量判断某个值在不在」时，先把列表
#         转成集合会快很多 —— 这正是 05 文件里"找差异"要先 set() 的原因。

# ------------------------------------------------------------------------------
# frozenset：冻结的集合
# ------------------------------------------------------------------------------
#
# 集合可变，所以不能当字典的键、也不能放进另一个集合。
# 想用"一组值"当键，就得用 frozenset（不可变集合）。
#
# 【重点】frozenset 支持所有集合运算（& | - ^），只是不能修改。
#         它是可哈希的，所以能当字典键，也能放进集合里。

print("\n--- frozenset ---")

frozen = frozenset([1, 2, 3, 2])
print("创建：", frozen, "；类型：", type(frozen).__name__)
print("并：", frozen | frozenset([4]), "；交：", frozen & {2, 3})

try:
    frozen.add(4)                   # 想改？不行
except AttributeError as e:
    print("不能 add：", e)

# 输出：
# --- frozenset ---
# 创建： frozenset({1, 2, 3}) ；类型： frozenset
# 并： frozenset({1, 2, 3, 4}) ；交： frozenset({2, 3})
# 不能 add： 'frozenset' object has no attribute 'add'
#
# 【重点】报的是 AttributeError（没有这个方法），说明 frozenset 干脆
#         就没提供 add/remove，从根上不让你改。运算结果仍是 frozenset。

# frozenset 最有价值的用法：当字典的键。需求：给"一组人"分配组名，
# 顺序不同也应该算同一组。元组当键是「顺序敏感」的，frozenset 当键则顺序无关。

teams = {frozenset({"张三", "李四"}): "A 组", frozenset({"王五"}): "B 组"}
tuple_keys = {("张三", "李四"): "A 组"}

print("\n顺序打乱也能查到：", teams[frozenset({"李四", "张三"})])
print("元组换个顺序：", tuple_keys.get(("李四", "张三"), "查不到"))

try:
    bad = {{1, 2}: "集合当键"}       # 普通 set 可变，不能当键
except TypeError as e:
    print("set 当键：", e)

# 输出：
# 顺序打乱也能查到： A 组
# 元组换个顺序： 查不到
# set 当键： cannot use 'set' as a dict key (unhashable type: 'set')
#
# 【怎么选】需要之后还能增删元素 → set；
#           要当字典键 / 放进另一个集合 / 保证不被改动 → frozenset。


# ==============================================================================
# 知识点 6：集合推导式与常见错误
# ==============================================================================
#
#     {表达式 for 变量 in 可迭代对象}          集合
#     {键: 值 for 变量 in 可迭代对象}          字典
#
# 【重点】没有冒号就是集合，所以"少写一个冒号"会让字典悄悄变成集合。

print("\n--- 集合推导式 ---")
print("平方集合：", sorted({x ** 2 for x in range(5)}))
print("偶数平方：", sorted({x ** 2 for x in range(10) if x % 2 == 0}))
print("首字母小写：", sorted({w[0].lower() for w in ["apple", "Avocado", "banana"]}))

# 输出：
# --- 集合推导式 ---
# 平方集合： [0, 1, 4, 9, 16]
# 偶数平方： [0, 4, 16, 36, 64]
# 首字母小写： ['a', 'b']
#
# 【注意】apple 和 Avocado 的首字母都变成 a，集合自动去重，只剩一个 'a'。
# 【常见错误】集合不能按下标取（它没有"第 0 个"）
nums = {0, 1, 4}

try:
    nums[0]
except TypeError as e:
    print("\n直接下标：", e)

print("先 sorted 再取：", sorted(nums)[0])

# 输出：
# 直接下标： 'set' object is not subscriptable
# 先 sorted 再取： 0

# 【常见错误】元素必须可哈希：列表不能放进去，元组可以
try:
    {1, [2, 3]}
except TypeError as e:
    print("列表进集合：", e)

print("元组进集合：", {(1, 2), (3, 4)})

# 输出：
# 列表进集合： cannot use 'list' as a set element (unhashable type: 'list')
# 元组进集合： {(1, 2), (3, 4)}
#
# 【为什么】集合要去重就得算哈希值，可变对象算不了；
#         元组只要里面的东西都可哈希，它自己就可哈希。
#
# 【常见错误】用 + 拼接集合：{1,2} + {3,4} 会报
#         TypeError: unsupported operand type(s) for +: 'set' and 'set'。
#         集合没有顺序，谈不上"接在后面"，想合并请用 | 或 union()。
# 【常见错误】以为集合能当"有序的唯一列表"用。错，集合顺序完全不可控，
#         要"去重 + 保序"，用 list(dict.fromkeys(...))。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 集合三特点：无序、不重复、元素必须可哈希（不可变）
# 2. 创建：{元素, ...} 或 set(可迭代对象)；空集合必须写 set()，{} 是空字典
# 3. 去重：set(列表) 最快但丢顺序；保序去重用 list(dict.fromkeys(列表))
# 4. 交集 &、并集 |、差集 -（有方向）、对称差 ^（无方向）
# 5. 方法版接受任意可迭代对象，还能一次传多个集合
# 6. 子集 issubset / <=，真子集 <；超集 issuperset / >=
# 7. isdisjoint 是"不相交"，问"有交集吗"要写 not isdisjoint
# 8. add 重复元素不报错；remove 缺失报 KeyError，discard 缺失不报错
# 9. 集合的 in 是 O(1)；frozenset 不可变、可哈希，能当字典键


