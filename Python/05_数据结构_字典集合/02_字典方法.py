# ==============================================================================
# 知识点 1：setdefault() —— 键不在就建一个
# ==============================================================================
#
# 回顾上一章：get() 只能读，读到 None 也不会帮你把键建出来。
# 现实里常有这种需求：「这个键还没有，就给个初始值；已经有了，就别动」。
#
#     value = d.setdefault(键, 默认值)
#
#     键不存在  →  插入「键: 默认值」，并返回默认值
#     键已存在  →  什么都不做，直接返回原来的值
#
# 【重点】名字读作 set-default（设置默认值）：只在缺失时 set，
#         永远返回当前值 —— 它是唯一一个「既能读、又可能写」的常用方法。

print("--- setdefault 基本行为 ---")

config = {"host": "localhost"}

result = config.setdefault("port", 8080)    # 键不存在：插入并返回 8080
print("第一次：", result, config)

result = config.setdefault("port", 9999)    # 键已存在：不覆盖，返回 8080
print("第二次：", result, config)

print("不给默认值：", config.setdefault("timeout"), config)

# 输出：
# --- setdefault 基本行为 ---
# 第一次： 8080 {'host': 'localhost', 'port': 8080}
# 第二次： 8080 {'host': 'localhost', 'port': 8080}
# 不给默认值： None {'host': 'localhost', 'port': 8080, 'timeout': None}
#
# 【注意】第二次传的 9999 被完全无视了。所以 setdefault 只能「补空缺」，
#         不能「改已有值」—— 要改请用 [] 或 update()。
# 【常见错误】以为 setdefault 能改值：d.setdefault("a", 100) 对 {"a": 1} 没有任何效果。


# ==============================================================================
# 知识点 2：setdefault 的经典用法 —— 分组
# ==============================================================================
#
# 这是 setdefault 存在的最大理由，一定要记住这个套路。
#
# 【为什么】setdefault(cls, []).append(name) 一次完成三件事：
#           1. 键还没有 → 先塞一个空列表 []
#           2. setdefault 返回这个列表（新建的或原有的都返回）
#           3. 立刻在返回的列表上 .append(name)
#
# 【重点】空列表 [] 是「每次调用时新建」的，所以不会出现所有人共用一个列表。

print("\n--- 分组：按班级归类 ---")

students = [
    ("张三", "一班"),
    ("李四", "二班"),
    ("王五", "一班"),
    ("赵六", "三班"),
    ("孙七", "二班"),
]

classes = {}
for name, class_name in students:
    classes.setdefault(class_name, []).append(name)

print(classes)

# 输出：
# --- 分组：按班级归类 ---
# {'一班': ['张三', '王五'], '二班': ['李四', '孙七'], '三班': ['赵六']}
#
# 不用 setdefault 的老写法要多两行：先 if 判断键在不在，不在就先赋 []，再 append。
# 结果完全一样，但 setdefault 把「初始化 + 追加」压成了一行。

# 另一个用法：计数时补零
print("\n--- 计数：没有就从 0 开始 ---")

words = ["苹果", "香蕉", "苹果", "橘子"]
counter = {}
for w in words:
    counter[w] = counter.setdefault(w, 0) + 1

print(counter)

# 输出：
# --- 计数：没有就从 0 开始 ---
# {'苹果': 2, '香蕉': 1, '橘子': 1}
#
# 【注意】计数更常见的写法是 counter[w] = counter.get(w, 0) + 1，效果一样。
#         setdefault 更适合「值是容器」的场景（列表、字典）。


# ==============================================================================
# 知识点 3：update() —— 一次性改多个键
# ==============================================================================
#
#     d.update(字典)         把里面的键值对全灌进来：已有的覆盖，没有的新增
#     d.update(键=值, ...)   关键字参数写法，适合少数几个键
#     d.update([(键, 值)])   传「键值对组成的列表」
#
# 【重点】update 是「原地修改」，返回 None。

print("\n--- update 的三种参数 ---")

info = {"name": "张三", "age": 20}

info.update({"age": 21, "city": "北京"})     # age 覆盖，city 新增
print("传字典：", info)

info.update(score=95, grade="A")             # 关键字参数
print("传关键字：", info)

info.update([("x", 1), ("y", 2)])            # 列表套元组
print("传列表：", info)

# 输出：
# --- update 的三种参数 ---
# 传字典： {'name': '张三', 'age': 21, 'city': '北京'}
# 传关键字： {'name': '张三', 'age': 21, 'city': '北京', 'score': 95, 'grade': 'A'}
# 传列表： {'name': '张三', 'age': 21, 'city': '北京', 'score': 95, 'grade': 'A', 'x': 1, 'y': 2}

# 【重点】update 返回 None，这是 Python 里「原地修改」方法的统一约定
print("\nupdate 的返回值：", info.update({"z": 3}), "；但 z 进去了吗？", "z" in info)

# 输出：
# update 的返回值： None ；但 z 进去了吗？ True
#
# 【常见错误】把返回值当字典用：
#     new = old.update({"a": 1})
#     print(new["a"])        # TypeError: 'NoneType' object is not subscriptable
#
# 【为什么】所有原地修改的方法都返回 None：list.append()、list.sort()、
#         set.add() 都是这样。这是 Python 故意的「防呆」设计。
#
# 【常见错误】传了「元素长度不是 2」的东西：update 的合法参数只有
#         字典、键值对列表、关键字参数三种，普通字符串会报
#         ValueError: dictionary update sequence element #0 has length 1; 2 is required


# ==============================================================================
# 知识点 4：pop() 和 popitem() —— 删除的两种姿势
# ==============================================================================
#
#     pop(键)             删掉这个键，并把值交给你
#     pop(键, 默认值)      键不存在时返回默认值，不报错
#     popitem()           删掉「最后一对」，返回 (键, 值) 元组
#
# 【重点】popitem 删的是「最后插入的那一对」，所以是后进先出（LIFO），
#         和列表的 pop() 从尾部取是一个思路。

print("\n--- pop 细节 ---")

d = {"a": 1, "b": 2, "c": 3}
print("取出的值：", d.pop("b"), "；剩下：", d)
print("带默认值：", d.pop("z", 0))

try:
    d.pop("z")                      # 不带默认值 → KeyError
except KeyError as e:
    print("不带默认值：", e)

# 输出：
# --- pop 细节 ---
# 取出的值： 2 ；剩下： {'a': 1, 'c': 3}
# 带默认值： 0
# 不带默认值： 'z'

print("\n--- popitem 从尾部拿 ---")

d2 = {"a": 1, "b": 2, "c": 3}
print("第一对：", d2.popitem(), "；剩下：", d2)
print("第二对：", d2.popitem())
d2.popitem()

try:
    d2.popitem()                    # 空字典再 popitem → KeyError
except KeyError as e:
    print("空字典：", e)

# 输出：
# --- popitem 从尾部拿 ---
# 第一对： ('c', 3) ；剩下： {'a': 1, 'b': 2}
# 第二对： ('b', 2)
# 空字典： 'popitem(): dictionary is empty'
#
# 【注意】popitem 配合 while 可以「逐个处理完并清空」，因为空字典的布尔值是 False：
#         while d: k, v = d.popitem(); print(k, v)


# ==============================================================================
# 知识点 5：fromkeys() —— 批量造字典
# ==============================================================================
#
#     dict.fromkeys(可迭代对象)          值默认是 None
#     dict.fromkeys(可迭代对象, 默认值)   值统一是默认值
#
# 【重点】fromkeys 是「类方法」，要写 dict.fromkeys(...)，不能写 d.fromkeys(...)。

print("\n--- fromkeys 基本用法 ---")

subjects = ["语文", "数学", "英语"]
print("不填值：", dict.fromkeys(subjects))
print("填 0：", dict.fromkeys(subjects, 0))

blank = dict.fromkeys(subjects, 0)
blank["语文"] = 85
print("填上语文成绩：", blank)

# 输出：
# --- fromkeys 基本用法 ---
# 不填值： {'语文': None, '数学': None, '英语': None}
# 填 0： {'语文': 0, '数学': 0, '英语': 0}
# 填上语文成绩： {'语文': 85, '数学': 0, '英语': 0}

# ------------------------------------------------------------------------------
# 【常见错误】fromkeys 的共享可变值大坑！
# ------------------------------------------------------------------------------
#
# 默认值如果是「可变对象」（列表、字典、集合），fromkeys 会让所有键
# 指向**同一个**对象，而不是每个键各建一个。
#
# 【为什么】fromkeys 只把「这一个对象」的引用复制了 N 份，没有复制内容。

print("\n--- 大坑：共享同一个列表 ---")

shared = dict.fromkeys(["x", "y"], [])
shared["x"].append(1)               # 只改了 x 吧？
print("改了 x 之后：", shared)
print("x 和 y 是同一个列表吗？", shared["x"] is shared["y"])

# 输出：
# --- 大坑：共享同一个列表 ---
# 改了 x 之后： {'x': [1], 'y': [1]}
# x 和 y 是同一个列表吗？ True
#
# 【注意】看上去是"两个空列表"，其实是"两个标签贴在同一张纸上"，
#         改一个，另一个跟着变 —— 这就是第 1 章说的"标签模型"的后果。
#
# 【怎么办】每个键要独立的可变对象时，用字典推导式（03_字典推导式.py 的主角）：
safe = {k: [] for k in ["x", "y"]}
safe["x"].append(1)
print("正确做法：", safe, "；还是同一个吗？", safe["x"] is safe["y"])

# 输出：
# 正确做法： {'x': [1], 'y': []} ；还是同一个吗？ False
#
# 【重点】fromkeys 只适合「不可变的值」：数字、字符串、None、元组。
#         值要放列表/字典时，一律用推导式。


# ==============================================================================
# 知识点 6：合并字典 —— 四种写法，一个结论
# ==============================================================================
#
# 【重点】合并冲突时「右边（后写的）赢」。
#
#     1. c = a | b        Python 3.9+，最简洁，返回新字典
#     2. a |= b           原地合并，改的是 a
#     3. c = {**a, **b}   字典解包，老项目常见
#     4. a.update(b)      老牌写法，原地修改

print("\n--- | 与 |= ---")

left = {"x": 1, "y": 2}
right = {"y": 20, "z": 30}

print("left | right：", left | right)     # y 被右边覆盖
print("right | left：", right | left)     # y 被右边（left）覆盖
print("left 没变：", left)

left |= right                             # 原地合并
print("left |= right：", left)

# 输出：
# --- | 与 |= ---
# left | right： {'x': 1, 'y': 20, 'z': 30}
# right | left： {'y': 2, 'z': 30, 'x': 1}
# left 没变： {'x': 1, 'y': 2}
# left |= right： {'x': 1, 'y': 20, 'z': 30}
#
# 【注意】right | left 的结果里 x 排在最后：先放 left 里已有的键
#         （y 被覆盖但仍占原位置），再把 right 独有的 x 追加到末尾。

print("\n--- 老写法 ---")
print("{**a, **b}：", {**{"a": 1, "b": 2}, **{"b": 20, "c": 30}})

base = {"a": 1}
base.update({"b": 2})
print("update：", base)

# 输出：
# --- 老写法 ---
# {**a, **b}： {'a': 1, 'b': 20, 'c': 30}
# update： {'a': 1, 'b': 2}

# 【常见错误】| 只能用于两个字典，不能和列表混用
try:
    print({"a": 1} | [("b", 2)])
except TypeError as e:
    print("\n和列表混用：", e)

# 输出：
# 和列表混用： unsupported operand type(s) for |: 'dict' and 'list'
#
# 【注意】|= 同样只认字典。要给字典加列表里的键值对，请用 update([...])。

# 【重点】怎么选？
#     想要新字典，Python 3.9+  → 用 |
#     想在原字典上改            → 用 |= 或 update()
#     要兼容 Python 3.8 及以前  → 用 {**a, **b}
#   四种都要看得懂，新代码首选 | 和 |=。


# ==============================================================================
# 知识点 7：copy() 是浅拷贝 —— 一个容易被忽略的细节
# ==============================================================================
#
# 【重点】copy() 只复制最外面一层。
# 【为什么】值是列表时，两个字典里存的是「同一个列表」的引用，改一个两边都变。

print("\n--- copy 是浅拷贝 ---")

original = {"name": "张三", "scores": [90, 85]}
shallow = original.copy()

shallow["name"] = "李四"             # 第一层：互不影响
print("原字典 name：", original["name"], "；副本 name：", shallow["name"])

shallow["scores"].append(100)        # 第二层：列表是共用的
print("原字典 scores：", original["scores"])

# 输出：
# --- copy 是浅拷贝 ---
# 原字典 name： 张三 ；副本 name： 李四
# 原字典 scores： [90, 85, 100]
#
# 【重点】第一层隔离了（赋值是"换标签"），第二层没隔离（两个字典指向同一个列表）。
#         要彻底隔离得用 copy.deepcopy()（第 11 章讲）。


