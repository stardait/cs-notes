# 【本章小结】
# ==============================================================================
#
# 1. setdefault(键, 默认值)：缺失就插入，永远返回当前值 —— 分组的神器
# 2. setdefault(类别, []).append(x) 一行完成「初始化 + 追加」
# 3. update(字典) / update(键=值) / update([(键,值)])：批量覆盖或新增，返回 None
# 4. pop(键[, 默认值])：删除并返回值；popitem()：删最后一对，返回元组
# 5. fromkeys 批量造字典，但值若是列表会「所有键共用一个列表」
# 6. 合并字典：a | b（新字典）、a |= b（原地）、{**a, **b}、update()，冲突时右边赢
# 7. | 和 |= 只认字典；copy() 是浅拷贝，嵌套的可变对象仍然共享
# 8. 所有「原地修改」方法都返回 None：update / append / sort / add


