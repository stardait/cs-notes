# 【本章小结】
# ==============================================================================
#
# 1. 字典存「键 → 值」的映射，用键查值，速度极快
# 2. 创建：{} 字面量（最常用）、dict()、dict(键值对列表)、dict(zip(...))
# 3. [] 取值，键不存在抛 KeyError；get() 取值，不存在返回 None 或默认值
# 4. 修改和新增是同一个语法 d[键] = 值，键存在就改，不存在就加
# 5. 删除：del 直接删、pop 删并返回值、clear 清空
# 6. 遍历：keys() / values() / items()，最常用 items() 配元组解包
# 7. 遍历时不能增删键，会 RuntimeError；要先 list(d) 复制一份
# 8. 键必须唯一且不可变；True 和 1、False 和 0 会被当成同一个键
# 9. 字典保持插入顺序但不是排序，in 只查键


