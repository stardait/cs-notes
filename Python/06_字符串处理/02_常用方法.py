# ==============================================================================
# 知识点 1：所有字符串方法的共同规律
# ==============================================================================
#
# 【讲解】字符串不可变（01 号文件讲过），所以它所有的方法都遵守同一个约定：
#   方法不修改原字符串，而是「返回一个新的字符串」。
#
#   这就像改作业：不能擦掉重写，只能另抄一份改好的，再让变量名指向新抄的那份。
#
# 【重点】因此 `s.strip()` 单独写一行没有意义，必须接住返回值：s = s.strip()

from re import split

from numpy import repeat


s = "  Hello  "
s.strip()                   # 返回值被丢掉了，s 一点没变
print(repr(s))              # repr 会显示引号，空格看得清清楚楚

cleaned = s.strip()         # 正确做法：接住返回值
print(repr(cleaned))

# 输出：
# '  Hello  '
# 'Hello'
#
# 【常见错误】以为 s.strip() 会「就地修改」，写完发现没效果。
#   只要记住「字符串方法都有返回值」，这个坑就不会再踩。


# ==============================================================================
# 知识点 2：strip 家族 —— 去掉两端的空白
# ==============================================================================
#
# 【讲解】用户输入、文件读取的文本，两头经常夹着空格、换行、制表符。
#   strip()   去掉两端
#   lstrip()  只去左边（left）
#   rstrip()  只去右边（right）
#
#   不带参数时，去掉的是「所有空白字符」：空格、\n、\t、\r 都算。

s = "  hello world  "
print(repr(s.strip()))          # 两端都去掉
print(repr(s.lstrip()))         # 只去左边
print(repr(s.rstrip()))         # 只去右边
print(repr("a  b".strip()))     # 中间的空格不受影响

# 输出：
# 'hello world'
# 'hello world  '
# '  hello world'
# 'a  b'

# 也可以指定要删的字符（注意：是「字符集合」，不是「子串」！）
print(repr("xxhixx".strip("x")))            # 两端的 x 全删掉
print(repr("www.example.com".strip("w.")))  # 两端的 w 和 . 都删掉

# 输出：
# 'hi'
# 'example.com'
#
# 【注意】strip("w.") 删除的是「w 或 .」中的任意字符，从左往右删到遇到别的
#   字符为止，右边同理。所以它只削两端的边角：想删中间的字符得用 replace。


# ==============================================================================
# 知识点 3：split —— 把字符串切成列表
# ==============================================================================
#
# 【讲解】split 按分隔符把字符串切成若干块，返回一个列表。
#   最常用的两种写法：
#       s.split()      不给参数：按「任意空白」切，并且自动丢掉空块
#       s.split(",")   给参数：严格按这个分隔符切，空块也保留
#
# 【为什么推荐无参 split()】处理用户输入时，多打几个空格不该产生空字符串。

print("a,b,c".split(","))       # 按逗号切
print("2024-05-01".split("-"))  # 按短横线切日期
print("a b  c".split())         # 无参：连续空格算一个分隔符

# 输出：
# ['a', 'b', 'c']
# ['2024', '05', '01']
# ['a', 'b', 'c']

# 有空块的情况：字符串里连着两个逗号，中间就是空串
print("a,b,,c".split(","))
print("a  b".split(" "))        # 指定空格：两个空格会切出一个空串
print(len("".split()))          # 无参 split 对空串返回空列表
print(repr("".split(",")))      # 指定分隔符则返回含一个空串的列表

# 输出：
# ['a', 'b', '', 'c']
# ['a', '', 'b']
# 0
# ['']
#
# 【注意】空串和「空列表」不是一回事：
#   "".split()   → []         一个元素都没有
#   "".split(",")→ ['']       有一个空字符串元素
#
# 【补充】第二个参数 maxsplit 可以限制切几刀，剩下的原样留在最后一块：
print("a,b,c".split(",", 1), "a,b,c".rsplit(",", 1))

# 输出：
# ['a', 'b,c'] ['a,b', 'c']
#
# 【常见错误】用 split 处理 CSV 时忘了空字段，后面按下标取值就 IndexError。
#   切完先 print 出来看一眼，永远是个好习惯。


# ==============================================================================
# 知识点 4：join —— 把列表拼成一个字符串
# ==============================================================================
#
# 【讲解】join 是 split 的逆操作。
#   语法有点反直觉：分隔符.join(列表)
#   也就是「用什么连」写在前面，「连谁」写在括号里。

print("-".join(["2024", "01", "01"]))   # 用短横线连接
print("".join(["a", "b", "c"]))         # 空串连接 = 直接粘起来
print(", ".join("abc"))                 # 参数可以是任何可迭代对象，字符串也行

# 输出：
# 2024-01-01
# abc
# a, b, c

# 【重点】join 要求列表里每个元素都是字符串，有数字要先转换
nums = [1, 2, 3]
parts = []
for n in nums:
    parts.append(str(n))        # 先逐个转成字符串
print("-".join(parts))

# 直接拼数字会报错，错误信息写得很清楚
try:
    "-".join([1, 2, 3]) # type: ignore
except TypeError as e:
    print("TypeError:", e)

# 输出：
# 1-2-3
# TypeError: sequence item 0: expected str instance, int found
#
# 【为什么用 join 而不是循环 +=】
#   join 会先算出总长度，一次性分配内存；
#   循环 += 每次都创建新字符串，拼接几万次会明显变慢。
#   记住：多个片段拼一个字符串，优先 join。


# ==============================================================================
# 知识点 5：replace —— 替换子串
# ==============================================================================
#
# 【讲解】replace(旧, 新) 会把「所有出现」的旧子串换成新子串。
#   第三个参数 count 可以限制最多替换几次。

s = "hello world"
print(s.replace("l", "L"))          # 所有 l 都换成 L
print(s.replace("l", "L", 1))       # 只换前 1 个
print(s.replace(" ", ""))           # 把空格全部删掉（替换成空串）
print(s)                            # 原串当然没变

# 输出：
# heLLo worLd
# heLlo world
# helloworld
# hello world

# 可以链式替换多个字符
print("a-b-c".replace("-", "_").replace("a", "A"))

# 输出：
# A_b_c
#
# 【注意】replace 是按「子串」替换，strip 是按「字符集合」删除，别搞混：
#   "hello".replace("ll", "LL")  → 'heLLo'（整段匹配）
#   "llhello".strip("l")         → 'hello'（只削两端，中间的 l 不管）
# 【常见错误】以为 replace 只换第一个。它默认全换，要限量得传 count。


# ==============================================================================
# 知识点 6：find / rfind / index / count —— 找位置
# ==============================================================================
#
# 【讲解】四个方法都用来「找」：
#   find(子串)     返回第一次出现的下标，找不到返回 -1
#   rfind(子串)    从右往左找，返回最后一次出现的下标
#   index(子串)    和 find 一样，但找不到会抛 ValueError
#   count(子串)    数一数出现了几次

s = "hello"
print(s.find("l"))          # 第一次出现的位置
print(s.find("l", 3))       # 从下标 3 开始往后找
print(s.rfind("l"))         # 最后一次出现的位置
print(s.find("z"))          # 找不到：返回 -1
print(repr(s.find("")))     # 空串在位置 0 就能匹配上
print(s.count("l"))         # 一共出现 2 次

# 输出：
# 2
# 3
# 3
# -1
# 0
# 2

# index 找不到直接报错，适合「这一步不该失败」的场景
try:
    s.index("z")
except ValueError as e:
    print("ValueError:", e)

# 输出：
# ValueError: substring not found
#
# 【重点】初学者优先用 `in` 判断有没有，需要位置时再用 find：
#       if "l" in s:     清晰、不会忘掉 -1 这个特殊情况
#
# 【常见错误】把 find 的返回值直接当布尔值用。
#   -1 在 Python 里是真值！`if s.find("z"):` 会误判为「找到了」。
#   正确写法：if s.find("z") != -1:


# ==============================================================================
# 知识点 7：startswith / endswith —— 开头和结尾
# ==============================================================================
#
# 【讲解】判断「是不是以某段开头/结尾」，返回 True / False。
#   括号里可以传「元组」，表示「满足任意一个就行」。

filename = "report.pdf"
print(filename.startswith("report"))            # 以 report 开头
print(filename.endswith(".pdf"))                # 以 .pdf 结尾
print(filename.endswith((".jpg", ".png")))      # 是图片吗？不是
print("hello".startswith("ell", 1))             # 从下标 1 开始判断
print("https://a.com".startswith(("http://", "https://")))   # 常见用法：判断协议
print(filename.endswith(".PDF"))                # 区分大小写！

# 输出：
# True
# True
# False
# True
# True
# False
#
# 【重点】大小写敏感。用户上传的文件名常是 .JPG，
#   稳妥写法：filename.lower().endswith(".jpg")


# ==============================================================================
# 知识点 8：大小写方法 —— upper / lower / title / capitalize / casefold
# ==============================================================================
#
# 【讲解】六个方法都返回新字符串，不会改动原串：
#   upper()       全部转大写
#   lower()       全部转小写
#   title()       每个单词首字母大写
#   capitalize()  只有整句第一个字母大写，其余全部小写
#   swapcase()    大写变小写、小写变大写
#   casefold()    比 lower 更彻底的「大小写折叠」，专用于比较

print("hello".upper(), "HELLO".lower())     # 全大写 / 全小写
print("hello world".title())                 # 每个单词首字母大写
print("hello WORLD".capitalize())            # 只有第一个字母大写，其余全小写
print("Hello World".swapcase())              # 大小写互换

# 输出：
# HELLO hello
# Hello World
# Hello world
# hELLO wORLD

# title() 有个坑：它把「任何非字母字符」后面都当成单词开头
print("it's a test".title())

# 输出：
# It'S A Test
#
# 【注意】英文撇号后面的 s 被 title() 当成了新单词的开头，
#   所以处理人名、带撇号的句子时不要用 title()，会得到 It'S 这种怪结果。

# casefold()：德语 ß 转成 ss，比 lower() 更彻底
print("Straße".casefold())
print(len("Straße"), len("Straße".casefold()))
print("STRASSE".casefold() == "Straße".casefold())

# 输出：
# strasse
# 6 7
# True
#
# 【重点】比较两个字符串是否「忽略大小写相等」，用 casefold 而不是 lower。
#   lower("ß") 还是 "ß"，长度不变，但 casefold 会变成 "ss"。


# ==============================================================================
# 知识点 9：链式调用 —— 一步接一步地清洗文本
# ==============================================================================
#
# 【讲解】既然每个方法都返回新字符串，那就可以「一个接一个」地调用：
#   s.strip().lower().replace(...) —— 每一步的输出是下一步的输入，像流水线。
#   注意别写太长，超过三四个方法就拆开，否则出错时不知道是哪一步的问题。

raw = "  Hello, World!  "
clean = raw.strip().lower().replace(",", "").replace("!", "")
print(repr(raw), repr(clean))       # 原始数据 vs 清洗后的结果

# 输出：
# '  Hello, World!  ' 'hello world'


# ==============================================================================
# 知识点 10：三个高频错误
# ==============================================================================
#
# 【常见错误 1】strip 传的是「字符集合」，不是子串
print(repr("hello".strip("hello")))         # 两端全是集合里的字符，删光
print(repr("abcHELLOcba".strip("abc")))     # 左边 abc 和右边 cba 都被削掉

# 输出：
# ''
# 'HELLO'

# 【常见错误 2】join 的参数顺序写反：列表.join(",") 是错的
try:
    ["a", "b"].join(",") # type: ignore
except AttributeError as e:
    print("AttributeError:", e)
print(",".join(["a", "b"]))                 # 分隔符在前，列表在后

# 输出：
# AttributeError: 'list' object has no attribute 'join'
# a,b

# 【常见错误 3】拿 find 的返回值当条件
pos = "hello".find("z")
if pos:                                     # -1 是真值！这里会进入分支
    print("找到了，位置：", pos)
print("正确判断：", pos != -1)

# 输出：
# 找到了，位置： -1
# 正确判断： False
#
# 【重点】Python 里 -1 是真值，所以 find 的结果必须显式和 -1 比较。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 字符串方法都不改原串，一律返回新字符串，必须接住返回值
# 2. strip / lstrip / rstrip 去两端空白；传参时按「字符集合」删
# 3. split() 无参按任意空白切且丢空块；split(",") 严格切并保留空串
# 4. split 的 maxsplit 参数可以限制切几刀；rsplit 从右边切
# 5. join 的调用者是分隔符：分隔符.join(列表)，元素必须全是 str
# 6. replace 默认替换全部，第三个参数 count 可以限量；它按子串匹配
# 7. find 找不到返回 -1，index 抛 ValueError；count 用来计数
# 8. startswith / endswith 可传元组，区分大小写
# 9. title() 会在撇号后错误大写；忽略大小写比较用 casefold()
# 10. 链式调用很爽，但要控制长度，方便排查


