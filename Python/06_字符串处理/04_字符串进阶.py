# 1. 转义字符用反斜杠表示特殊字符：\n 换行、\t 制表符、\\ 反斜杠、\" 引号
# 2. 码点转义：\xhh、\u4e2d、\U0001F600、\N{名字}
# 3. print 给人看，repr 给调试看；repr 能暴露换行、制表符、零宽字符
# 4. 三引号保留换行和缩进；\ 放在开引号后可以吃掉首个换行
# 5. 相邻字符串字面量会自动拼接，写长句用圆括号最清楚
# 6. 字符 / 码点 / 字节是三层概念：ord、chr、encode、decode 各管一段
# 7. UTF-8 里汉字 3 字节，GBK 里 2 字节；ASCII 字符两种编码下都是 1 字节
# 8. 编码解码必须用同一张表，用错就得乱码（乱码可逆，能救回来）
# 9. UnicodeEncodeError 是「字典里没这个字」，UnicodeDecodeError 是「字节不合规」
# 10. 比较文本前先做 NFC 归一化；从网页复制来的文本要小心零宽字符


