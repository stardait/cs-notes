# ==============================================================================
# 知识点 1：转义字符 —— 用反斜杠表示看不见的字符
# ==============================================================================
#
# 【讲解】有些字符没法直接敲出来（换行、制表符），有些字符和语法冲突（引号）。
#   Python 用「反斜杠 + 一个字母」来表示它们，这种写法叫「转义」。
#
#   最常用的几个：
#       \n    换行（newline）
#       \t    制表符（tab），相当于按一下 Tab 键
#       \\    一个真正的反斜杠
#       \'    单引号
#       \"    双引号
#       \x41  十六进制码点，这里是字母 A
#       \u4e2d  四位 Unicode 码点，这里是「中」
#       \U0001F600  八位 Unicode 码点，这里是 😀
#       \N{SNOWMAN}  按 Unicode 名字写，这里是 ☃
#
# 【为什么需要】字符串用引号包起来，如果内容里也有引号，不加转义就会提前结束。
#   所以反斜杠充当「我把下一个字符当普通字符看」的暗号。

print("第一行\n第二行")              # \n 换行
print("路径：C:\\Users\\new")        # \\ 表示一个反斜杠
print('He said: \'hi\'')             # 单引号字符串里转义单引号
print("She said: \"hi\"")            # 双引号字符串里转义双引号

# 输出：
# 第一行
# 第二行
# 路径：C:\Users\new
# He said: 'hi'
# She said: "hi"

# 制表符看不见，用 repr 让它现形
print(repr("姓名\t年龄"))            # repr 把 \t 显示成两个字符
print(repr("姓名    年龄"))          # 真实空格：repr 里就是一片空白

# 输出：
# '姓名\t年龄'
# '姓名    年龄'
#
# 【重点】print 是给人看的，repr 是给调试看的；不确定有没有藏空白时用 print(repr(s))。

# 也可以用码点写字符
print("\u4e2d\u6587")               # 四位 Unicode 转义：中文
print("\N{SNOWMAN}")                # 按名字：雪人

# 输出：
# 中文
# ☃
#
# 【重点】\n、\t 本身也只占一个字符位置：len("\n") 是 1，不是 2。


# ==============================================================================
# 知识点 2：多行字符串 —— 三引号与隐式拼接
# ==============================================================================
#
# 【讲解】想写「跨好几行」的字符串，最常用两种办法：
#       1. 三引号 """...""" 或 '''...'''：直接回车换行
#       2. 圆括号里放多个字符串字面量：Python 会自动拼接（推荐）
#   另外还有「行尾加反斜杠 \ 续行」的老写法，不推荐，容易漏看。
#
# 【注意】三引号会把「源码里的换行和缩进」原封不动保留下来，缩进要自己控制。

poem = """床前明月光，
疑是地上霜。"""
print(poem)

# 输出：
# 床前明月光，
# 疑是地上霜。

# 反斜杠放在开引号后面，可以吃掉「第一行换行」，避免开头多一个空行
text = """\
第一行
第二行"""
print(text)

# 输出：
# 第一行
# 第二行
#
# 【注意】三引号里的缩进也是内容的一部分，不会自动去掉：
indented = """第一行
    第二行"""
print(indented)

# 输出：
# 第一行
#     第二行
#
# 【常见错误】在函数里写三引号，第二行缩进 4 个空格，输出里就会带着 4 个空格。
#   处理办法：用 textwrap.dedent()，或者干脆自己拼字符串。

# 隐式拼接：括号里相邻的字符串字面量会自动连起来，适合写长句
message = ("这是一句很长的话，"
           "分成两行写，"
           "运行时其实是一个字符串。")
print(message, len(message), sep="\n")   # 先打印内容，再打印长度

# 输出：
# 这是一句很长的话，分成两行写，运行时其实是一个字符串。
# 27
#
# 【注意】三引号最常见的用途是写「文档字符串」（函数体第一行的说明），
#   它可以被 greet.__doc__ 读出来——第 3 章写过，这里不再重复。
#   另外，太长的表达式可以用圆括号分行，不需要行尾反斜杠。


# ==============================================================================
# 知识点 3：字符、码点、字节 —— 三个容易混的概念
# ==============================================================================
#
# 【讲解】先建立三个层次，后面讲编码就不会乱：
#
#   1. 字符：人看到的一个符号，比如「中」「A」「😀」
#   2. 码点：Unicode 给每个字符编的号，是个整数——「A」是 65，
#         「中」是 20013（0x4E2D），「😀」是 128512（0x1F600）
#   3. 字节：计算机实际存储的 0~255 的数字序列
#
#   【重点】len() 数的是「字符」，不是字节，也不是终端里的显示宽度。

print(ord("A"), chr(65))                    # ord 字符→码点，chr 码点→字符
print(ord("中"), hex(ord("中")), chr(20013), ord("😀"), hex(ord("😀")))

# 输出：
# 65 A
# 20013 0x4e2d 中 128512 0x1f600

print(len("abc"), len("中文"), len("😀"))   # 都是字符个数
print(len("😀".encode("utf-8")))            # 但存成 UTF-8 要 4 个字节

# 输出：
# 3 2 1
# 4

# Unicode 给每个字符都起了「官方名字」，可以用 unicodedata 查
import unicodedata

print(unicodedata.name("中"), unicodedata.name("😀"))
print(unicodedata.lookup("SNOWMAN"))        # 反过来：按名字查字符

# 输出：
# CJK UNIFIED IDEOGRAPH-4E2D GRINNING FACE
# ☃
#
# 【注意】终端字体显示不出来时，字符并不会消失，只是画成方框。
#   用 repr 或 unicodedata.name 确认它到底是什么，比盯着屏幕猜靠谱。


# ==============================================================================
# 知识点 4：encode 与 decode —— str 和 bytes 的翻译官
# ==============================================================================
#
# 【讲解】Python 3 把「文本」和「字节」分得很清楚：
#
#   str   是「文本」，人读的，用 Unicode 码点存
#   bytes 是「字节」，机器存的，前面带 b，元素是 0~255 的整数
#
#   两个方向的转换：
#       str.encode("编码名")   → bytes   （编码：把文本翻译成字节）
#       bytes.decode("编码名") → str     （解码：把字节翻译回文本）
#
#   【重点】编码和解码必须用同一张表！用错就会得到乱码或者直接报错。

text = "中文"
data = text.encode("utf-8")
print(data, type(data))             # b 开头，\xe4 这种是十六进制字节；类型是 bytes
print(len(text), len(data))         # 2 个字符，占 6 个字节

# 输出：
# b'\xe4\xb8\xad\xe6\x96\x87' <class 'bytes'>
# 2 6

print(data.decode("utf-8"))         # 解回来还是「中文」
print(data == b"\xe4\xb8\xad\xe6\x96\x87")   # 可以直接和字节字面量比较

# 输出：
# 中文
# True
#
# 【重点】str.encode() 负责编码，bytes.decode() 负责解码，两者必须用同一张表。

# 同一个文本，换一种编码，字节就完全不同（长度也不同）
gbk_data = text.encode("gbk")
print(gbk_data, len(gbk_data))      # GBK 里一个汉字 2 字节
print(b"\xe4\xb8\xad".decode("utf-8"), b"abc".decode("ascii"))   # 字节字面量也能直接解码

# 输出：
# b'\xd6\xd0\xce\xc4' 4
# 中 abc

# ASCII 兼容：纯英文在 UTF-8 下就是原样，一个字母一个字节
# 【重点】bytes 按下标取出来是「整数」，不是字符：
print("abc".encode("utf-8"), len("abc".encode("utf-8")))
print(b"abc"[0], type(b"abc"[0]), chr(b"abc"[0]), b"abc"[0:2])

# 输出：
# b'abc' 3
# 97 <class 'int'> a b'ab'
#
# 【注意】b"中文" 这种写法直接是语法错误，字节字面量里只能写 ASCII。
#   要得到中文的字节，必须先写字符串再 encode。


# ==============================================================================
# 知识点 5：编码报错与乱码 —— 出错了怎么救
# ==============================================================================
#
# 【讲解】两类错误：
#   UnicodeEncodeError：编码时发现「这个字符不在目标编码表里」
#       比如把 emoji 存成 GBK，GBK 根本没有这个字符
#   UnicodeDecodeError：解码时发现「这串字节不符合目标编码的规则」
#       比如拿 UTF-8 的表去解 GBK 的字节
#
# 【为什么】编码表就像字典：GBK 收录汉字，但不收录 emoji；
#   拿错字典查词，当然查不到，或者查出一堆不相干的东西。

try:
    "😀".encode("gbk")
except UnicodeEncodeError as e:
    print("UnicodeEncodeError:", e)

# 输出：
# UnicodeEncodeError: 'gbk' codec can't encode character '\U0001f600' in position 0: illegal multibyte sequence

try:
    b"\xd6\xd0".decode("utf-8")     # 这是 GBK 的「中」，不是合法 UTF-8
except UnicodeDecodeError as e:
    print("UnicodeDecodeError:", e)

# 输出：
# UnicodeDecodeError: 'utf-8' codec can't decode byte 0xd6 in position 0: invalid continuation byte

# 实在要转，可以用 errors 参数指定「遇到坏字节怎么办」
bad = b"\xd6\xd0"
print(repr(bad.decode("utf-8", errors="ignore")))         # 直接丢弃
print(len(bad.decode("utf-8", errors="replace")))         # 换成 �，两个字节两个

# 输出：
# ''
# 2
#
# 【注意】errors="ignore" 不会报错，但会「悄悄吃掉数据」。
#   只有在「脏数据丢一点无所谓」的场景才用，比如做统计前的清洗。

# 乱码长什么样：GBK 字节拿 latin-1 去解，就会得到一串看不懂的欧洲字母
mojibake = "中文".encode("gbk").decode("latin-1")
print(repr(mojibake))               # 直接 print 会显示成 ÖÐÎÄ，这里用 repr 看清楚

# 输出：
# 'ÖÐÎÄ'

# 乱码是可以救回来的：按原路反向操作一次
fixed = mojibake.encode("latin-1").decode("gbk")
print(fixed, fixed == "中文")

# 输出：
# 中文 True
#
# 【重点】乱码的本质是「用错了解码表」，不是数据坏了。
#   只要能确定原来用的编码，就还有救。


# ==============================================================================
# 知识点 6：Unicode 归一化 —— 看起来一样的字符，可能并不相等
# ==============================================================================
#
# 【讲解】有些字符有两种存法：预组合（é 是一个码点 U+00E9）、
#   组合式（e 加上组合重音 U+0301，两个码点拼出来）。
#   人眼看着一模一样，但 len() 和 == 的结果完全不同。
#
# 【为什么】历史原因，不同系统/输入法选择不同。macOS 的文件名常用组合式，
#   Windows 常用预组合式，于是「同一个文件名」在两个系统上可能对不上。

precomposed = "\u00e9"          # é：一个码点
combined = "e\u0301"            # e + 组合重音：两个码点

# 把「码点」列出来，才能看出它们根本不是同一个东西
def codepoints(s):
    """返回字符串中每个字符的码点，如 U+00E9。"""
    return " ".join(f"U+{ord(ch):04X}" for ch in s)

print(len(precomposed), len(combined))      # 1 和 2
print(precomposed == combined, codepoints(precomposed), codepoints(combined))

# 输出：
# 1 2
# False U+00E9 U+0065 U+0301
#
# 【注意】combined 直接 print 出来也是 é，肉眼完全分辨不出。
#   只有看码点、看 len、或者用 == 比较，才能发现它们的区别。

# 归一化：把两种写法统一成同一种标准形式
nfc = unicodedata.normalize("NFC", combined)    # NFC：合成成最短形式
print(len(nfc), nfc == precomposed, codepoints(nfc))

# 输出：
# 1 True U+00E9
#
# 【重点】比较用户输入、给文件名去重之前，先 normalize("NFC", s) 一下，
#   能避免很多「明明看起来一样却不相等」的玄学 bug。


# ==============================================================================
# 知识点 7：三个高频错误
# ==============================================================================
#
# 【常见错误 1】str 和 bytes 混着拼，或者用 str() 去转 bytes
try:
    print("abc" + b"def") # type: ignore
except TypeError as e:
    print("TypeError:", e)
print("abc" + b"def".decode())      # 正确：先解码成 str 再拼
print(str(b"abc"))                  # 错误：得到 "b'abc'"，b 和引号都成了内容
print(b"abc".decode())              # 正确：得到 abc

# 输出：
# TypeError: can only concatenate str (not "bytes") to str
# abcdef
# b'abc'
# abc

# 【常见错误 2】以为 len() 是字节数或显示宽度
print(len("中文"), len("中文".encode("utf-8")))
print(f"|{'中文':<10}|")            # 补了 8 个空格，视觉上却窄一截

# 输出：
# 2 6
# |中文        |
#
# 【为什么】len 数字符（2 个），UTF-8 占 6 字节，终端显示占 4 列，三个数不一样。

# 【常见错误 3】以为打印不出来就代表字符不存在
weird = "\u200b"                    # 零宽空格：宽度为 0，肉眼完全看不见
print(len(weird), repr(weird))      # 长度 1，repr 能看到它

# 输出：
# 1 '\u200b'
#
# 【注意】零宽字符是「文本比对莫名失败」的常见元凶，从网页复制来的文本
#   尤其容易带；读写文件别忘写 encoding="utf-8"（第 11 章细讲）。


