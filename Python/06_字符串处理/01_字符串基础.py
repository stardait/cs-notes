# 【本章小结】
# ==============================================================================
#
# 1. 字符串是一串字符，单引号 / 双引号等价，三引号用于多行
# 2. 索引从 0 开始，-1 表示最后一个；越界抛 IndexError
# 3. 切片 s[起点:终点:步长]，含头不含尾，越界自动截断不报错
# 4. 步长为负可以反转字符串：s[::-1]
# 5. 字符串不可变：所有方法都返回新串，s[0] = "X" 会 TypeError
# 6. 不可变带来两个好处：可作字典 key、可安全共享
# 7. for 遍历拿单个字符；enumerate 同时拿下标；in 判断子串且区分大小写
# 8. 原始字符串 r'' 让反斜杠不转义，写路径和正则必备
# 9. == 比内容，is 比对象；判断字符串相等只用 ==
# 10. len() 数的是字符数，不是字节数


