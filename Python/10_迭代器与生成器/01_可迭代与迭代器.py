# ==============================================================================
# 知识点 1：可迭代对象 —— 能被 for 遍历的东西
# ==============================================================================
#
# 只要一个东西能放在 for 后面，它就是「可迭代对象」（iterable）。
#
# 【生活类比】一本书 = 可迭代对象，书里有内容，可以一页页翻；
#             书签   = 迭代器，它不存内容，只记住「读到第几页了」。
#
# 【重点】列表、元组、字符串、字典、集合、range、文件……全都是可迭代对象。

print("--- 遍历列表 ---")
for item in [1, 2, 3]:
    print("列表元素：", item)

print("--- 遍历字符串 ---")
for ch in "Py":
    print("字符：", ch)

print("--- 遍历字典（默认遍历键）---")
scores = {"语文": 90, "数学": 95}
for key in scores:
    print(f"{key}的成绩是 {scores[key]} 分")

# 输出：
# --- 遍历列表 ---
# 列表元素： 1
# 列表元素： 2
# 列表元素： 3
# --- 遍历字符串 ---
# 字符： P
# 字符： y
# --- 遍历字典（默认遍历键）---
# 语文的成绩是 90 分
# 数学的成绩是 95 分

# 【注意】可迭代对象不一定是「容器」。range(100000000) 并不真存 1 亿个数，
#         它只是「知道怎么一个个产生」，所以几乎不占内存。
#         这种「要的时候才给」的思想，是本章贯穿始终的主线。


# ==============================================================================
# 知识点 2：迭代器 —— 带书签的取值器
# ==============================================================================
#
# 可迭代对象本身不会「记住读到哪」。每次 for 开始时，它都要先造一个
# 「临时书签」记录进度，这个书签就是迭代器（iterator）。
#
#     iter(可迭代对象)  →  得到迭代器
#     next(迭代器)      →  取出下一个值，书签往后挪一格
#
# 【重点】iter() 不复制数据，只是换了个「看数据的角度」。

numbers = [10, 20, 30]              # 列表：可迭代对象
it = iter(numbers)                  # 造一个迭代器（书签）

print("\n--- iter() 做了什么 ---")
print("列表的类型：", type(numbers).__name__)
print("迭代器的类型：", type(it).__name__)
print("是同一个对象吗：", it is numbers)

print("\n--- 用 next() 一个个取值 ---")
print("next(it) =", next(it))       # 取第 1 个，书签移到 1
print("next(it) =", next(it))       # 取第 2 个，书签移到 2
print("next(it) =", next(it))       # 取第 3 个，书签移到末尾

# 输出：
# --- iter() 做了什么 ---
# 列表的类型： list
# 迭代器的类型： list_iterator
# 是同一个对象吗： False
#
# --- 用 next() 一个个取值 ---
# next(it) = 10
# next(it) = 20
# next(it) = 30
#
# 【注意】list_iterator 是列表的迭代器类型名。元组、range 也各有自己的
#         迭代器类型（tuple_iterator、range_iterator），名字不同，用法一样。
# 【重点】迭代器内部只有一个「当前位置」标记，不知道前面取过什么，
#        也没法往回退 —— 书签只能往前挪。

# ==============================================================================
# 知识点 3：StopIteration —— 没数据了，抛个异常告诉你
# ==============================================================================
#
# 取完了还继续 next()，Python 不返回 None，而是抛出 StopIteration。
#
# 【为什么】用异常而不是特殊值（-1、None），是因为特殊值可能和真实数据
#         撞车（数据里本来就有 None 怎么办？）；异常不会和正常数据混淆。
#
# 【注意】StopIteration 在 for 里是「正常结束信号」，不是错误，
#         它被 for 悄悄捕获掉了，所以平时看不到。

it = iter([1])
print("\n--- 迭代器耗尽 ---")
print("还能取到：", next(it))

try:
    next(it)
except StopIteration as e:
    print("捕获到了 StopIteration，异常对象是", repr(e))

print("\n--- 给 next() 一个默认值，就不用抓异常 ---")
it2 = iter(["a", "b"])
print(next(it2, "没有更多了"))      # 有值，正常返回 "a"
print(next(it2, "没有更多了"))      # 有值，正常返回 "b"
print(next(it2, "没有更多了"))      # 没值，返回默认值，不抛异常

# 输出：
# --- 迭代器耗尽 ---
# 还能取到： 1
# 捕获到了 StopIteration，异常对象是 StopIteration()
#
# --- 给 next() 一个默认值，就不用抓异常 ---
# a
# b
# 没有更多了
#
# 【重点】next(迭代器, 默认值) 是「安全取值」的写法。


# ==============================================================================
# 知识点 4：for 循环的内部机制 —— 三件套的秘密
# ==============================================================================
#
# 很多人以为 for 是高级语法，其实背后只有三步：
#     1. iter(对象)        → 拿到迭代器
#     2. 反复 next(迭代器) → 拿到每个值，执行循环体
#     3. 捕获 StopIteration → 结束循环
#
# 下面这个类会在每次被调用时「喊一声」，看清 for 到底做了什么。

class NoisyIterator:
    """一个会「说话」的迭代器，用来观察 for 循环的调用顺序"""

    def __init__(self, data):
        self.data = data            # 要遍历的数据
        self.index = 0              # 书签：当前读到第几个

    def __iter__(self):
        print("  [迭代器] for 调用了 __iter__，拿到迭代器")
        return self                 # 迭代器的 __iter__ 一般返回自己

    def __next__(self):
        print(f"  [迭代器] for 调用了 __next__，index = {self.index}")
        if self.index >= len(self.data):
            print("  [迭代器] 数据取完了，抛出 StopIteration")
            raise StopIteration     # 用异常告诉 for：结束了
        value = self.data[self.index]
        self.index += 1
        return value


print("\n--- 观察 for 循环内部 ---")
for value in NoisyIterator(["甲", "乙"]):
    print("循环体拿到：", value)
print("for 循环结束")

print("\n--- 用 while 手动模拟 for ---")
iterator = iter([10, 20, 30])       # 第 1 步：拿迭代器
while True:
    try:
        item = next(iterator)       # 第 2 步：取值
    except StopIteration:           # 第 3 步：抓异常
        break                       #         结束循环
    print("手动遍历拿到：", item)

# 输出：
# --- 观察 for 循环内部 ---
#   [迭代器] for 调用了 __iter__，拿到迭代器
#   [迭代器] for 调用了 __next__，index = 0
# 循环体拿到： 甲
#   [迭代器] for 调用了 __next__，index = 1
# 循环体拿到： 乙
#   [迭代器] for 调用了 __next__，index = 2
#   [迭代器] 数据取完了，抛出 StopIteration
# for 循环结束
#
# --- 用 while 手动模拟 for ---
# 手动遍历拿到： 10
# 手动遍历拿到： 20
# 手动遍历拿到： 30
#
# 【重点】__iter__ 只调用 1 次，__next__ 调用 N+1 次（最后一次发现没数据）。
#         最后那次 StopIteration 被 for 吞掉，所以循环体只执行了 2 次。
# 【结论】for x in obj 就是上面 while 版的「语法糖」。


# ==============================================================================
# 知识点 5：【常见错误】迭代器是一次性的！
# ==============================================================================
#
# 新手最容易踩的坑：列表可以反复遍历，迭代器只能用一次。
# 因为列表每次都能造新书签，而迭代器自己就是那个「一次性的书签」。

it = iter([1, 2, 3])
print("\n--- 迭代器只能用一次 ---")
print("第一次遍历：", list(it))     # list() 会把迭代器抽干
print("第二次遍历：", list(it))     # 已经空了

data = [1, 2, 3]
print("\n--- 列表可以反复遍历 ---")
print("第一次遍历：", list(iter(data)))   # 每次 iter() 都是新书签
print("第二次遍历：", list(iter(data)))

print("\n--- 迭代器的两个「不能」 ---")
try:
    print(len(it))
except TypeError as e:
    print("对迭代器用 len() 报错：", e)

try:
    print(it[0])
except TypeError as e:
    print("对迭代器用下标报错：", e)

# 输出：
# --- 迭代器只能用一次 ---
# 第一次遍历： [1, 2, 3]
# 第二次遍历： []
#
# --- 列表可以反复遍历 ---
# 第一次遍历： [1, 2, 3]
# 第二次遍历： [1, 2, 3]
#
# --- 迭代器的两个「不能」 ---
# 对迭代器用 len() 报错： object of type 'list_iterator' has no len()
# 对迭代器用下标报错： 'list_iterator' object is not subscriptable
#
# 【为什么】迭代器把「当前位置」存在自己身上，抽干后位置停在末尾，
#         再遍历当然什么都没有；列表本身不存位置。
# 【怎么避免】需要反复用的数据就保存成列表；只遍历一次的场合才用迭代器。


# ==============================================================================
# 知识点 6：怎么判断？__iter__ 和 __next__ 协议
# ==============================================================================
#
# Python 看的是对象有没有实现对应方法：
#     有 __iter__               →  可迭代对象（iterable）
#     有 __iter__ 和 __next__   →  迭代器（iterator）
#
# 【重点】迭代器一定也是可迭代对象（它多了 __next__）；
#         可迭代对象不一定是迭代器（比如列表）。
# 标准库 collections.abc 提供了现成的判断工具，比 hasattr() 更可靠。

from collections.abc import Iterable, Iterator

data = [1, 2, 3]
iterator = iter(data)

print("\n--- 用 isinstance 判断能力 ---")
print("列表是 Iterable 吗：", isinstance(data, Iterable))
print("列表是 Iterator 吗：", isinstance(data, Iterator))
print("迭代器是 Iterable 吗：", isinstance(iterator, Iterable))
print("迭代器是 Iterator 吗：", isinstance(iterator, Iterator))

# 输出：
# --- 用 isinstance 判断能力 ---
# 列表是 Iterable 吗： True
# 列表是 Iterator 吗： False
# 迭代器是 Iterable 吗： True
# 迭代器是 Iterator 吗： True
#
# 【注意】迭代器的 __iter__ 必须返回一个迭代器，惯例是 return self。
#         这就是为什么迭代器能直接放在 for 后面用。


# ==============================================================================
# 知识点 7：自己写一个迭代器 —— 倒计时
# ==============================================================================
#
# 只要实现了 __iter__ 和 __next__，你的类就能被 for 遍历。

class Countdown:
    """从 start 倒数到 1 的迭代器"""

    def __init__(self, start):
        self.current = start        # 状态：当前该数到几了

    def __iter__(self):
        return self                 # 我自己就是迭代器

    def __next__(self):
        if self.current <= 0:
            raise StopIteration     # 数到 0 了，结束
        value = self.current        # 先记下要返回的值
        self.current -= 1           # 状态往前走一步
        return value                # 再返回


print("\n--- 用 for 遍历自定义迭代器 ---")
for n in Countdown(3):
    print(f"  倒计时 {n}")
print("发射！")

countdown = Countdown(3)
print("\n--- 这个迭代器同样只能跑一次 ---")
print("第一次 list：", list(countdown))
print("第二次 list：", list(countdown))

# 如果希望「每次 for 都能从头开始」，就把状态拆出去：
# 对象只负责「造迭代器」，每次 __iter__ 都发一张全新的书签。

class CountdownFixed:
    """可反复遍历的倒计时：状态不留在自己身上"""

    def __init__(self, start):
        self.start = start

    def __iter__(self):
        return Countdown(self.start)    # 每次新建一个迭代器


print("\n--- 拆成两个类之后，可以反复遍历 ---")
fixed = CountdownFixed(3)
print("第一次 list：", list(fixed))
print("第二次 list：", list(fixed))

# 输出：
# --- 用 for 遍历自定义迭代器 ---
#   倒计时 3
#   倒计时 2
#   倒计时 1
# 发射！
#
# --- 这个迭代器同样只能跑一次 ---
# 第一次 list： [3, 2, 1]
# 第二次 list： []
#
# --- 拆成两个类之后，可以反复遍历 ---
# 第一次 list： [3, 2, 1]
# 第二次 list： [3, 2, 1]
#
# 【重点】__next__ 里必须做两件事：
#         1. 先判断「还有没有」—— 没有就 raise StopIteration
#         2. 先算返回值，再更新状态（顺序反了会少一个数或重复一个数）
# 【重点】「可迭代对象」和「迭代器」分开写，就能反复遍历。
#         标准库正是这么分工的（list 和 list_iterator）。
#
# 【常见错误】忘了写 __iter__，或者 __iter__ 返回 None，
#             都会得到 "'Xxx' object is not iterable" 这个 TypeError。
#
# 【为什么要多出「迭代器」这一层】有了统一接口，列表、文件、数据库游标
#   就能被同一段代码处理 —— 调用方只需知道「它能被迭代」，无需关心它是什么。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 可迭代对象：能用 for 遍历的东西，实现了 __iter__（列表、字符串、字典……）
# 2. 迭代器：记录「读到哪了」的一次性取值器，同时实现了 __iter__ 和 __next__
# 3. iter(x) 把可迭代对象变成迭代器；next(it) 取下一个值
# 4. 取完了再 next() 会抛 StopIteration；next(it, 默认值) 可以不抛
# 5. for 循环 = iter() + 反复 next() + 捕获 StopIteration
# 6. 迭代器是一次性的：抽干后第二次遍历得到空
# 7. 迭代器没有 len()、不支持下标、不能后退
# 8. 自定义迭代器：写 __iter__（返回 self）和 __next__（返回下一个值）
# 9. 想让对象可反复遍历，就把「可迭代对象」和「迭代器」拆成两个类


