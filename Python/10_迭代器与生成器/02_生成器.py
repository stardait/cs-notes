# ==============================================================================
# 知识点 1：yield —— 会「暂停」的 return
# ==============================================================================
#
# 普通函数用 return 交回结果，然后函数就死了，局部变量全销毁。
# 生成器函数用 yield 交回结果，但函数只是「暂停」，还活着，
# 局部变量和进度都原封不动地留着，下次叫它就从暂停处继续。
#
# 【生活类比】普通函数像「一次性快递」：送到就结束。
#             生成器像「食堂打饭阿姨」：给你一勺，手停一下，
#             你吃完再来，她接着从刚才那锅往下打。
#
# 【重点】函数体里只要出现 yield，这个函数就不再是普通函数，
#         而是一个「生成器函数」。调用它不会执行函数体，
#         只会返回一个生成器对象。

def make_numbers():
    print("  [函数体] 准备产出 1")
    yield 1                         # 交出 1，然后暂停在这里
    print("  [函数体] 准备产出 2")
    yield 2                         # 交出 2，再暂停
    print("  [函数体] 准备产出 3")
    yield 3
    print("  [函数体] 后面没有 yield 了，函数真正结束")


print("--- 调用生成器函数 ---")
print("调用前：什么都不会打印")
gen = make_numbers()                # 注意：函数体一行都没执行！
print("调用后：拿到的是", type(gen).__name__, "对象")

print("\n取第 1 个值")
print("取到：", next(gen))           # 这时才真正开始执行函数体
print("\n取第 2 个值")
print("取到：", next(gen))           # 从上次暂停的 yield 2 之前继续
print("\n取第 3 个值")
print("取到：", next(gen))
print("\n再取一次")
print("结果：", next(gen, "已经没有值了"))

# 输出：
# --- 调用生成器函数 ---
# 调用前：什么都不会打印
# 调用后：拿到的是 generator 对象
#
# 取第 1 个值
#   [函数体] 准备产出 1
# 取到： 1
#
# 取第 2 个值
#   [函数体] 准备产出 2
# 取到： 2
#
# 取第 3 个值
#   [函数体] 准备产出 3
# 取到： 3
#
# 再取一次
#   [函数体] 后面没有 yield 了，函数真正结束
# 结果： 已经没有值了
#
# 【重点】yield 干了三件事：
#         1. 把值交出去（像 return）
#         2. 把函数「冻结」在这里，保存所有局部变量
#         3. 等下一次 next() 时解冻，从下一行继续
# 【注意】最后那次 next() 会先把函数跑完（所以打印了最后一句），
#         函数正常结束时会抛 StopIteration，next 的默认值接住了它。


# ==============================================================================
# 知识点 2：生成器的执行流程 —— 暂停点在哪里
# ==============================================================================
#
# 把生成器和 for 循环配合，输出顺序会「交错」：
# 生成器产出一个值 → 循环体处理 → 回来再产出下一个……
#
# 看下面的输出，你会发现「准备 yield 2」出现在「处理 1」之后，
# 这就是「生成器暂停在 yield 那一行」的直接证据。

def counter(n):
    """从 1 数到 n，每数一个就交出去一次"""
    print(f"  [counter] 开始执行，n = {n}")
    for i in range(1, n + 1):
        print(f"  [counter] 准备 yield {i}")
        yield i                     # 暂停点：交出 i，等下一次 next
    print("  [counter] 循环结束")


print("\n--- 生成器与 for 循环交替执行 ---")
for value in counter(3):
    print(f"循环体：收到 {value}，正在处理")

# 输出：
# --- 生成器与 for 循环交替执行 ---
#   [counter] 开始执行，n = 3
#   [counter] 准备 yield 1
# 循环体：收到 1，正在处理
#   [counter] 准备 yield 2
# 循环体：收到 2，正在处理
#   [counter] 准备 yield 3
# 循环体：收到 3，正在处理
#   [counter] 循环结束
#
# 【重点】生成器不是「先算完所有结果再一个个给你」，
#         而是「你要一个，我算一个」。这才是它省内存的根本原因。


# ==============================================================================
# 知识点 3：惰性求值 —— 不取就不算
# ==============================================================================
#
# 「惰性」的意思是：能拖就拖，不真正需要就不干活。
# 生成器创建时不计算任何东西，只有 next() 才推动它往前走一步。
#
# 【好处】1. 省内存：不用把结果全放内存
#         2. 省时间：只用前几个，后面的根本不计算
#         3. 能表示无限序列（文件 04 会讲）

def number_stream(limit):
    """模拟一个很贵的数据源：每产出一个数都要「花力气」"""
    for i in range(1, limit + 1):
        print(f"  [数据源] 制造第 {i} 个数")
        yield i


print("\n--- 只取前 3 个，后面的不制造 ---")
stream = number_stream(100)         # 注意：这里不会制造任何数
print("生成器已创建，但一个数都还没造")
for value in stream:
    print("使用：", value)
    if value == 3:
        break                       # 提前退出，第 4 个以后根本没算

print("\n--- 生成器还停在原地，可以接着取 ---")
print("继续 next：", next(stream))

# 输出：
# --- 只取前 3 个，后面的不制造 ---
# 生成器已创建，但一个数都还没造
#   [数据源] 制造第 1 个数
# 使用： 1
#   [数据源] 制造第 2 个数
# 使用： 2
#   [数据源] 制造第 3 个数
# 使用： 3
#
# --- 生成器还停在原地，可以接着取 ---
#   [数据源] 制造第 4 个数
# 继续 next： 4
#
# 【重点】break 跳出 for 并不会销毁生成器，它只是「停在半路」。
#         这也是为什么生成器很适合「读大文件读到满足条件就停」。


# ==============================================================================
# 知识点 4：send() —— 不只是「取」，还能「送」
# ==============================================================================
#
# 之前都是我们向生成器要数据。send() 反过来：我们还能把数据送进去。
#
# yield 其实是一个「双向通道」：
#     value = yield 结果     ← 把「结果」交出去，同时准备接收外面送来的值
#
# 【重点】send(x) 会做两件事：
#         1. 把 x 送到上一次暂停的 yield 表达式的位置
#         2. 继续执行，直到遇到下一个 yield，并把那个值返回
#
# 【注意】刚创建的生成器还没停在任何 yield 上，
#         所以第一次必须用 next(g) 或 g.send(None) 启动，否则报错。

def adder():
    """累加器：每 send 一个数，就返回当前总和"""
    total = 0
    while True:
        value = yield total         # 交出 total，然后等外面 send 进来
        if value is None:
            break
        total += value


g = adder()
print("\n--- 用 send() 往生成器里送数据 ---")
print("启动（第一次必须 next 或 send(None)）：", next(g))
print("send(10) 后返回：", g.send(10))
print("send(20) 后返回：", g.send(20))
print("send(5)  后返回：", g.send(5))

# 输出：
# --- 用 send() 往生成器里送数据 ---
# 启动（第一次必须 next 或 send(None)）： 0
# send(10) 后返回： 10
# send(20) 后返回： 30
# send(5)  后返回： 35
#
# 【为什么第一次返回 0】因为生成器一启动就跑到 yield total，
#   此时 total 还是 0，所以先交出 0，然后停住等输入。

print("\n--- 第一次就 send 非 None 会怎样 ---")
g2 = adder()
try:
    g2.send(10)
except TypeError as e:
    print("报错：", e)

# 输出：
# --- 第一次就 send 非 None 会怎样 ---
# 报错： can't send non-None value to a just-started generator
#
# 【常见错误】忘了先 next(g) 启动，直接 g.send(值)，就会遇到这个 TypeError。
# 【小结】next(g) 等价于 g.send(None)：都不带数据，只让生成器往前走一步。


# ==============================================================================
# 知识点 5：生成器的状态与生命周期
# ==============================================================================
#
# 生成器一生只有三种状态（用 inspect.getgeneratorstate 查看）：
#
#     GEN_CREATED    刚创建，还没开始执行
#     GEN_SUSPENDED  执行到 yield 暂停了，等着被唤醒
#     GEN_CLOSED     执行完了，或者被 close() 掉了
#
# 【重点】生成器只能往前走，不能重置，也不能倒回去。

import inspect

print("\n--- 观察生成器的状态变化 ---")


def counter_state(n):
    for i in range(1, n + 1):
        yield i


g = counter_state(2)
print("刚创建：       ", inspect.getgeneratorstate(g))

value = next(g)
print(f"next 取到 {value}，状态：", inspect.getgeneratorstate(g))

value = next(g)
print(f"next 取到 {value}，状态：", inspect.getgeneratorstate(g))

try:
    next(g)
except StopIteration:
    print("取完了，抛出 StopIteration")
print("最终状态：     ", inspect.getgeneratorstate(g))

# 输出：
# --- 观察生成器的状态变化 ---
# 刚创建：        GEN_CREATED
# next 取到 1，状态： GEN_SUSPENDED
# next 取到 2，状态： GEN_SUSPENDED
# 取完了，抛出 StopIteration
# 最终状态：      GEN_CLOSED

print("\n--- close()：主动提前结束生成器 ---")


def worker():
    try:
        while True:
            yield "工作中"          # 无限生成，永远不会自己结束
    finally:
        print("  [worker] 收拾现场：关闭文件、释放连接")


w = worker()
print("取一次：", next(w))
print("调用 close() 结束它：")
w.close()                           # 会触发 finally 里的清理代码
print("关闭后的状态：", inspect.getgeneratorstate(w))

# 输出：
# --- close()：主动提前结束生成器 ---
# 取一次： 工作中
# 调用 close() 结束它：
#   [worker] 收拾现场：关闭文件、释放连接
# 关闭后的状态： GEN_CLOSED
#
# 【重点】生成器里用 try/finally 写清理代码，即使被 close() 或提前丢弃，
#         清理逻辑也会执行 —— 这就是生成器能安全管理资源的原因。
#
# 【补充】生成器函数也能写 return，它的作用是「提前结束」，
#         返回的值藏在 StopIteration.value 里，for 和 list() 都看不到，
#         日常开发几乎用不到，知道有这回事即可。


# ==============================================================================
# 知识点 6：【常见错误】新手必踩的三个坑
# ==============================================================================
#
# 坑 1：以为调用生成器函数就会执行 —— 其实只是造了个对象（见知识点 1）
# 坑 2：把生成器当列表反复用 —— 它只能用一次
# 坑 3：忘写 yield，函数就变回了普通函数，for 它会报 not iterable

print("\n--- 坑 2：生成器只能遍历一次 ---")


def simple():
    yield 1
    yield 2


g = simple()
print("第一次 list：", list(g))
print("第二次 list：", list(g))

print("\n--- 坑 3：用 return 代替 yield 就变回普通函数 ---")


def not_generator():
    return 1 + 1                    # 没有 yield，这是普通函数


result = not_generator()
print(f"调用结果：{result}，类型是 {type(result).__name__}")
try:
    for _ in result:
        pass
except TypeError as e:
    print("想 for 它就会报错：", e)

# 输出：
# --- 坑 2：生成器只能遍历一次 ---
# 第一次 list： [1, 2]
# 第二次 list： []
#
# --- 坑 3：用 return 代替 yield 就变回普通函数 ---
# 调用结果：2，类型是 int
# 想 for 它就会报错： 'int' object is not iterable
#
# 【怎么避免】
#   1. 看到 yield 就要意识到「这是个生成器，得驱动它」
#   2. 需要反复用的数据，先用 list() 物化（存成列表）
#   3. 报 "object is not iterable" 时，先检查函数里有没有写 yield


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 函数体里有 yield，它就是生成器函数；调用它返回生成器对象，不执行函数体
# 2. next() 驱动生成器：从上次暂停处继续，遇到 yield 再暂停
# 3. yield = 交出值 + 冻结现场（局部变量、执行位置都保留）
# 4. 惰性求值：不取就不算，所以省内存、能提前退出
# 5. send(x) 把值送进生成器，yield 表达式的结果就是它；第一次必须 send(None)
# 6. 三种状态：GEN_CREATED / GEN_SUSPENDED / GEN_CLOSED
# 7. close() 提前结束生成器，会触发 finally 里的清理代码
# 8. 生成器 return 的值藏在 StopIteration.value 里，for 和 list() 看不到
# 9. 生成器只能遍历一次；需要反复用就先 list() 存起来


