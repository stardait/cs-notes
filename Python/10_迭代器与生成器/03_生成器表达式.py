# ==============================================================================
# 知识点 1：语法 —— 方括号换成圆括号
# ==============================================================================
#
# 列表推导式：  [表达式 for 变量 in 可迭代对象 if 条件]
# 生成器表达式： (表达式 for 变量 in 可迭代对象 if 条件)
#
# 就只差一对括号，但结果天差地别：
#     列表推导式 → 立刻算出所有元素，返回 list
#     生成器表达式 → 只造一个生成器，一个元素都还没算
#
# 【重点】生成器表达式是「用一行代码写出的生成器函数」，
#         它同样有 yield 的「暂停 / 恢复」能力，只是语法更短。

numbers = [1, 2, 3, 4, 5]

list_result = [n * n for n in numbers]      # 立刻算完，得到列表
gen_result = (n * n for n in numbers)       # 只造生成器，不算

print("--- 两种写法的结果 ---")
print("列表推导式：", list_result)
print("生成器表达式的类型：", type(gen_result).__name__)
print("把生成器转成列表：", list(gen_result))

# 输出：
# --- 两种写法的结果 ---
# 列表推导式： [1, 4, 9, 16, 25]
# 生成器表达式的类型： generator
# 把生成器转成列表： [1, 4, 9, 16, 25]
#
# 【注意】生成器表达式的值就是「一个生成器对象」，
#         它不会打印出内容来，必须用 next() / for / list() 去驱动。

print("\n--- 用 for 逐个取出 ---")
squares = (n * n for n in range(1, 5))
for value in squares:
    print("平方：", value)

print("\n--- 也可以带 if 过滤 ---")
even_squares = (n * n for n in range(10) if n % 2 == 0)
print("偶数的平方：", list(even_squares))

# 输出：
# --- 用 for 逐个取出 ---
# 平方： 1
# 平方： 4
# 平方： 9
# 平方： 16
#
# --- 也可以带 if 过滤 ---
# 偶数的平方： [0, 4, 16, 36, 64]
#
# 【重点】内层的 if 是「过滤」，不是「筛选后再算」：
#         0 % 2 == 0 成立，所以 0 也进来了（0 的平方还是 0）。


# ==============================================================================
# 知识点 2：惰性求值 —— 生成器表达式的灵魂
# ==============================================================================
#
# 生成器表达式在「创建的那一刻」什么都不算，只有取值时才执行表达式。
# 这一点用「带副作用的表达式」最容易验证。

print("\n--- 表达式什么时候执行 ---")


def noisy_square(n):
    """每次被调用就打印一句，用来看清「什么时候算」"""
    print(f"  正在计算 {n} 的平方")
    return n * n


print("创建生成器：")
lazy = (noisy_square(n) for n in range(3))
print("创建完毕，上面有『正在计算』吗？没有！")

print("\n开始取值：")
print("拿到：", next(lazy))
print("拿到：", next(lazy))
print("拿到：", next(lazy))

# 输出：
# --- 表达式什么时候执行 ---
# 创建生成器：
# 创建完毕，上面有『正在计算』吗？没有！
#
# 开始取值：
#   正在计算 0 的平方
# 拿到： 0
#   正在计算 1 的平方
# 拿到： 1
#   正在计算 2 的平方
# 拿到： 4
#
# 【重点】每 next 一次，表达式才执行一次。这就是「惰性」。
# 【注意】这也是为什么生成器表达式里不要写「必须按顺序产生副作用」的代码，
#         因为执行时机被推迟了，容易让人误判。


# ==============================================================================
# 知识点 3：内存对比 —— 8 字节 vs 几百字节
# ==============================================================================
#
# 列表会把所有元素「物化」到内存里：n 个元素就要 n 份空间。
# 生成器不管多少元素，只占一个固定大小的对象（存着「算到哪了」）。
#
# 【生活类比】列表 = 把整本书打印出来放桌上；
#             生成器 = 只拿一张书签，需要哪页现翻哪页。

import sys

COUNT = 100000

big_list = [n for n in range(COUNT)]        # 真的存了 10 万个整数
big_gen = (n for n in range(COUNT))         # 只存了「下一个是几」

print("\n--- 内存占用对比 ---")
print(f"元素个数：{COUNT}")
print(f"列表占用：{sys.getsizeof(big_list)} 字节")
print(f"生成器占用：{sys.getsizeof(big_gen)} 字节")

print("\n--- 小数据也一样，生成器大小几乎不变 ---")
tiny_gen = (n for n in range(3))
print(f"3 个元素的生成器：{sys.getsizeof(tiny_gen)} 字节")
print(f"10 万个元素的生成器：{sys.getsizeof(big_gen)} 字节")

# 输出：
# --- 内存占用对比 ---
# 元素个数：100000
# 列表占用：800984 字节
# 生成器占用：216 字节
#
# --- 小数据也一样，生成器大小几乎不变 ---
# 3 个元素的生成器：216 字节
# 10 万个元素的生成器：216 字节
#
# 【重点】列表的大小随元素个数增长（每个元素一个指针，8 字节），
#         生成器的大小基本是固定的（几个 bookkeeping 字段）。
#         数据量越大，差距越夸张。
# 【注意】上面的具体字节数会随 Python 版本、操作系统略有差异，
#         但「列表随数据增长、生成器基本恒定」这个结论不会变。

print("\n--- 用 sum 直接消费，连 list 都不用建 ---")
print("1 到 100 万的和：", sum(n for n in range(1, 1_000_001)))
print("1 到 10 的平方和：", sum(n * n for n in range(1, 11)))

# 输出：
# --- 用 sum 直接消费，连 list 都不用建 ---
# 1 到 100 万的和： 500000500000
# 1 到 10 的平方和： 385
#
# 【重点】sum(n for n in range(...)) 全程只占一个生成器的内存，
#         即使数据量到 10 亿也不会爆内存。


# ==============================================================================
# 知识点 4：省略括号 —— 函数只有一个参数时
# ==============================================================================
#
# 当生成器表达式是函数的「唯一参数」时，外层圆括号可以省略：
#
#     sum((n for n in range(10)))   →   sum(n for n in range(10))
#
# 【注意】只有「唯一参数」时才行。如果有多个参数，括号不能省。
# 【常见错误】把 (x for x in ...) 当成元组 —— 它不是元组！
#             想造元组要用 tuple(x for x in ...) 或 tuple([...])。

print("\n--- 括号可省的场景 ---")
print("sum：", sum(n for n in range(5)))              # 省掉一层括号
print("max：", max(n * n for n in range(6)))          # 求最大平方
print("any：", any(n > 3 for n in range(5)))          # 有没有大于 3 的
print("all：", all(n >= 0 for n in range(5)))         # 是不是都非负
print("min：", min(abs(n - 5) for n in [1, 4, 9]))    # 离 5 最近的距离

# 输出：
# --- 括号可省的场景 ---
# sum： 10
# max： 25
# any： True
# all： True
# min： 1
#
# 【常见错误】以为多个参数也能省括号。下面这行会直接报错，
#   而且报的是「编译期」的 SyntaxError —— 整份代码都无法运行，
#   连 try/except 都救不了，所以这里只写成注释：
#
#   print(sum(n for n in range(5), 0))
#   # SyntaxError: Generator expression must be parenthesized

print("\n--- 想得到元组，要显式转换 ---")
gen = (n for n in range(3))
print("直接转换：", tuple(gen))
print("再转一次：", tuple(gen), "← 生成器已经空了")

# 输出：
# --- 想得到元组，要显式转换 ---
# 直接转换： (0, 1, 2)
# 再转一次： () ← 生成器已经空了
#
# 【怎么记】生成器表达式当参数时，只要函数还有别的参数，就必须自己带括号。
#         （这一行如果取消注释，整个文件都会运行不了，别轻易试。）


# ==============================================================================
# 知识点 5：大数据处理 —— 边读边算，不占内存
# ==============================================================================
#
# 真实场景里，数据往往「一次只能读一点」：日志文件、数据库游标、网络流。
# 这些场景天然适合生成器表达式：来一条处理一条，处理完就丢。
#
# 我们用一个「带计数器」的数据源来量化：到底处理了多少条？

print("\n--- 只处理最先满足条件的几条 ---")


def source(limit):
    """模拟逐个到达的数据，每产出一条就计数"""
    for i in range(1, limit + 1):
        print(f"  [数据源] 读取第 {i} 条")
        yield i


stream = source(1000)
# 生成器表达式：只要偶数，且平方大于 20
filtered = (n * n for n in stream if n % 2 == 0)
for value in filtered:
    if value > 20:
        print("第一个满足条件的值：", value)
        break

# 输出：
# --- 只处理最先满足条件的几条 ---
#   [数据源] 读取第 1 条
#   [数据源] 读取第 2 条
#   [数据源] 读取第 3 条
#   [数据源] 读取第 4 条
#   [数据源] 读取第 5 条
#   [数据源] 读取第 6 条
# 第一个满足条件的值： 36
#
# 【重点】即使数据源有 1000 条，实际只读到第 6 条就停了。
#         列表推导式做不到这一点 —— 它必须先算完 1000 条才能开始筛选。

print("\n--- 用列表推导式做同样的事，会读完全部 ---")


def source2(limit):
    for i in range(1, limit + 1):
        print(f"  [数据源] 读取第 {i} 条")
        yield i


# 先 list() 物化，再筛选：必须把数据源抽干
all_values = [n * n for n in source2(10) if n % 2 == 0]
print("列表里第一个大于 20 的：", next(v for v in all_values if v > 20))

# 输出：
# --- 用列表推导式做同样的事，会读完全部 ---
#   [数据源] 读取第 1 条
#   [数据源] 读取第 2 条
#   [数据源] 读取第 3 条
#   [数据源] 读取第 4 条
#   [数据源] 读取第 5 条
#   [数据源] 读取第 6 条
#   [数据源] 读取第 7 条
#   [数据源] 读取第 8 条
#   [数据源] 读取第 9 条
#   [数据源] 读取第 10 条
# 列表里第一个大于 20 的： 36
#
# 【重点】同样的答案，列表版把 10 条全读了，生成器版只读到第 6 条。
#         数据量越大、越早找到答案，差距越明显。


# ==============================================================================
# 知识点 6：【常见错误】和「怎么选」
# ==============================================================================
#
# 【常见错误 1】以为生成器表达式能反复用
# 【常见错误 2】对生成器用 len()、下标、排序
# 【常见错误 3】把生成器表达式当元组打印，结果是 <generator object ...>
#
# 【怎么选】
#   需要多次遍历、需要 len / 下标 / 排序      →  列表
#   只需要遍历一次、数据很大、可能提前结束     →  生成器表达式

print("\n--- 错误 1：只能用一次 ---")
gen = (n * 2 for n in range(3))
print("第一次：", list(gen))
print("第二次：", list(gen))

print("\n--- 错误 2：没有 len，没有下标 ---")
gen2 = (n * 2 for n in range(3))
try:
    print(len(gen2))
except TypeError as e:
    print("len 报错：", e)

try:
    print(gen2[0])
except TypeError as e:
    print("下标报错：", e)

print("\n--- 错误 3：打印出来看到的是对象，不是内容 ---")
gen3 = (n * 2 for n in range(3))
print("直接打印：", str(gen3).split(" at ")[0] + " at 0x...>")
print("转成列表：", list(gen3))

print("\n--- 正确做法：先物化再用 ---")
gen4 = (n * 2 for n in range(3))
materialized = list(gen4)           # 一次性抽干，存成列表
print("长度：", len(materialized))
print("第一个：", materialized[0])
print("倒序：", sorted(materialized, reverse=True))

# 输出：
# --- 错误 1：只能用一次 ---
# 第一次： [0, 2, 4]
# 第二次： []
#
# --- 错误 2：没有 len，没有下标 ---
# len 报错： object of type 'generator' has no len()
# 下标报错： 'generator' object is not subscriptable
#
# --- 错误 3：打印出来看到的是对象，不是内容 ---
# 直接打印： <generator object <genexpr> at 0x...>
# 转成列表： [0, 2, 4]
#
# --- 正确做法：先物化再用 ---
# 长度： 3
# 第一个： 0
# 倒序： [4, 2, 0]
#
# 【重点】「物化」就是 list(...)，代价是把结果全放进内存。
#         需要反复用就物化一次；只遍历一次就用生成器。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 生成器表达式：(表达式 for 变量 in 可迭代对象 if 条件)，类型是 generator
# 2. 它就是「一行写完的生成器函数」，一样惰性、一样只能遍历一次
# 3. 列表推导式立刻算完并存进内存；生成器表达式只造对象，取一个算一个
# 4. 内存：列表随数据增长，生成器大小基本不变
# 5. 函数只有唯一参数时，生成器表达式的括号可以省略：sum(n for n in ...)
# 6. (x for x in ...) 不是元组，是生成器；元组要写 tuple(...)
# 7. 大数据 / 提前结束的场景用生成器，能省内存、省时间
# 8. 需要 len / 下标 / 多次遍历，就用 list() 物化


