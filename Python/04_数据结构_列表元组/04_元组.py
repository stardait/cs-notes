# ==============================================================================
# 知识点 1：创建元组 —— 关键在逗号，不在括号
# ==============================================================================
#
# 【讲解】元组（tuple）和列表很像，都是有序序列，区别是：
#   列表可以改，元组创建后不能改。
#
#   常见创建方式：
#       (1, 2, 3)            普通元组
#       1, 2, 3              可以省略括号
#       (42,)                单元素元组，逗号不能省！
#       tuple(可迭代对象)     把别的序列转成元组
#
# 【重点】真正决定「这是不是元组」的是逗号，不是括号。
#   (42) 只是给 42 加了一对括号，它仍然是 int；
#   (42,) 才是一个包含一个元素的元组。
#
#   生活类比：元组像封好口的快递箱，里面的东西不能换；
#   列表像敞口的收纳盒，随时可以增删。

print("--- 创建元组 ---")

empty = ()
single = (42,)
normal = (1, 2, 3)
no_parens = "a", "b", "c"
from_list = tuple([1, 2, 3])
from_str = tuple("abc")
mixed = (1, "two", 3.0)
not_tuple = (42)

print(f"空元组：{empty}")
print(f"单元素元组：{single}")
print(f"普通元组：{normal}")
print(f"省略括号：{no_parens}")
print(f"列表转元组：{from_list}")
print(f"字符串转元组：{from_str}")
print(f"混合类型元组：{mixed}")
print(f"(42) 的值和类型：{not_tuple}，{type(not_tuple)}")

# 输出：
# --- 创建元组 ---
# 空元组：()
# 单元素元组：(42,)
# 普通元组：(1, 2, 3)
# 省略括号：('a', 'b', 'c')
# 列表转元组：(1, 2, 3)
# 字符串转元组：('a', 'b', 'c')
# 混合类型元组：(1, 'two', 3.0)
# (42) 的值和类型：42，<class 'int'>
#
# 【常见错误】写单元素元组时漏掉逗号：
#       point = (3)        # 这是 int，不是元组
#       point = (3,)       # 这才是元组
#   当元组里有两个及以上元素时，逗号是天然的，(1, 2) 不会歧义；
#   只有一个元素时，必须用「尾巴上的逗号」告诉 Python：这是元组。
#
# 【注意】空元组只能写 () 或 tuple()，没有「空逗号」这种写法。


# ==============================================================================
# 知识点 2：不可变性 —— 封箱之后不能换货
# ==============================================================================
#
# 【讲解】元组的「不可变」指的是：
#   创建后不能新增、删除、替换它里面的元素。
#
#   所以下面这些操作都不行：
#       point[0] = 10             不能改某个位置
#       point.append(5)           没有 append 方法
#       del point[0]              不能删某个元素
#
#   【为什么】元组常用来表示「不应该被修改的事实」，
#   比如坐标、RGB 颜色、一年四季。禁止修改可以防止意外改动。

print("--- 不可变性 ---")

point = (3, 4)
print(f"初始坐标：{point}")

try:
    point[0] = 10 # type: ignore
except TypeError as e:
    print(f"尝试修改元组：TypeError: {e}")

# 输出：
# --- 不可变性 ---
# 初始坐标：(3, 4)
# 尝试修改元组：TypeError: 'tuple' object does not support item assignment
#
# 【重点】「不可变」不等于「里面所有东西都不可变」。
#   元组只保证自己这一层元素的「引用」不变；
#   如果某个元素本身是列表，那个列表仍然可以被修改。

person = ("小明", 20, ["篮球", "音乐"])
person[2].append("编程")

print(f"\n修改元组里的列表后：{person}")
print("元组本身没变，变的只是它引用的那个列表")

# 输出：
#
# 修改元组里的列表后：('小明', 20, ['篮球', '音乐', '编程'])
# 元组本身没变，变的只是它引用的那个列表
#
# 【注意】别把可变对象放进元组又指望它「完全冻结」。
#   需要真正不可变的快照时，元组里也应该只放不可变对象。
#
# 【常见错误】想往元组里加东西，调用 append：
#       point.append(5)      # AttributeError: 'tuple' object has no attribute 'append'
#   元组根本没有 append、remove、sort 这些方法。

new_point = point + (6,)
print(f"\n用 + 拼接得到新元组：{new_point}")
print(f"原来的 point 完全没变：{point}")

# 输出：
#
# 用 + 拼接得到新元组：(3, 4, 6)
# 原来的 point 完全没变：(3, 4)
#
# 【重点】元组的 + 不是「往原来的元组里加」，而是创建新元组。
#   这和列表的 append 有本质区别。


# ==============================================================================
# 知识点 3：解包 —— 一次把多个值分给多个变量
# ==============================================================================
#
# 【讲解】解包（unpacking）是把序列里的元素，按位置分配给多个变量：
#
#       x, y = (3, 4)            x 得到 3，y 得到 4
#
#   变量个数必须和元素个数一致，否则报 ValueError。
#
#   星号解包可以收集「剩下的一堆」：
#       first, *middle, last = (1, 2, 3, 4, 5)
#       first = 1，middle = [2, 3, 4]，last = 5
#
#   【注意】带星号的变量拿到的是列表，即使只剩一个元素也是列表。

print("--- 解包 ---")

point = (3, 4)
x, y = point
print(f"点坐标解包：x={x}, y={y}")

student = ("小明", 20, "北京")
name, age, city = student
print(f"学生信息：姓名={name}, 年龄={age}, 城市={city}")

numbers = (1, 2, 3, 4, 5)
first, *middle, last = numbers
print(f"首尾和中间：first={first}, middle={middle}, last={last}")

a, b = 1, 2
a, b = b, a
print(f"交换后：a={a}, b={b}")

def min_max(values):
    return min(values), max(values)

low, high = min_max([4, 1, 9, 2])
print(f"最小值={low}, 最大值={high}")

# 用下划线表示「这个位置我不关心」
name2, _, score = ("小红", 20, 95)
print(f"忽略年龄字段：姓名={name2}, 成绩={score}")

try:
    a, b = (1, 2, 3) # type: ignore
except ValueError as e:
    print(f"解包数量不匹配：ValueError: {e}")

# 输出：
# --- 解包 ---
# 点坐标解包：x=3, y=4
# 学生信息：姓名=小明, 年龄=20, 城市=北京
# 首尾和中间：first=1, middle=[2, 3, 4], last=5
# 交换后：a=2, b=1
# 最小值=1, 最大值=9
# 忽略年龄字段：姓名=小红, 成绩=95
# 解包数量不匹配：ValueError: too many values to unpack (expected 2, got 3)
#
# 【重点】`a, b = b, a` 之所以能交换，是因为等号右边先被当成一个元组 (b, a)，
#   再把两个值分别解包给左边的 a、b，不需要临时变量。
#
# 【常见错误】变量个数和元素个数不一致，例如 x, y = (1, 2, 3)。
#   报错信息会告诉你 expected 2，意思是左边期待 2 个变量。
#
# 【常见错误】把解包当成「按索引挑元素」：解包是逐个位置分配，不能跳过中间元素；
#   想只取部分，用切片或星号收集再取需要的值。


# ==============================================================================
# 知识点 4：namedtuple —— 给元组字段起名字
# ==============================================================================
#
# 【讲解】普通元组只能靠位置记：point[0] 是 x 还是 y？元素一多就很容易搞混。
#
#   collections.namedtuple 可以创建一个「带字段名的元组类」：
#       Point = namedtuple("Point", ["x", "y"])
#       p = Point(3, 4)
#
#   之后可以：
#       p.x、p.y       按名字访问，清楚
#       p[0]、p[1]     仍然支持按位置访问
#       p._asdict()    转成字典
#       p._replace()   生成修改了某些字段的新元组
#
# 【重点】namedtuple 本质上还是元组，依然不可变。
#   p.x = 10 会报错；想改字段用 p._replace(x=10)，它返回一个新对象。

print("--- namedtuple ---")

from collections import namedtuple

Point = namedtuple("Point", ["x", "y"])
p = Point(3, 4)

print(f"p = {p}")
print(f"p 的类型：{type(p)}")
print(f"按名字访问：p.x={p.x}, p.y={p.y}")
print(f"按下标访问：p[0]={p[0]}, p[1]={p[1]}")
print(f"字段名：{Point._fields}")
print(f"转成字典：{p._asdict()}")

p2 = p._replace(x=10)
print(f"_replace 得到新元组：{p2}")
print(f"原来的 p 不变：{p}")

px, py = p
print(f"namedtuple 也能解包：x={px}, y={py}")

# 输出：
# --- namedtuple ---
# p = Point(x=3, y=4)
# p 的类型：<class '__main__.Point'>
# 按名字访问：p.x=3, p.y=4
# 按下标访问：p[0]=3, p[1]=4
# 字段名：('x', 'y')
# 转成字典：{'x': 3, 'y': 4}
# _replace 得到新元组：Point(x=10, y=4)
# 原来的 p 不变：Point(x=3, y=4)
# namedtuple 也能解包：x=3, y=4
#
# 【注意】type(p) 显示 `<class '__main__.Point'>`，因为它继承自 tuple。
#
# 【重点】_replace 不是「把 p 改了」，而是「复制一份并替换字段」。
#   所以一定要接住返回值：p = p._replace(x=10)。
#
# 【常见错误】直接给字段赋值 p.x = 10 会报 AttributeError，因为它继承了元组的不可变性。


# ==============================================================================
# 知识点 5：元组 vs 列表 —— 到底该用哪个？
# ==============================================================================
#
# 【讲解】两者都是有序序列，很多操作长得一样：
#   索引、切片、len()、in、遍历、解包都支持。
#
#   真正的区别在「语义」和「可变性」：
#
#   列表 list：
#       - 用 [] 创建
#       - 可以增删改，长度可变
#       - 适合「同类元素的集合」，后续还会变化
#       - 例子：购物车、待办清单、成绩列表
#
#   元组 tuple：
#       - 用 () 或逗号创建
#       - 创建后不能增删改
#       - 适合「固定结构的一条记录」，字段有明确含义
#       - 例子：坐标 (x, y)、RGB 颜色、一年四季
#
# 【重点】选择标准不是「谁更快」，而是「这个数据应不应该被修改」。
#   如果一组值天然就是一个整体、且不应该变，用元组；
#   如果是一个会增减的集合，用列表。

print("--- 元组 vs 列表 ---")

weekdays = ("周一", "周二", "周三", "周四", "周五", "周六", "周日")
todo = ["写作业", "买菜"]

print(f"一周固定七天：{weekdays}")
print(f"待办清单：{todo}")

todo.append("跑步")
print(f"待办可以增加：{todo}")

try:
    weekdays.append("周八") # type: ignore
except AttributeError as e:
    print(f"元组没有 append：AttributeError: {e}")

print(f"元组转列表：{list(weekdays)[:3]}……")
print(f"列表转元组：{tuple(todo)}")

# 输出：
# --- 元组 vs 列表 ---
# 一周固定七天：('周一', '周二', '周三', '周四', '周五', '周六', '周日')
# 待办清单：['写作业', '买菜']
# 待办可以增加：['写作业', '买菜', '跑步']
# 元组没有 append：AttributeError: 'tuple' object has no attribute 'append'
# 元组转列表：['周一', '周二', '周三']……
# 列表转元组：('写作业', '买菜', '跑步')
#
# 【注意】元组和列表可以互相转换，但转换会创建新对象。
#   如果某个函数明确要求列表，而你手里是元组，用 list() 转一下即可。
#
# 【常见错误】用元组只是因为「看起来更高级」或「听说更快」。
#   如果数据后续要增删改，用元组会逼你不停创建新元组，代码又长又慢。
#   先问语义，再选类型。


# ==============================================================================
# 知识点 6：常见误区速查
# ==============================================================================
#
# 【讲解】元组的坑集中在「逗号」和「不可变」两件事上。
#
#   误区 1：以为 (42) 是元组           → 其实是 int，必须写 (42,)
#   误区 2：以为元组里的列表不能改     → 列表本身仍然可以改（见知识点 2）
#   误区 3：以为元组能 append          → 没有这个方法
#   误区 4：以为解包变量可以多几个     → 数量必须匹配，或用 * 收集

print("--- 常见误区 ---")

print(f"(42) 的类型：{type((42))}")
print(f"(42,) 的类型：{type((42,))}")

ranked = sorted((3, 1, 2))
print(f"sorted(元组) 得到：{ranked}")
print(f"返回类型：{type(ranked)}")

# 输出：
# --- 常见误区 ---
# (42) 的类型：<class 'int'>
# (42,) 的类型：<class 'tuple'>
# sorted(元组) 得到：[1, 2, 3]
# 返回类型：<class 'list'>
#
# 【注意】sorted() 对任何可迭代对象都返回「列表」，不是返回元组。
#   如果确实需要元组结果，要再包一层：tuple(sorted(data))。
#
# 【常见错误】在函数参数里写默认值 default=() 没问题，
#   但如果期望它是「每个调用独立的一份」，请确认里面的元素不可变；
#   元组本身不可变，但里面若装了列表，那个列表仍然是共享的。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 元组用 () 创建，但真正决定身份的是逗号；(42) 是 int，(42,) 才是元组
# 2. 元组有序、不可变，不能改元素、不能增删，也没有 append/remove/sort
# 3. 元组的「不可变」只到第一层；里面如果放列表，列表仍然可以改
# 4. 解包可以一次给多个变量赋值，变量个数必须和元素个数匹配
# 5. 星号解包 first, *middle, last 会把中间部分收集成一个列表
# 6. namedtuple 让元组有了字段名，支持 p.x、_asdict()、_replace()
# 7. namedtuple 仍然不可变，_replace() 返回的是新对象
# 8. 元组适合固定记录（坐标、日期、配置），列表适合会变化的集合（购物车、待办）
# 9. sorted(元组) 返回列表；需要元组结果时用 tuple(sorted(data))


