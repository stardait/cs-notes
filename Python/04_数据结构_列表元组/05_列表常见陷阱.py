# ==============================================================================
# 知识点 1：可变默认参数 —— 那个「永远清不空」的购物车
# ==============================================================================
#
# 【讲解】看下面这个函数：
#
#       def add_item(item, basket=[]):
#           basket.append(item)
#           return basket
#
#   你可能以为：每次调用都会新建一个空列表 basket，然后加一个东西。
#   实际不是！默认参数的值只在「定义函数的那一刻」创建一次，
#   之后所有调用共用同一个列表。
#
#   生活类比：商场门口放了一个「默认购物车」。
#   第一位顾客用了没清空，第二位顾客推走的还是同一辆车，
#   里面还留着上一位顾客的东西。
#
# 【重点】默认参数只在函数定义时求值一次，不会每次调用都重新创建。
#   可变对象（list、dict、set）作为默认参数，就会变成「跨调用共享」。

print("--- 可变默认参数：错误示范 ---")

def add_item(item, basket=[]):
    basket.append(item)          # 每次都往同一个默认列表里加
    return basket

print(f"第一次调用：{add_item('苹果')}")
print(f"第二次调用：{add_item('香蕉')}")
print(f"第三次调用：{add_item('橘子')}")

# 输出：
# --- 可变默认参数：错误示范 ---
# 第一次调用：['苹果']
# 第二次调用：['苹果', '香蕉']
# 第三次调用：['苹果', '香蕉', '橘子']
#
# 【为什么】basket 的默认值 [] 在 def 执行时就创建好了，
#   之后 add_item 每次调用都复用这同一个列表对象。
#   所以「第二次调用」并不是从空列表开始，而是接着上一次的结果。
#
# 【正确写法】用 None 作为默认值，在函数内部再创建新列表。

print("--- 可变默认参数：正确写法 ---")

def add_item_safe(item, basket=None):
    if basket is None:           # 只有没传篮子时，才新建一个
        basket = []
    basket.append(item)
    return basket

print(f"第一次调用：{add_item_safe('苹果')}")
print(f"第二次调用：{add_item_safe('香蕉')}")

custom_basket = ["牛奶"]
print(f"传入自己的篮子：{add_item_safe('面包', custom_basket)}")
print(f"自己的篮子被修改：{custom_basket}")

# 输出：
# --- 可变默认参数：正确写法 ---
# 第一次调用：['苹果']
# 第二次调用：['香蕉']
# 传入自己的篮子：['牛奶', '面包']
# 自己的篮子被修改：['牛奶', '面包']
#
# 【重点】判断必须写 `is None`，不要写 `if not basket`。
#   因为空列表 [] 也是「假值」，如果调用者故意传了一个空列表，
#   `if not basket` 会错误地再新建一个，反而不会修改调用者的列表。
#
# 【常见错误】
#   1. def f(items=[])          → 默认列表跨调用共享
#   2. def f(items=[]) 里用 items += ...  → 同样会污染默认值
#   3. 修复时只写 if not items  → 传空列表时语义错误
#   正确模板：def f(items=None): if items is None: items = []


# ==============================================================================
# 知识点 2：赋值、浅拷贝、深拷贝 —— 三种「复制」差很多
# ==============================================================================
#
# 【讲解】先记住一句话：
#       等号不是复制，只是给同一个对象再贴一个标签。
#
#   三种层次：
#
#   1. 直接赋值：b = a
#      两个变量指向同一个列表。改 b 就是改 a。
#
#   2. 浅拷贝：b = a.copy()（或 a[:]、list(a)、copy.copy(a)）
#      创建新的外层列表，但里面的元素还是原来的引用。
#      对一维列表足够安全；对嵌套列表，内层仍然共享。
#
#   3. 深拷贝：b = copy.deepcopy(a)
#      递归复制每一层，外层、内层、更深层都互相独立。
#
#   生活类比：
#       赋值 = 把同一个房间的钥匙多配一把
#       浅拷贝 = 新建一个文件柜，但里面放的还是原来那些文件夹
#       深拷贝 = 连文件夹里的每一张纸都复印一份，放进新文件柜

print("--- 赋值不是拷贝 ---")

a = [1, 2, 3]
b = a
b.append(4)

print(f"a：{a}")
print(f"b：{b}")
print(f"a is b：{a is b}")

# 输出：
# --- 赋值不是拷贝 ---
# a：[1, 2, 3, 4]
# b：[1, 2, 3, 4]
# a is b：True
#
# 【重点】a 和 b 不是两个列表，而是同一个列表的两个名字。
#   修改 b 就是修改 a，不存在「谁影响谁」的问题，它们根本是同一个对象。
#
# 【重点】`is` 判断是否为同一个对象，`==` 判断值是否相等。
#   这里用 is 是为了确认 a、b 根本是同一个列表，而不是内容相同的两份副本。

print("\n--- 浅拷贝：一维列表是安全的 ---")

c = a.copy()
c.append(5)

print(f"a：{a}")
print(f"c：{c}")
print(f"a is c：{a is c}")

# 输出：
#
# --- 浅拷贝：一维列表是安全的 ---
# a：[1, 2, 3, 4]
# c：[1, 2, 3, 4, 5]
# a is c：False
#
# 【注意】对于只装数字、字符串等不可变元素的一维列表，
#   copy() 之后就可以放心改，互不影响。

print("\n--- 浅拷贝：嵌套列表会露馅 ---")

import copy

nested = [[1, 2], [3, 4]]
shallow = nested.copy()
shallow_by_module = copy.copy(nested)
deep = copy.deepcopy(nested)

print(f"nested is shallow：{nested is shallow}")
print(f"nested[0] is shallow[0]：{nested[0] is shallow[0]}")
print(f"copy.copy 的内层也共享：{nested[0] is shallow_by_module[0]}")

shallow[0][0] = 999

print(f"改浅拷贝的内层后，nested：{nested}")
print(f"shallow 自己：{shallow}")
print(f"深拷贝 deep 不受影响：{deep}")

# 输出：
#
# --- 浅拷贝：嵌套列表会露馅 ---
# nested is shallow：False
# nested[0] is shallow[0]：True
# copy.copy 的内层也共享：True
# 改浅拷贝的内层后，nested：[[999, 2], [3, 4]]
# shallow 自己：[[999, 2], [3, 4]]
# 深拷贝 deep 不受影响：[[1, 2], [3, 4]]
#
# 【重点】浅拷贝只复制「最外面这一层」。
#   外层列表是新的，但 nested[0] 和 shallow[0] 指向同一个内层列表，
#   所以改内层时，两个外层列表都会看到变化。
#
# 【常见错误】以为 nested.copy() 之后就得到了完全独立的副本。
#   只要列表里还有可变对象（列表、字典、集合），就必须考虑 deepcopy。
#
# 【权衡】deepcopy 会递归复制，速度和内存开销都更大。
#   只有确实存在嵌套可变对象时才需要它；一维列表用 copy() 就够。


# ==============================================================================
# 知识点 3：循环中删除元素 —— 边走边拆桥，会漏掉人
# ==============================================================================
#
# 【讲解】很多新手会这样写：
#
#       for n in nums:
#           if n % 2 == 0:
#               nums.remove(n)
#
#   看起来是「遍历每个元素，遇到偶数就删掉」，
#   实际上 Python 的 for 循环在内部维护一个「当前走到第几个」的计数器。
#   你删掉一个元素后，后面的元素整体前移，但计数器照样往前走，
#   于是紧跟在被删元素后面的那个元素就被跳过了。
#
#   生活类比：点名时点到第 2 个人，把他叫走，
#   第 3 个人立刻补到第 2 个位置；老师接着点「第 3 个」，
#   结果原来第 3 个人被跳过，直接点到了原来第 4 个人。

print("--- 边遍历边删除：错误示范 ---")

numbers = [2, 2, 3]

print(f"删除前：{numbers}")
for n in numbers:
    if n % 2 == 0:
        numbers.remove(n)

print(f"删除后：{numbers}")

# 输出：
# --- 边遍历边删除：错误示范 ---
# 删除前：[2, 2, 3]
# 删除后：[2, 3]
#
# 【重点】结果里还剩一个 2！原因：
#   第 1 轮取到索引 0 的 2，remove 删掉它，列表变成 [2, 3]；
#   下一轮计数器指向索引 1，也就是 3，第二个 2 被跳过，再也没被检查。
#
# 【常见错误】以为「只删一个、刚好删完」就没事。
#   这个 bug 的隐蔽之处在于：代码不报错，数据量小时结果甚至可能碰巧正确。
#   一旦数据里有连续重复项，就会出问题。

print("\n--- 正确做法 1：用推导式生成新列表 ---")

clean = [n for n in [2, 2, 3] if n % 2 != 0]
print(f"筛选出奇数：{clean}")

# 输出：
#
# --- 正确做法 1：用推导式生成新列表 ---
# 筛选出奇数：[3]
#
# 【重点】这是最推荐的做法：不修改原列表，直接生成想要的新列表。
#   如果还需要原数据，也不会被破坏。

print("\n--- 正确做法 2：遍历副本 ---")

safe_numbers = [2, 2, 3]
for n in safe_numbers[:]:         # [:] 复制一份，遍历副本
    if n % 2 == 0:
        safe_numbers.remove(n)

print(f"遍历副本删除后：{safe_numbers}")

# 输出：
#
# --- 正确做法 2：遍历副本 ---
# 遍历副本删除后：[3]
#
# 【注意】这里遍历的是 safe_numbers[:] 这个新列表，
#   删除的是 safe_numbers 本身。遍历的列表没有被改动，所以不会跳元素。

print("\n--- 正确做法 3：倒着删 ---")

safe_numbers2 = [2, 2, 3]
index = len(safe_numbers2) - 1

while index >= 0:
    if safe_numbers2[index] % 2 == 0:
        safe_numbers2.pop(index)  # 从后往前删，不会影响还没检查的下标
    index -= 1

print(f"倒序删除后：{safe_numbers2}")

# 输出：
#
# --- 正确做法 3：倒着删 ---
# 倒序删除后：[3]
#
# 【权衡】三种写法怎么选：
#   要保留原列表、生成筛选结果  → 推导式
#   必须原地修改，且元素不多    → 遍历副本
#   必须原地修改，且按下标处理  → 从后往前遍历


# ==============================================================================
# 知识点 4：乘法创建嵌套列表 —— 三行一起变，因为它们是同一行
# ==============================================================================
#
# 【讲解】想创建一个 3×3 的零矩阵，新手常写：
#
#       rows = [[0] * 3] * 3
#
#   看起来是「三行，每行三个 0」，实际上只创建了一行，
#   然后把这同一行的引用复制了三份。
#
#   生活类比：三个门牌号写着不同的地址，但钥匙其实是同一把，
#   打开任何一扇门，进的都是同一个房间。
#
# 【重点】列表乘法复制的是「引用」，不是「对象本身」。
#   对不可变元素（数字、字符串）没问题；
#   对可变元素（内层列表）就会得到三个共享同一个内层列表的「假独立行」。

print("--- 乘法创建嵌套列表：错误示范 ---")

rows = [[0] * 3] * 3
print(f"初始矩阵：{rows}")
print(f"rows[0] is rows[1]：{rows[0] is rows[1]}")
print(f"rows[0] is rows[2]：{rows[0] is rows[2]}")

rows[0][0] = 1
print(f"只改第一行第一列后：{rows}")

# 输出：
# --- 乘法创建嵌套列表：错误示范 ---
# 初始矩阵：[[0, 0, 0], [0, 0, 0], [0, 0, 0]]
# rows[0] is rows[1]：True
# rows[0] is rows[2]：True
# 只改第一行第一列后：[[1, 0, 0], [1, 0, 0], [1, 0, 0]]
#
# 【重点】三行的「外壳」看起来不同，但里面是同一个内层列表对象。
#   所以 rows[0][0] = 1 会同时影响三行。

print("\n--- 正确写法：用推导式创建独立的内层列表 ---")

rows_safe = [[0] * 3 for _ in range(3)]
print(f"rows_safe[0] is rows_safe[1]：{rows_safe[0] is rows_safe[1]}")

rows_safe[0][0] = 1
print(f"只改第一行第一列后：{rows_safe}")

# 输出：
#
# --- 正确写法：用推导式创建独立的内层列表 ---
# rows_safe[0] is rows_safe[1]：False
# 只改第一行第一列后：[[1, 0, 0], [0, 0, 0], [0, 0, 0]]
#
# 【注意】内层的 [0] * 3 是安全的，因为 0 是不可变整数，
#   三个 0 共享同一个整数对象也没关系，改一个位置只是换掉那个位置的引用。
#   危险的是「用乘法复制可变对象」。
#
# 【常见错误】用 [[0] * 3] * 3 之后发现数据串了，
#   又用 copy.copy() 去补，结果还是浅拷贝，问题依旧。
#   正确做法是让每一行在构造时分别创建：[[0] * 3 for _ in range(3)]。


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 可变默认参数只在函数定义时创建一次，会跨调用共享；应改为 None 再在内部创建
# 2. 判断默认参数要用 `is None`，不要用 `if not basket`
# 3. b = a 只是多一个名字；改 b 就是改 a
# 4. copy() / a[:] / list(a) / copy.copy(a) 都是浅拷贝，只复制外层
# 5. 嵌套可变对象要用 copy.deepcopy()，它会递归复制每一层
# 6. 不要在 for 循环遍历列表的同时直接删除元素，否则会跳元素
# 7. 删除元素的三种安全写法：推导式、遍历副本、从后往前删
# 8. [[0] * 3] * 3 得到的是三个共享的内层列表，不是三行独立数据
# 9. 创建二维列表用 [[0] * 3 for _ in range(3)]
# 10. `is` 判断是不是同一个对象，`==` 判断值是否相等，别混用


