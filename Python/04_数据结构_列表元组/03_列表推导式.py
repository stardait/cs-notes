# ==============================================================================
# 知识点 1：基础推导式 —— 把循环和 append 压成一行
# ==============================================================================
#
# 【讲解】列表推导式（list comprehension）用来从一个序列出发，
#   对每个元素做同样的处理，生成一个新列表。
#
#   基本语法：
#       [对每个元素做什么  for 元素 in 原序列]
#
#   生活类比：给全班同学每人拍一张证件照。
#       普通循环：拿相机，走到每个人面前，拍一张，放进相册（append）
#       推导式：一句「给每个人拍一张」，相机自动走完全班
#
# 【重点】推导式的结果永远是一个新列表，它不会修改原列表。
#   读的时候从中间的 for 开始读：「对每个 n，把 n*n 放进新列表」。

print("--- 基础推导式 ---")

# 普通循环：先建空列表，再逐个 append
squares_loop = []
for n in range(1, 6):
    squares_loop.append(n * n)

print(f"循环写法：{squares_loop}")

# 推导式：同样的逻辑，一行完成
squares_comp = [n * n for n in range(1, 6)]
print(f"推导式写法：{squares_comp}")

names = ["Tom", "Alice", "Bob"]
name_lengths = [len(name) for name in names]
print(f"每个名字的长度：{name_lengths}")

# 输出：
# --- 基础推导式 ---
# 循环写法：[1, 4, 9, 16, 25]
# 推导式写法：[1, 4, 9, 16, 25]
# 每个名字的长度：[3, 5, 3]
#
# 【注意】推导式里的表达式可以调用函数，比如 len(name)、str.upper()，
#   只要它能根据当前元素算出一个值就行。
#
# 【常见错误】把推导式当成「执行动作」的工具：
#       [print(x) for x in range(3)]
#   它能运行，但会生成 [None, None, None] 这个没用的列表。
#   只是想打印，就老老实实写 for 循环。


# ==============================================================================
# 知识点 2：条件过滤 —— 只要满足条件的元素
# ==============================================================================
#
# 【讲解】在推导式末尾加 if，只保留满足条件的元素：
#
#       [表达式 for 元素 in 原序列 if 条件]
#
#   读法：「对每个元素，如果条件成立，才把表达式的结果放进新列表」。
#
#   注意 if 在 for 后面，它是「过滤器」，不是「二选一」。
#   不满足条件的元素会被直接丢掉，不会出现在结果里。

print("--- 条件过滤 ---")

numbers = range(1, 11)
evens = [n for n in numbers if n % 2 == 0]
print(f"1~10 的偶数：{evens}")

words = ["apple", "kiwi", "banana", "fig"]
long_words = [word for word in words if len(word) >= 5]
print(f"长度至少为 5 的单词：{long_words}")

selected = [n for n in range(1, 20) if n % 3 == 0 and n % 2 != 0]
print(f"1~19 中能被 3 整除的奇数：{selected}")

# 输出：
# --- 条件过滤 ---
# 1~10 的偶数：[2, 4, 6, 8, 10]
# 长度至少为 5 的单词：['apple', 'banana']
# 1~19 中能被 3 整除的奇数：[3, 9, 15]
#
# 【重点】if 后面不写 else。因为过滤是「留或不留」，
#   没有「留下来的元素替换成什么」这回事。
#
# 【常见错误】把 if 放在 for 前面：
#       [n for if n % 2 == 0 n in numbers]     # 语法错误
#   顺序永远是：表达式 → for → if。


# ==============================================================================
# 知识点 3：if-else 表达式 —— 不是过滤，是「二选一替换」
# ==============================================================================
#
# 【讲解】如果你希望「满足条件的变一个样，不满足的变另一个样」，
#   那用的是 Python 的条件表达式（三元表达式），位置在 for 前面：
#
#       [值A if 条件 else 值B for 元素 in 原序列]
#
#   它和上一节的过滤完全不同：
#       过滤：不满足条件的元素直接消失，结果可能变短
#       二选一：每个元素都保留，只是值被替换，结果长度不变
#
# 【重点】位置决定含义：
#       if 在 for 前面 → 二选一，必须带 else
#       if 在 for 后面 → 过滤，不能带 else
#   这是新手最容易混淆的地方。

print("--- if-else 表达式 ---")

nums = [1, 2, 3, 4, 5]

parity = ["偶数" if n % 2 == 0 else "奇数" for n in nums]
print(f"判断奇偶：{parity}")

replaced = [n if n % 2 == 0 else 0 for n in nums]
print(f"偶数保留、奇数变 0：{replaced}")

# 输出：
# --- if-else 表达式 ---
# 判断奇偶：['奇数', '偶数', '奇数', '偶数', '奇数']
# 偶数保留、奇数变 0：[0, 2, 0, 4, 0]
#
# 【注意】replaced 的长度还是 5，因为每个元素都保留了下来；
#   而上一节的 evens 长度变短了，因为它是过滤。
#
# 【常见错误】写出下面这种「四不像」，Python 会直接报 SyntaxError：
#       [n if n % 2 == 0 for n in nums]
#   三元表达式要求 if 和 else 成对出现，缺一不可。


# ==============================================================================
# 知识点 4：嵌套推导式 —— 双层循环，从外到内
# ==============================================================================
#
# 【讲解】推导式里可以有多个 for，书写顺序和普通嵌套循环一致：
#
#       [元素 for 外层变量 in 外层序列 for 内层变量 in 内层序列]
#
#   等价于：
#       for 外层变量 in 外层序列:
#           for 内层变量 in 内层序列:
#               把元素放进新列表
#
#   最左边的 for 是最外层循环，越往右越靠内。
#
#   两种常见用法：
#       1. 展平二维列表：把 [[1,2], [3,4]] 变成 [1, 2, 3, 4]
#       2. 生成二维结构：对每一行、每一列做处理

print("--- 嵌套推导式 ---")

matrix = [
    [1, 2, 3],
    [4, 5, 6],
]

# 展平：外层先取每一行，内层再取行里的每个数字
flattened = [num for row in matrix for num in row]
print(f"展平矩阵：{flattened}")

# 生成新矩阵：对矩阵里的每个数字求平方
squared = [[num * num for num in row] for row in matrix]
print(f"每个元素平方：{squared}")

# 转置：原来的每一列，变成新矩阵的每一行
transposed = [[row[i] for row in matrix] for i in range(3)]
print(f"转置矩阵：{transposed}")

colors = ["红", "蓝"]
sizes = ["S", "M"]
pairs = [(color, size) for color in colors for size in sizes]
print(f"颜色与尺码组合：{pairs}")

# 输出：
# --- 嵌套推导式 ---
# 展平矩阵：[1, 2, 3, 4, 5, 6]
# 每个元素平方：[[1, 4, 9], [16, 25, 36]]
# 转置矩阵：[[1, 4], [2, 5], [3, 6]]
# 颜色与尺码组合：[('红', 'S'), ('红', 'M'), ('蓝', 'S'), ('蓝', 'M')]
#
# 【重点】展平矩阵时，两个 for 的顺序不能反：
#       [num for row in matrix for num in row]   # 正确，按行展开
#       [num for num in row for row in matrix]   # 错误，row 还没定义
#
# 【注意】转置的写法有点绕，可以拆成普通循环理解：
#   外层 for i in range(3) 决定新矩阵有几行；
#   内层 [row[i] for row in matrix] 把原矩阵每一行的第 i 个元素收集起来。
#
# 【常见错误】嵌套推导式超过两层还硬写，别人（以及三个月后的你）很难读懂。
#   可读性优先，复杂逻辑请改回普通循环。


# ==============================================================================
# 知识点 5：性能对比 —— 推导式为什么通常更快？
# ==============================================================================
#
# 【讲解】列表推导式在 CPython 里由解释器做了专门优化：
#   它省掉了「反复查找 append 方法」和「反复调用函数」的开销，
#   在内存里一次把结果列表构建好。
#
#   但请记住：
#       1. 快是「通常」，不是绝对；数据量很小时差距可以忽略
#       2. 可读性通常比这点性能更重要
#       3. 真正遇到性能瓶颈，应该用 timeit / cProfile 测，而不是猜
#
# 【注意】下面不打印具体秒数，因为每台机器、每次运行都不同，
#   写死在注释里会变成「假输出」。我们只比较快慢，并验证结果一致。

print("--- 性能对比 ---")

import timeit

result_a = [n * n for n in range(100)]
result_b = []
for n in range(100):
    result_b.append(n * n)

print(f"两种写法结果一致：{result_a == result_b}")

# number 表示把这段代码重复执行多少次，用来放大差异、减少计时误差
comp_time = timeit.timeit(
    "[n * n for n in range(100)]",
    number=2000,
)
loop_time = timeit.timeit(
    "squares = []\nfor n in range(100):\n    squares.append(n * n)",
    number=2000,
)

print(f"列表推导式更快：{comp_time < loop_time}")
print("（具体秒数每次运行都不同，所以这里只比较快慢，不打印数字）")

# 输出：
# --- 性能对比 ---
# 两种写法结果一致：True
# 列表推导式更快：True
# （具体秒数每次运行都不同，所以这里只比较快慢，不打印数字）
#
# 【重点】推导式通常更快，不是因为它「更高级」，
#   而是因为它少了一些解释器层面的重复开销。
#
# 【常见错误】为了追求这种微小的速度优势，把复杂业务逻辑塞进推导式。
#   结果代码难读、难调试，性能收益可能只有几毫秒，完全不划算。


# ==============================================================================
# 知识点 6：可读性建议 —— 什么时候「不要」用推导式
# ==============================================================================
#
# 【讲解】推导式适合「一眼能看懂」的简单转换。
#   判断标准可以记成下面几条：
#
#   ✅ 适合用推导式：
#       - 一个 for + 一个简单的 if 过滤
#       - 对每个元素做简单的运算或方法调用
#       - 展平简单的二维列表
#
#   ❌ 不适合用推导式：
#       - 需要同时维护多个变量、状态
#       - 里面要写 try/except 或复杂的 if-elif
#       - 为了「炫技」把三层 for 塞进一行
#       - 只是想在循环里打印或修改外部状态
#
# 【重点】代码是写给人看的，顺便给机器执行。
#   当推导式需要你停下来想 10 秒才能读懂时，就该换成普通循环了。

print("--- 可读性建议 ---")

scores = [58, 72, 90, 45, 66]

# 简单清晰：筛选及格的同学，并给每人加 5 分
passed_boosted = [score + 5 for score in scores if score >= 60]
print(f"及格并加 5 分：{passed_boosted}")

# 等价的普通循环，逻辑更显式
passed_boosted_loop = []
for score in scores:
    if score >= 60:
        passed_boosted_loop.append(score + 5)

print(f"循环写法结果相同：{passed_boosted == passed_boosted_loop}")

# 输出：
# --- 可读性建议 ---
# 及格并加 5 分：[77, 95, 71]
# 循环写法结果相同：True
#
# 【注意】这个例子只有一个 for 和一个简单 if，是推导式的「舒适区」。
#   如果条件变成「三科都及格、平均分超过 80、还要排除缺考」，
#   就请老老实实写普通循环，并给中间变量起有意义的名字。
#
# 【常见错误】把「副作用」写进推导式：
#       [file.close() for file in files]    # 能运行，但语义很奇怪
#   一旦需要执行动作而不是生成值，就应该用 for 循环。
#   推导式的本质是「根据旧列表生成新列表」，不是「循环控制语句」。


# ==============================================================================
# 知识点 7：作用域与常见错误
# ==============================================================================
#
# 【讲解】Python 3 的推导式有自己独立的作用域。
#   推导式里用的循环变量，不会泄漏到外面的代码里。
#
# 【重点】这和普通 for 循环不一样：
#       普通 for 循环的变量在循环结束后还能访问
#       推导式的循环变量在外面访问会报 NameError
#
#   所以推导式里可以放心用 n、x 这种短名字，
#   不必担心污染外层的同名变量。

print("--- 作用域 ---")

squares = [secret * secret for secret in range(5)]
print(f"结果：{squares}")

try:
    print(secret) # type: ignore
except NameError as e:
    print(f"推导式外访问 secret：NameError: {e}")

# 输出：
# --- 作用域 ---
# 结果：[0, 1, 4, 9, 16]
# 推导式外访问 secret：NameError: name 'secret' is not defined
#
# 【常见错误汇总】
#   1. 过滤 if 带了 else：
#          [n for n in nums if n % 2 == 0 else 0]      # SyntaxError
#   2. 三元 if 没带 else：
#          [n if n > 0 for n in nums]                  # SyntaxError
#   3. 嵌套循环顺序写反：
#          [num for num in row for row in matrix]      # NameError
#   4. 把推导式当循环用，只为打印：
#          [print(n) for n in nums]                    # 生成一堆 None
#   5. 把推导式结果丢掉：
#          [n * 2 for n in nums]                       # 算完就扔，毫无意义
#
# 【注意】最后一条是纯新手坑：推导式不会修改原列表。
#   如果需要一个处理后的列表，请把结果赋给变量：
#       doubled = [n * 2 for n in nums]


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. 推导式语法：[表达式 for 元素 in 序列]，返回新列表，不修改原列表
# 2. 过滤：if 写在 for 后面，不满足条件的元素被丢弃，不能带 else
# 3. 二选一：if-else 写在 for 前面，每个元素都保留，必须带 else
# 4. 嵌套推导式按 for 的先后顺序执行，左边最外层，右边最内层
# 5. 展平二维列表：[num for row in matrix for num in row]
# 6. 推导式通常比「for + append」快，但具体耗时要用 timeit 实测
# 7. 简单转换用推导式；复杂逻辑、副作用、多层嵌套请用普通循环
# 8. Python 3 推导式的循环变量不会泄漏到外层作用域
# 9. 推导式的本质是「生成新列表」，不是「执行循环动作」


