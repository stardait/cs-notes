# 5. and / or 返回操作数本身，支持短路，可用来写「默认值」
# 6. 位运算符 & | ^ ~ << >> 操作二进制，适合权限、标志位
# 7. 优先级：数学 > 位运算 > 比较 > not > and > or > :=
# 8. `**` 右结合，一元负号低于 `**`，所以 -2 ** 2 是 -4
# 9. `:=` 在表达式里赋值，注意括号，别滥用
# 10. 上面每个「输出」都亲手跑一遍，比读十遍都管用


