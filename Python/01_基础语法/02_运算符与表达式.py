# 知识点 1：算术运算符 —— 七个符号，四个带坑
# ==============================================================================
#
# 用「分蛋糕」类比两个数 a 和 b：
#   /    精确分：切碎了也要分匀，结果一定是 float
#   //   整块分：只要整数块，剩下的不要（向下取整）
#   %    看剩下：分完还剩几块（取余数）
#   **   叠起来：b 个 a 相乘
#
# 【重点】`/` 永远返回 float，除得尽也是：10 / 5 得 2.0，不是 2。
#        这是 Python 3 和 Python 2 最大的差别之一，也是新手第一个坑。

a, b = 17, 5                      # 元组解包：一次给两个变量赋值

print(f"{a} + {b} = {a + b}")     # 加
print(f"{a} - {b} = {a - b}")     # 减
print(f"{a} * {b} = {a * b}")     # 乘
print(f"{a} / {b} = {a / b}")     # 真除法：结果一定是 float
print(f"{a} // {b} = {a // b}")   # 整除：只要整数部分
print(f"{a} % {b} = {a % b}")     # 取余：分完之后剩下的
print(f"{a} ** {b} = {a ** b}")   # 幂运算
print(f"10 / 5 = {10 / 5}，type = {type(10 / 5).__name__}")   # 除得尽仍是 float

# 输出：
# 17 + 5 = 22
# 17 - 5 = 12
# 17 * 5 = 85
# 17 / 5 = 3.4
# 17 // 5 = 3
# 17 % 5 = 2
# 17 ** 5 = 1419857
# 10 / 5 = 2.0，type = float

# 【补充】divmod(a, b) 一次拿到 (商, 余数)，最实用的场景是秒数转时分秒。
minutes, seconds = divmod(3725, 60)      # 3725 秒 → 62 分 5 秒
hours, minutes = divmod(minutes, 60)     # 62 分 → 1 时 2 分
print(f"3725 秒 = {hours} 时 {minutes} 分 {seconds} 秒")

# 输出：
# 3725 秒 = 1 时 2 分 5 秒


# ==============================================================================
# 知识点 2：负数的 // 和 % —— 从 C 转过来的人 100% 会踩
# ==============================================================================
#
# 【重点】Python 的 `//` 是「向下取整」（floor），不是「向零取整」。
#   -7 / 2 = -3.5，数轴上往左（更小）取整是 -4，所以 -7 // 2 得 -4。
#   C / Java / Go 的整数除法是向零截断，同一个算式得 -3 —— 移植代码必翻车。
#
# 【为什么 % 也跟着怪】Python 保证恒等式 a == (a // b) * b + a % b 永远成立，
#   所以余数的符号必须跟着「除数」走，而不是跟着被除数走。

print(f"-7 // 2 = {-7 // 2}   ← 向下取整到 -4，不是 -3")
print(f"-7 % 2 = {-7 % 2}    ← 余数符号跟着除数 2")
print(f"7 % -2 = {7 % -2}    ← 余数符号跟着除数 -2")

a, b = -7, 2
check = (a // b) * b + a % b       # 用商和余数反推被除数
print(f"验证：{a // b} * {b} + {a % b} = {check}，等于 a 吗？{check == a}")

# 输出：
# -7 // 2 = -4   ← 向下取整到 -4，不是 -3
# -7 % 2 = 1    ← 余数符号跟着除数 2
# 7 % -2 = -1    ← 余数符号跟着除数 -2
# 验证：-4 * 2 + 1 = -7，等于 a 吗？True
#
# 【怎么办】写代码前先问「这里会出现负数吗」。要「向零取整」的效果，用 int(a / b)。


# ==============================================================================
# 知识点 3：比较运算符 —— 以及 Python 独有的链式比较
# ==============================================================================
#
#   == 等于   != 不等于   > 大于   < 小于   >= 大于等于   <= 小于等于
# 比较的结果永远是 bool（True / False）。

x, y = 10, 20

print(f"{x} == {y} → {x == y}，{x} != {y} → {x != y}")
print(f"{x} > {y} → {x > y}，{x} >= {y} → {x >= y}")

# 输出：
# 10 == 20 → False，10 != 20 → True
# 10 > 20 → False，10 >= 20 → False

# 【重点】Python 支持「链式比较」，数学里怎么写，代码里就怎么写。
#        `1 < x < 10` 等价于 `1 < x and x < 10`，但 x 只算一次。
print(f"1 < 2 < 3 → {1 < 2 < 3}，1 < 3 < 2 → {1 < 3 < 2}")

score = 85
print(f"60 <= {score} <= 100 → {60 <= score <= 100}   ← 判断成绩是否及格")

# 输出：
# 1 < 2 < 3 → True，1 < 3 < 2 → False
# 60 <= 85 <= 100 → True   ← 判断成绩是否及格

# 字符串也能比大小：按字符编码从左往右逐位比，像查字典。
print(f"'apple' < 'banana' → {'apple' < 'banana'}")
print(f"'10' < '9' → {'10' < '9'}   ← 比的是字符不是数值；'Z' < 'a' → {'Z' < 'a'}，大写编码小")

# 输出：
# 'apple' < 'banana' → True
# '10' < '9' → True   ← 比的是字符不是数值；'Z' < 'a' → True，大写编码小

# 【常见错误】== 和 is 分不清：
#   == 问「内容一样吗」，is 问「是不是同一个对象（同一块内存）」。
list_a = [1, 2, 3]
list_b = [1, 2, 3]                 # 新建一个内容相同的列表
list_c = list_a                    # 别名：两个名字指向同一个列表

print(f"list_a == list_b → {list_a == list_b}   ← 内容相同")
print(f"list_a is list_b → {list_a is list_b}   ← 但不是同一个对象")
print(f"list_a is list_c → {list_a is list_c}   ← 同一个对象")

# 输出：
# list_a == list_b → True   ← 内容相同
# list_a is list_b → False   ← 但不是同一个对象
# list_a is list_c → True   ← 同一个对象
#
# 【重点】判断 None 用 is，判断数值 / 内容用 ==：`if x is None:`


# ==============================================================================
# 知识点 4：逻辑运算符 and / or / not —— 返回的不是布尔值！
# ==============================================================================
#
# 字面意思是 and「并且」、or「或者」、not「取反」。
#
# 【重点】但 and / or 返回的是「决定结果的那个操作数」，不是 True/False：
#   a and b ：谁第一个是假值就返回谁；全真则返回最后一个
#   a or  b ：谁第一个是真值就返回谁；全假则返回最后一个
#   not  a  ：老实人，一定返回 True / False
# 判断真假沿用 bool() 规则（文件 01）：0、0.0、""、[]、None 都是假。

print(f"True and 'ok' → {True and 'ok'}，False and 'ok' → {False and 'ok'}")
print(f"0 and 'ok' → {0 and 'ok'}，'' or '默认值' → {'' or '默认值'}")
print(f"'hi' or '默认值' → {'hi' or '默认值'}，not '' → {not ''}")

# 输出：
# True and 'ok' → ok，False and 'ok' → False
# 0 and 'ok' → 0，'' or '默认值' → 默认值
# 'hi' or '默认值' → hi，not '' → True

# 【为什么】这样设计是为了支持「短路求值」：左边一旦能决定结果，右边就不执行。
#   好处是 `if user is not None and user.age > 18` 左边失败时，右边不会报错。
# 下面定义个小函数，它被调用时会打印一行。函数第 3 章才讲，
# 这里只要知道「它被调用 = 右边真的执行了」。
def check(name):
    print(f"  → 真的执行了 check('{name}')")
    return True

print("--- 短路求值 ---")
print(f"False and check('A') → {False and check('A')}")   # 左边假，右边跳过
print(f"True or check('B') → {True or check('B')}")      # 左边真，右边跳过
print(f"True and check('C') → {True and check('C')}")    # 左边真，必须看右边

# 输出：
# --- 短路求值 ---
# False and check('A') → False
# True or check('B') → True
#   → 真的执行了 check('C')
# True and check('C') → True
#
# 【注意】第三行前面多出来的那句，是 check() 先执行时打印的。
#        短路省掉的不只是判断，还有「副作用」。

# 由此还能写出很地道的「给默认值」写法：
user_input = ""                    # 模拟用户什么都没输入
name = user_input or "匿名用户"      # 空串是假值 → 取右边的默认值
print(f"昵称：{name}")

# 输出：
# 昵称：匿名用户
#
# 【常见错误】以为 True and 'ok' 的结果是 True，它其实是字符串 'ok'。
#            想要真布尔就套一层 bool()。


# ==============================================================================
# 知识点 5：位运算符 —— 直接对二进制动手
# ==============================================================================
#
# 位运算不分大小，一位一位地算，像「一排开关」：1 是开，0 是关。
#   &   与：两个都是 1 才得 1        |   或：有一个 1 就得 1
#   ^   异或：两个不同才得 1          ~   取反：0 变 1、1 变 0
#   <<  左移：相当于乘 2 的 n 次方     >>  右移：相当于整除 2 的 n 次方
# 用途：权限控制、标志位、图像与网络协议的底层处理。

print(f"6 = {6:04b}，3 = {3:04b}")     # b 表示二进制，04 表示补足 4 位
print(f"6 & 3 = {6 & 3}，6 | 3 = {6 | 3}，6 ^ 3 = {6 ^ 3}   ← 与 / 或 / 异或")
print(f"~6 = {~6}，6 << 1 = {6 << 1}，6 >> 1 = {6 >> 1}   ← 取反 / 左移 / 右移")

# 输出：
# 6 = 0110，3 = 0011
# 6 & 3 = 2，6 | 3 = 7，6 ^ 3 = 5   ← 与 / 或 / 异或
# ~6 = -7，6 << 1 = 12，6 >> 1 = 3   ← 取反 / 左移 / 右移
#
# 【为什么】0110 & 0011 = 0010（两位都是 1 才得 1）；0110 | 0011 = 0111；
#         0110 ^ 0011 = 0101（不同才得 1）。
# 【为什么】~6 得 -7：Python 的整数没有位数上限，取反等于 -x-1，按补码解释。

# 最经典的实战：一位一权限，管理读 / 写 / 执行。
READ, WRITE, EXEC = 0b100, 0b010, 0b001    # 各占一位，互不干扰

perm = READ | WRITE                        # 打开读 + 写
print(f"初始权限：{perm:03b}（{perm}）")
perm |= EXEC                               # 追加执行权限
print(f"加上 EXEC：{perm:03b}（{perm}）")
perm &= ~WRITE                             # 去掉写：~WRITE 是「除了写全开」的掩码
print(f"去掉 WRITE：{perm:03b}（{perm}）")
print(f"有读权限吗？{bool(perm & READ)}")
print(f"有写权限吗？{bool(perm & WRITE)}")   # 那一位已抹掉 → 0 → False

# 输出：
# 初始权限：110（6）
# 加上 EXEC：111（7）
# 去掉 WRITE：101（5）
# 有读权限吗？True
# 有写权限吗？False

# 【常见错误】把 & 当成 and 用。
print(f"6 and 3 = {6 and 3}   ← 两个都是真值，返回最后一个")
print(f"6 & 3 = {6 & 3}     ← 真的按位算")

# 输出：
# 6 and 3 = 3   ← 两个都是真值，返回最后一个
# 6 & 3 = 2     ← 真的按位算
#
# 【注意】`0b10 and 0b01` 得 1，不是 0 —— 两个都是非零真值。
#        想做位运算就用 & | ^，别用 and or。


# ==============================================================================
# 知识点 6：运算符优先级 —— 记不住就加括号
# ==============================================================================
#
# 从高到低：
#   **  >  +x -x ~x  >  * / // %  >  + -  >  << >>  >  &  >  ^  >  |  >
#   比较（== != < <= > >= is in）>  not  >  and  >  or  >  :=
#
# 【重点】一句话记忆：数学 > 位运算 > 比较 > not > and > or。
#        另外 ** 是右结合，一元负号比 ** 低，所以 -2 ** 2 是 -(2**2)。

print(f"2 + 3 * 4 = {2 + 3 * 4}，(2 + 3) * 4 = {(2 + 3) * 4}")
print(f"-2 ** 2 = {-2 ** 2}，(-2) ** 2 = {(-2) ** 2}   ← 一元负号比 ** 低")
print(f"2 ** 3 ** 2 = {2 ** 3 ** 2}，1 + 2 << 2 = {1 + 2 << 2}，not 2 > 1 = {not 2 > 1}")

# 输出：
# 2 + 3 * 4 = 14，(2 + 3) * 4 = 20
# -2 ** 2 = -4，(-2) ** 2 = 4   ← 一元负号比 ** 低
# 2 ** 3 ** 2 = 512，1 + 2 << 2 = 12，not 2 > 1 = False

# and 比 or 先算，这是最容易看错的一行：
print(f"True or False and False = {True or False and False}")
print(f"(True or False) and False = {(True or False) and False}")

# 输出：
# True or False and False = True
# (True or False) and False = False
#
# 【为什么】第一行等价于 True or (False and False) = True。
#          C / Java 也是这个顺序，但永远建议加括号，可读性比省字符重要。
#
# 【为什么 Python 比 C 安全】C 里 `&` 优先级低于 `==`，
# `perm & READ == READ` 会被解析成 `perm & (READ == READ)`，是经典 bug。
# Python 把 `&` 放到了比较之前，所以下面这行是「先与、再比较」：
perm = 0b110
print(f"perm & 0b100 == 0b100 → {perm & 0b100 == 0b100}")

# 输出：
# perm & 0b100 == 0b100 → True


# ==============================================================================
# 知识点 7：海象运算符 := —— 在表达式里顺手赋值
# ==============================================================================
#
# Python 3.8 新增，名字来自符号本身：横过来像海象的眼睛和两颗牙。
#   =  是「语句」，只能单独站一行，不能塞进 if 的条件里
#   := 是「表达式」，有值、能嵌在别的表达式里
# 典型用法：算一次、存起来、马上用，避免同一个表达式写两遍。

text = "Python"
if (n := len(text)) > 3:            # 边算长度边存到 n，然后比大小
    print(f"'{text}' 的长度是 {n}，超过 3 个字符")

data = [3, 8, 1, 0, 9]
i = 0
print("--- 用 := 边读边判断 ---")
while (value := data[i]) != 0:      # 读到 0 就停
    print(f"读到 {value}")
    i += 1
print(f"遇到 0 停止，停在下标 {i}")

# 输出：
# 'Python' 的长度是 6，超过 3 个字符
# --- 用 := 边读边判断 ---
# 读到 3
# 读到 8
# 读到 1
# 遇到 0 停止，停在下标 3

# 还能用在推导式里：先算、再筛、顺便留下结果。
numbers = [1, 2, 3, 4, 5, 6, 7, 8]
squares = [s for x in numbers if (s := x * x) > 20]
print(f"平方大于 20 的：{squares}")

# 输出：
# 平方大于 20 的：[25, 36, 49, 64]

# 【常见错误】漏括号，语义完全变了。:= 优先级最低，
# 所以 `x := a > b` 会先算 `a > b` 得到布尔值，再赋给 x。
value = 7
if (half := value / 2) > 3:          # 正确：先算 value/2 存进 half，再比较
    print(f"正确写法：half = {half}，大于 3")
if flag := value / 2 > 3:            # 错：flag 拿到的是 bool，不是 3.5
    print(f"漏括号写法：flag = {flag}，类型 {type(flag).__name__}")

# 输出：
# 正确写法：half = 3.5，大于 3
# 漏括号写法：flag = True，类型 bool
#
# 【注意】在 if / while 的条件里，:= 可以不加最外层括号；
#        但只要它出现在别的表达式内部（比如作为比较的一边），就必须加括号。
# 【重点】:= 别滥用。它的价值是「不重复计算」，纯粹为少写一行会让代码变难读。


# ==============================================================================
# 【常见错误速查】
# ==============================================================================
#
# 1. 把 = 当 == ：`if x = 1:` 直接语法错误（这点 Python 比 C 友好）
# 2. 负数除法方向搞反：-7 // 2 是 -4，不是 -3
# 3. 以为 and / or 返回 True/False，其实返回的是操作数
# 4. 浮点数用 == 比较：0.1 + 0.2 == 0.3 是 False，要用 math.isclose()
# 5. 用 & 代替 and（或反过来）：6 and 3 得 3，6 & 3 得 2
# 6. := 漏括号：`if x := a > b:` 里 x 会变成布尔值
# 7. 依赖优先级不写括号：多写一对括号，永远不算亏


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. `/` 永远返回 float；`//` 整除；`%` 取余；`**` 幂
