# ==============================================================================
# 知识点 1：变量 —— Python 里变量是什么？
# ==============================================================================
#
# 【重要】Python 的变量不是「装东西的盒子」，而是「贴在东西上的标签」。
#
#   C / Java 的做法（盒子模型）：
#       int a = 100;      分配一块内存，命名为 a，把 100 放进去
#       a = 200;          把盒子里的 100 换成 200
#
#   Python 的做法（标签模型）：
#       a = 100           在内存里创建整数对象 100，把标签 a 贴上去
#       a = 200           创建新对象 200，把标签 a 从 100 撕下来贴到 200 上
#                         原来的 100 没人引用了，稍后被自动回收
#
# 这个区别现在看不出影响，但学「可变/不可变」时就是分水岭。

name = "Alice"      # 给字符串 "Alice" 贴上标签 name
age = 20            # 给整数 20 贴上标签 age
score = 95.5        # 给浮点数 95.5 贴上标签 score
is_pass = True      # 给布尔值 True 贴上标签 is_pass

print("name =", name)
print("age =", age)
print("score =", score)
print("is_pass =", is_pass)

# 输出：
# name = Alice
# age = 20
# score = 95.5
# is_pass = True



















# ==============================================================================
# 知识点 2：四种基本数据类型
# ==============================================================================
#
# int    整数：    1, -5, 0, 1000000（Python 的整数没有大小上限！）
# float  浮点数：  3.14, -0.001, 2.0, 1e10（科学计数法）
# str    字符串：  "hello", 'Python', """多行文本"""
# bool   布尔值：  True / False（注意首字母大写！）
#
# 【额外】NoneType：只有一个值 None，表示「什么都没有」

integer = 42
floating = 3.14159
text = "你好，Python"
boolean = False
nothing = None

print("\n--- 四种基本类型 ---")
print(integer, type(integer))
print(floating, type(floating))
print(text, type(text))
print(boolean, type(boolean))
print(nothing, type(nothing))

# 输出：
# --- 四种基本类型 ---
# 42 <class 'int'>
# 3.14159 <class 'float'>
# 你好，Python <class 'str'>
# False <class 'bool'>
# None <class 'NoneType'>
#
# 【注意】type() 返回的是 <class 'xxx'>，说明 Python 里「类型也是对象」。
#         这为后面学面向对象埋下伏笔。
















# ==============================================================================
# 知识点 3：整数 vs 浮点数 —— 一个最常见的坑
# ==============================================================================
#
# Python 的整数是「精确」的，浮点数是「近似」的。
# 因为浮点数用二进制表示小数，有些十进制小数无法精确存储。

print("\n--- 浮点数精度问题 ---")
print("0.1 + 0.2 =", 0.1 + 0.2)
print("是否等于 0.3：", 0.1 + 0.2 == 0.3)

# 输出：
# 0.1 + 0.2 = 0.30000000000000004
# 是否等于 0.3： False
#
# 【为什么】0.1 和 0.2 在二进制里是无限循环小数，存进去就被截断了。
#         这不是 Python 的 bug，所有语言（C、Java、JS）都一样。
#
# 【怎么办】
#   1. 需要精确计算（钱）：用 decimal 模块
#   2. 比较浮点数：用 math.isclose()

import math

print("用 math.isclose 比较：", math.isclose(0.1 + 0.2, 0.3))
print("整数除法 10/2 =", 10 / 2, "  ← 结果仍是 float")
print("整除 10//3 =", 10 // 3, "  ← // 是整除，向下取整")
print("取余 10%3 =", 10 % 3)
print("幂运算 2**10 =", 2 ** 10)

# 输出：
# 用 math.isclose 比较： True
# 整数除法 10/2 = 5.0   ← 结果仍是 float
# 整除 10//3 = 3   ← // 是整除，向下取整
# 取余 10%3 = 1
# 幂运算 2**10 = 1024
#
# 【重点】Python 3 里 `/` 永远返回 float，要整数结果必须用 `//`。






















# ==============================================================================
# 知识点 4：动态类型 —— Python 不像 C 那样声明类型
# ==============================================================================
#
# C / Java：变量有固定类型，只能装该类型的数据
#     int a = 10;
#     a = "hello";   // 编译错误！
#
# Python：变量没有类型，只有「当前指向的对象」有类型
#     a = 10        此时 a 指向 int
#     a = "hello"   现在 a 指向 str，完全合法

dynamic = 100
print("\n--- 动态类型 ---")
print("初始：", dynamic, type(dynamic))

dynamic = "现在变成字符串了"
print("改变：", dynamic, type(dynamic))

dynamic = [1, 2, 3]
print("再改变：", dynamic, type(dynamic))

# 输出：
# --- 动态类型 ---
# 初始： 100 <class 'int'>
# 改变： 现在变成字符串了 <class 'str'>
# 再改变： [1, 2, 3] <class 'list'>
#
# 【好处】写起来灵活，不用先想好类型。
# 【坏处】类型错误在运行时才暴露（C/Java 编译期就能发现）。
#         所以 Python 需要写测试，或者用类型标注（type hint）。






















# ==============================================================================
# 知识点 5：类型转换（casting）
# ==============================================================================
#
# 常用转换函数：
#     int(x)      → 转整数（会截断小数部分，不是四舍五入！）
#     float(x)    → 转浮点数
#     str(x)      → 转字符串
#     bool(x)     → 转布尔值

print("\n--- 类型转换 ---")

# int() 会「截断」小数，不是四舍五入
print("int(3.9)  =", int(3.9), "  ← 截断，不是四舍五入")
print("int(-3.9) =", int(-3.9), "  ← 向零取整")
print("round(3.9)=", round(3.9), "  ← 这才是四舍五入")

# 字符串转数字
print("int('123')   =", int("123"))
print("float('3.14')=", float("3.14"))

# 注意：不能把非数字字符串转成数字
try:
    int("hello")
except ValueError as e:
    print("int('hello') 报错：", e)

# bool() 的真相：空的东西都是 False
print("\n--- bool() 转换规则 ---")
print("bool(0)      =", bool(0))
print("bool(0.0)    =", bool(0.0))
print("bool('')     =", bool(''))
print("bool([])     =", bool([]))
print("bool(None)   =", bool(None))
print("bool(-1)     =", bool(-1), "  ← 非零整数都是 True")
print("bool('0')    =", bool('0'), "  ← 非空字符串都是 True（注意！）")

# 输出：
# --- 类型转换 ---
# int(3.9)  = 3   ← 截断，不是四舍五入
# int(-3.9) = -3   ← 向零取整
# round(3.9)= 4   ← 这才是四舍五入
# int('123')   = 123
# float('3.14')= 3.14
# int('hello') 报错： invalid literal for int() with base 10: 'hello'
#
# --- bool() 转换规则 ---
# bool(0)      = False
# bool(0.0)    = False
# bool('')     = False
# bool([])     = False
# bool(None)   = False
# bool(-1)     = True   ← 非零整数都是 True
# bool('0')    = True   ← 非空字符串都是 True（注意！）
#
# 【重点】bool('0') 是 True！因为 '0' 是非空字符串。
#         这是新手最容易搞错的点之一。

















# ==============================================================================
# 知识点 6：命名规范（PEP 8）
# ==============================================================================
#
# Python 官方风格指南 PEP 8 的命名规则：
#
#   变量 / 函数：用小写 + 下划线（snake_case）
#       ✅ user_name, total_price, calculate_score
#       ❌ userName, TotalPrice（这是 Java/JS 风格）
#
#   常量：全大写 + 下划线
#       ✅ MAX_SIZE, PI, DEFAULT_TIMEOUT
#
#   类名：大驼峰（PascalCase）
#       ✅ Student, BankAccount
#
#   私有变量：前面加下划线
#       ✅ _internal_cache
#
# 【为什么重要】Python 社区高度统一，不按规范写别人会觉得你「不像写 Python 的」。

MAX_STUDENTS = 100          # 常量：全大写
default_timeout = 30        # 变量：小写下划线
_student_count = 0          # 私有：下划线开头

print("\n--- 命名规范示例 ---")
print("常量 MAX_STUDENTS =", MAX_STUDENTS)
print("普通变量 default_timeout =", default_timeout)
print("私有变量 _student_count =", _student_count)
























# ==============================================================================
# 知识点 7：一次赋值多个变量
# ==============================================================================

print("\n--- 多变量赋值 ---")

# 元组解包：一行赋多个值
x, y, z = 1, 2, 3
print(f"x={x}, y={y}, z={z}")

# 交换两个变量（Python 特有，不需要临时变量！）
a, b = 10, 20
print(f"交换前：a={a}, b={b}")
a, b = b, a
print(f"交换后：a={a}, b={b}")

# 链式赋值：多个变量指向同一个值
p = q = r = 0
print(f"p={p}, q={q}, r={r}")

# 输出：
# --- 多变量赋值 ---
# x=1, y=2, z=3
# 交换前：a=10, b=20
# 交换后：a=20, b=10
# p=0, q=0, r=0
#
# 【注意】`p = q = r = 0` 三个变量指向同一个整数对象。
#         因为整数不可变，所以不会互相影响。
#         但如果是列表，就要小心了（第 4 章会讲）。































