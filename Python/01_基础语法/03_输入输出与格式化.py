# ==============================================================================
# 知识点 1：print 的两个隐藏参数 —— sep 和 end
# ==============================================================================
#
# print 每次都在干三件事：
#   1. 把每个值用 str() 转成文字
#   2. 用 sep 把相邻的值隔开（默认一个空格 " "）
#   3. 打完所有值后，末尾补上 end（默认一个换行 "\n"）
#
# 【重点】记住这个公式，本知识点就通了：
#       print(a, b, c, sep=?, end=?)
#       输出 = str(a) + sep + str(b) + sep + str(c) + end
# 类比：sep 是「串糖葫芦的签子间距」，end 是「这串吃完后换不换行」。

print("苹果", "香蕉", "橘子")                 # 默认 sep=" "，用空格隔开
print("苹果", "香蕉", "橘子", sep="、")       # 换成顿号
print("2026", "11", "12", sep="-")           # 拼日期：2026-11-12
print("a", "b", sep="")                      # sep 是空串 → 完全贴在一起
print("第一行", "第二行", sep="\n")            # sep 也能是换行符
print(3.14, [1, 2], None, True)              # print 自动 str()，什么类型都能打

# 输出：
# 苹果 香蕉 橘子
# 苹果、香蕉、橘子
# 2026-11-12
# ab
# 第一行
# 第二行
# 3.14 [1, 2] None True

# end 决定「这一行怎么收尾」，默认换行，改成空串就不换行。
print("\n加载中", end="")                      # 不换行
print("...")                                 # 接着上一行继续打印
print("完成")                                 # 这一行正常换行
print("倒计时：", end="")                      # 冒号后面别换行
for i in range(3, 0, -1):                    # 循环第 2 章才讲，这里只看效果
    print(i, end=" ")                        # 每个数字后用空格代替换行
print("发射！")                               # 循环结束才换行
print("第一段", end="\n\n")                   # 结尾换两次 = 两段之间空一行
print("第二段")
print()                                      # 不带参数 = 只输出一个换行

# 输出：
#
# 加载中...
# 完成
# 倒计时：3 2 1 发射！
# 第一段
#
# 第二段

# 【说明】第一行的空行来自 print("\n加载中") 里的 \n；「第一段」下面的空行来自
#        end="\n\n"；最后的 print() 又在末尾补了一个空行。
#
# 用字符串乘法画分隔线，是脚手架代码的常见写法。
print("=" * 30)
print("|" + "菜单".center(16, "-") + "|")      # center(总宽度, 填充字符)
print("=" * 30)

# 输出：
# ==============================
# |-------菜单-------|
# ==============================
#
# 【注意】"菜单" 只有 2 个字符，center 按字符数补 7 个横线；但终端里一个
#        汉字占两格宽，看起来会偏。中文别指望 center 能对齐。
# 【常见错误】用了 end="" 忘了收尾换行，后面的输出全挤在同一行。



























# ==============================================================================
# 知识点 2：input() —— 从键盘拿一行文字
# ==============================================================================
#
# 规则只有两条，但足够坑新手一整晚：
#   1. 它暂停程序，等你敲回车，把「这一行」返回给你（不含换行符）
#   2. 它永远返回 str！哪怕你输入 123，拿到的也是 "123"
# 类比：input() 像快递柜，你塞进去什么形状的东西，取出来都套着同一个袋子。
#
# 【重点】要参与计算，必须自己转型：age = int(input("年龄："))
# 【注意】下面用 io.StringIO 伪造键盘，这样文件能直接运行、不会卡住等你打字。

import io
import sys

_real_stdin = sys.stdin                     # 先存好真实键盘
sys.stdin = io.StringIO("小明\n18\n")        # 换成假键盘：两行输入已就绪

# 真实交互时就这么写（本文件为了能直接运行才用了上面的假键盘）：
# name = input("请输入姓名：")
# age_text = input("请输入年龄：")

name = input()                              # 从假键盘读第一行
age_text = input()                          # 读第二行

sys.stdin = _real_stdin                     # 恢复真实键盘

print(f"name = {name!r}，类型 {type(name).__name__}")
print(f"age_text = {age_text!r}，类型 {type(age_text).__name__}")
print(f"明年 {int(age_text) + 1} 岁")        # 要算数必须先转 int

# 输出：
# name = '小明'，类型 str
# age_text = '18'，类型 str
# 明年 19 岁

# 【常见错误】忘了转换，直接拿字符串做加法。
try:
    age_text + 1                            # str + int 是不允许的
except TypeError as e:
    print(f"报错：{e}")
    print(f"正确做法：int(age_text) + 1 = {int(age_text) + 1}")

# 输出：
# 报错：can only concatenate str (not "int") to str
# 正确做法：int(age_text) + 1 = 19

# input() 一次只读「一整行」，不会自动按空格拆开，要拆就自己 split()。
sys.stdin = io.StringIO("10 20 30\n")
line = input()
sys.stdin = _real_stdin

parts = line.split()                        # 按空白切分，得到字符串列表
nums = [int(p) for p in parts]              # 列表推导式第 4 章才讲，这里看效果
print(f"读到 {line!r}，切分 {parts}，求和 {sum(nums)}")

# 输出：
# 读到 '10 20 30'，切分 ['10', '20', '30']，求和 60

# 【为什么】脚本里要慎用 input()：没有键盘可读时（输入被重定向、程序在后台跑）
#        它会抛 EOFError 直接中断。正经程序用命令行参数或读文件。
sys.stdin = io.StringIO("")                 # 空键盘 = 一读就到文件末尾
try:
    input()
except EOFError:
    print("空输入会抛 EOFError，程序直接中断")
sys.stdin = _real_stdin

# 输出：
# 空输入会抛 EOFError，程序直接中断
























# ==============================================================================
# 知识点 3：f-string —— 现在最推荐的写法
# ==============================================================================
#
# 写法：字符串前面加 f，然后用 {} 把变量或表达式包起来。
#   print(f"我叫{name}，今年{age}岁")
# 类比：字符串变成一张「填空题」试卷，{} 是空格，运行时把答案填进去。
#
# 【重点】三层结构要分清：f"文本 {表达式:格式说明符} 文本"
#                          冒号后面才是格式，前面是值。

name = "小明"
age = 18
height = 1.75

print(f"我叫{name}，今年{age}岁，身高{height}米")     # 最基础：{} 里放变量
print(f"明年{age + 1}岁，名字{len(name)}个字")        # 里面可以写表达式、调函数
print(f"身高保留两位：{height:.2f}，大写：{'python'.upper()}")  # 冒号后是格式符

# 输出：
# 我叫小明，今年18岁，身高1.75米
# 明年19岁，名字2个字
# 身高保留两位：1.75，大写：PYTHON

# 3.8 之后还有调试神器：变量名后面跟 =，会把「名字 + 值」一起打出来。
print(f"{age=}")              # 不用再手写 "age=" 了
print(f"{height = }")         # 等号两边加空格，空格会原样保留

# 输出：
# age=18
# height = 1.75
#
# 【常见错误】忘记写 f 前缀，花括号会原样输出，一点替换都不做。
print("我叫{name}")            # 少了 f
print(f"我叫{name}")           # 有 f 才替换

# 输出：
# 我叫{name}
# 我叫小明

# 引号嵌套：外层双引号、内层单引号，互不打架；字典取值也得换引号。
student = {"name": "小红", "score": 92}
print(f"{student['name']} 考了 {student['score']} 分")

# 输出：
# 小红 考了 92 分


# ==============================================================================
# 知识点 4：format() —— 老一点的通用写法
# ==============================================================================
#
# f-string 之前，大家用 "模板".format(值) 填空，老代码和日志里到处都是。
#   按位置： "{} {}".format(a, b)
#   按编号： "{0} {1}".format(a, b)     编号可重复用
#   按名字： "{x} {y}".format(x=a, y=b) 最清楚
#
# 【重点】它的格式说明符和 f-string 完全一样（f-string 就是从它抄的），
#        冒号后面的 .2f、,、>8 都能直接用。

print("{} 今年 {} 岁".format(name, age))
print("{0} 和 {1}，{0} 又出现了".format("A", "B"))
print("{who} 今年 {how_old} 岁".format(who=name, how_old=age))
print("{:.2f} / {:,} / {:>8}|".format(3.14159, 1234567, "hi"))

# 输出：
# 小明 今年 18 岁
# A 和 B，A 又出现了
# 小明 今年 18 岁
# 3.14 / 1,234,567 /       hi|

# format() 现在真正的用武之地是「模板要复用很多次」：
template = "{name} 的成绩是 {score} 分"
print(template.format(name="小明", score=92))
print(template.format(name="小红", score=88))

# 输出：
# 小明 的成绩是 92 分
# 小红 的成绩是 88 分











































# ==============================================================================
# 知识点 5：% 格式化 —— 从 C 语言带过来的老写法
# ==============================================================================
#
# 写法："格式串" % (值1, 值2)，用 %s %d %f 占位。
#   %s 字符串（什么都能塞）  %d 整数（会截断小数）  %f 浮点（默认 6 位）
#   %.2f 两位小数   %% 一个百分号   %5d / %-5s 宽度 5、右对齐 / 左对齐

print("%s 今年 %d 岁" % (name, age))
print("%s 身高 %.2f 米" % (name, height))
print("及格率：%.1f%%" % 85.6)                # %% 转义成百分号
print("%05.2f" % 3.14159)                    # 总宽 5、补零、保留两位
print("[%-6s] / [%6s]" % ("hi", "hi"))        # 左对齐 / 右对齐
print("%d" % 3.9)                            # %d 会截断，不四舍五入

# 输出：
# 小明 今年 18 岁
# 小明 身高 1.75 米
# 及格率：85.6%
# 03.14
# [hi    ] / [    hi]
# 3
#
# 【常见错误】多个值忘了加括号，写成 "%s %s" % name。
#            这时 name 会被当成一整组参数，数量对不上就报错。
try:
    print("%s 和 %s" % "A")
except TypeError as e:
    print(f"报错：{e}")

# 输出：
# 报错：not enough arguments for format string (got 1)
#
# 【重点】只有一个占位符时可以省略元组：`"%s" % name` 没问题；
#        有两个及以上，必须写 `% (a, b)`。






























# ==============================================================================
# 知识点 6：数字格式化 —— 保留小数、千分位、百分比、对齐
# ==============================================================================
#
# 格式说明符的完整语法（f-string 和 format() 通用）：
#   {值:[填充][对齐][符号][宽度][,][.精度][类型]}
#   对齐：< 左对齐   > 右对齐   ^ 居中     符号：+ 正数也显示 +
#   宽度：不够就补空格，宽度前写 0 表示补 0     ,：千分位
#   类型：d 整数  f 定点小数  e 科学计数  % 百分比  s 字符串  b/o/x 进制
#
# 【重点】格式说明符只影响「怎么显示」，不改变变量本身的值。

pi = 3.14159265
big = 1234567.891
rate = 0.856

print(f"默认 {pi} / 两位 {pi:.2f} / 四位 {pi:.4f}")
print(f"千分位 {big:,.2f} / 整数 {1234567:,}")
print(f"百分比 {rate:.1%} / {rate:.2%} / 超 100% {1.5:.0%}")
print(f"补零 {42:05d} / 带符号 {42:+d} / {-42:+d}")
print(f"右对齐 [{3.14:>10.2f}] / 左对齐 [{3.14:<10.2f}] / 居中 [{3.14:^10.2f}]")
print(f"十六进制 {255:#x} / 二进制 {255:b} / 科学 {12345.678:.2e}")

# 输出：
# 默认 3.14159265 / 两位 3.14 / 四位 3.1416
# 千分位 1,234,567.89 / 整数 1,234,567
# 百分比 85.6% / 85.60% / 超 100% 150%
# 补零 00042 / 带符号 +42 / -42
# 右对齐 [      3.14] / 左对齐 [3.14      ] / 居中 [   3.14   ]
# 十六进制 0xff / 二进制 11111111 / 科学 1.23e+04

# 实战：一张对齐的小票。用英文是为了宽度好算，中文对齐见下面的【注意】。
print("--- 小票 ---")
print(f"{'item':<8}{'price':>8}{'qty':>5}{'subtotal':>10}")
print("-" * 31)
items = [("apple", 3.5, 2), ("milk", 12.0, 1), ("bread", 8.8, 3)]
total = 0.0
for item_name, price, count in items:        # 循环第 2 章才讲，这里看排版效果
    subtotal = price * count
    total += subtotal
    print(f"{item_name:<8}{price:>8.2f}{count:>5}{subtotal:>10.2f}")
print("-" * 31)
print(f"{'total':<8}{'':>8}{'':>5}{total:>10.2f}")

# 输出：
# --- 小票 ---
# item       price  qty  subtotal
# -------------------------------
# apple       3.50    2      7.00
# milk       12.00    1     12.00
# bread       8.80    3     26.40
# -------------------------------
# total                     45.40
#
# 【注意】中文对不齐：len("苹果") 是 2，但终端里显示占 4 格。想排版中文表格，
#        要么全用英文，要么用 wcwidth 之类的库按「显示宽度」算。
#
# 【注意】格式化用的是「四舍六入五成双」，不是严格的四舍五入：
print(f"2.5→{2.5:.0f}，3.5→{3.5:.0f}，round(2.5)→{round(2.5)}")

# 输出：
# 2.5→2，3.5→4，round(2.5)→2
#
# 【为什么】正好在中间的 .5 会「往偶数那边靠」，所以 2.5→2、3.5→4。
#        这在统计上更公平，但和小学数学不同。要严格四舍五入用 decimal 模块。


# ==============================================================================
# 【常见错误速查】
# ==============================================================================
#
# 1. 用了 end="" 忘了收尾换行，后面的输出全挤在一行
# 2. 以为 input() 返回数字，忘了 int() / float() 转换
# 3. 在非交互环境（重定向、后台、某些 IDE）里调 input()，抛 EOFError
# 4. f-string 忘了写 f 前缀，花括号原样输出
# 5. 用 + 拼接字符串和数字：TypeError: can only concatenate str (not "int") to str
# 6. 多值 % 格式化忘了括号，报 not enough arguments for format string
# 7. 以为 .2f 会改变变量：它只改「显示」，pi 本身一点没变
# 8. 用中文做对齐：len() 数的是字符数，不是终端显示宽度


# ==============================================================================
# 【本章小结】
# ==============================================================================
#
# 1. print 的输出 = str(值) + sep 连接 + end 结尾；sep 默认空格，end 默认换行
# 2. sep 可以是任意字符串；end="" 用来不换行地续写
# 3. input() 永远返回 str，要算数必须 int() / float()
# 4. input() 一次读一行，要拆分用 split()；读不到数据会抛 EOFError
# 5. f-string 是首选：f"文本{表达式:格式}"，{} 里能放任意表达式，{x=} 能调试
# 6. format() 适合「模板复用」，按位置 / 编号 / 名字填都行
# 7. % 是 C 时代的老写法，认识即可；多值必须写元组
# 8. 数字格式化：.2f 保留小数、, 千分位、.1% 百分比、05d 补零、>10 对齐
# 9. 格式化只改变显示，不改变变量的值
# 10. 四舍六入五成双：2.5 格式化后是 2，不是 3
# 11. 新代码一律用 f-string；模板要复用时用 format()；% 只用来读老代码












